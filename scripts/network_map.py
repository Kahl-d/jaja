#!/usr/bin/env python3
"""network_map.py - the whole network, classified. Read-only on records.

Sources (each optional; a silent record reads "unknown", missing is not empty):
  - the newest parsed LinkedIn export, state/harvest/linkedin-<date>.jsonl (scripts/linkedin_export.py parse):
    its `connection` rows (company, position, connected on) and `person` rows (message and invitation dates)
  - prospects/*.md (company, company_slug, title or headline, role, linkedin_url, x_handle, last message dates; the
    body for a school), with touches/*.jsonl dates per prospect
  - the Scout's hiring posters, the `PERSON` lines of hub/lanes/HUNT.md (connected or not)
  - X following, from state/x/following.json (written by `python3 scripts/x_api.py following`); while X credits are
    depleted (x_api.credit_state) it is skipped with the date
Every person gets: company and its target tier (targets/companies.yaml; "untracked" when the company is not on the
watchlist), role kind from the title (recruiter, founder, hiring-manager, ai-engineer, engineer, other, unknown),
school (from the configured identity.schools list, else unknown), warmth (warm: a message in the last
WARM_DAYS; dormant: older; none) and the hiring post seen. An X bio is untrusted text: it only feeds the role-kind pattern, never a company.

Writes graph/NETWORK.md (GENERATED, like build_graph): referral paths per hub/NEXT-UP.md company, recruiters, hiring
posters, dormant warm ties worth reviving, counts; and state/network/network-map.json, the rows network_plan.py reads
({name, company, company_slug, linkedin_url, why, connected} plus the classification). No email address and no
message text is ever written. The MCP tool network_for(company or role) reads build() live.

CLI:  python3 scripts/network_map.py [--root R] [--today YYYY-MM-DD] [--dry-run]
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
from collections import Counter
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import agency_config as cfg  # noqa: E402
import js_comms_util as cu  # noqa: E402
from fetch_ats import load_companies  # noqa: E402
from js_common import JS_ROOT, cli_date, iter_records, iter_touches, normalize_company, read_jsonl, slugify, today  # noqa: E402

SELF = "scripts/network_map.py"
HEADER_MD = f"<!-- GENERATED by {SELF} from the job-search records; do not edit -->"
WARM_DAYS = 90
LIST_CAP = 60
KINDS = ("recruiter", "founder", "hiring-manager", "ai-engineer", "engineer", "other", "unknown")
USEFUL = ("recruiter", "founder", "hiring-manager", "ai-engineer")
TIER_RANK = {"dream": 0, "strong": 1, "good": 2, "fallback": 3, "untracked": 4, "unknown": 5}
RECRUITER = re.compile(r"recruit|sourc(?:er|ing)|talent (?:acquisition|partner)|headhunt", re.I)
FOUNDER = re.compile(r"\bco-?founder\b|\bfounder\b|\bcofounder\b", re.I)
MANAGER = re.compile(r"\bmanager\b|\bhead of\b|\bdirector\b|\bvp\b|vice president|\blead\b", re.I)
ENGINEER = re.compile(r"engineer|developer|scientist|researcher|technical staff|\bmts\b", re.I)
AI_WORDS = re.compile(r"\b(?:ai|ml|machine learning|llms?|agents?|evals?|evaluations?|applied|nlp|genai)\b", re.I)
ROLE_FIELD = {"recruiter": "recruiter", "founder": "founder", "hiring_manager": "hiring-manager",
              "hiring-manager": "hiring-manager", "engineer": "engineer"}
PERSON_LINE = re.compile(r"^PERSON (?P<names>[^·]+?) · (?P<company>[^·(]+?)\s*(?:\((?P<role>[^)]*)\))? · "
                         r"(?P<post>[^·]+?)(?: · |$)")


def _cell(value: Any) -> str:
    return re.sub(r"\s+", " ", str(value if value is not None else "")).replace("|", "/").strip()


def role_kind(title: str | None, role_field: str | None = None) -> str:
    t = str(title or "").strip()
    if t:
        if RECRUITER.search(t):
            return "recruiter"
        if FOUNDER.search(t):
            return "founder"
        if MANAGER.search(t):
            return "hiring-manager"
        if ENGINEER.search(t):
            return "ai-engineer" if AI_WORDS.search(t) else "engineer"
        return "other"
    return ROLE_FIELD.get(str(role_field or "").strip().lower(), "unknown")


def schools() -> list[tuple[str, re.Pattern[str]]]:
    """The schools to recognise (config identity.schools: a list of {name, pattern}); none by default."""
    out = []
    for entry in cfg.get("identity.schools", []) or []:
        if isinstance(entry, dict) and entry.get("name") and entry.get("pattern"):
            out.append((str(entry["name"]), re.compile(str(entry["pattern"]), re.I)))
    return out


def school_of(*texts: Any) -> str:
    blob = " ".join(str(t or "") for t in texts)
    for name, rx in schools():
        if rx.search(blob):
            return name
    return "unknown"


def _ts(value: Any) -> datetime | None:
    if not value:
        return None
    try:
        dt = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    except ValueError:
        return None
    return dt if dt.tzinfo else dt.replace(tzinfo=timezone.utc)


def _latest(*values: Any) -> str | None:
    stamps = [(_ts(v), str(v)) for v in values if _ts(v)]
    return max(stamps)[1] if stamps else None


# --------------------------------------------------------------------------- sources
def latest_export(root: Path) -> Path | None:
    files = sorted(p for p in (root / "state" / "harvest").glob("linkedin-*.jsonl") if ".classified" not in p.name) \
        if (root / "state" / "harvest").is_dir() else []
    return files[-1] if files else None


def next_up(root: Path) -> list[dict[str, str]]:
    try:
        lines = (root / "hub" / "NEXT-UP.md").read_text(encoding="utf-8").splitlines()
    except OSError:
        return []
    out, seen = [], set()
    for ln in lines:
        m = re.match(r"^\|\s*(\d+[a-z]?)\s*\|\s*([^|]+?)\s*·\s*([^|]+?)\s*\|", ln)
        if not m:
            continue
        company = re.sub(r"\s*\([^)]*\)", "", m.group(2)).strip()
        key = normalize_company(company)
        if key and key not in seen:
            seen.add(key)
            out.append({"rank": m.group(1), "company": company, "role": m.group(3).strip(), "key": key})
    return out


def x_state(root: Path) -> dict[str, Any]:
    path = root / "state" / "x" / "following.json"
    if path.is_file():
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError):
            data = None
        if isinstance(data, dict):
            users = [u for u in data.get("users") or [] if isinstance(u, dict)]
            return {"state": "read", "users": users, "note": f"read {len(users)} accounts "
                    f"(fetched {data.get('fetched_at') or 'unknown'})"}
    try:
        import x_api
        credits = x_api.credit_state(root)
    except Exception:                                   # x_api unavailable: say so, never guess
        credits = {"state": "unknown", "last_402": None}
    if credits.get("state") == "depleted":
        at = str((credits.get("last_402") or {}).get("at") or "")[:10]
        return {"state": "skipped", "users": [], "note": f"skipped: X credits depleted since {at}; "
                "run python3 scripts/x_api.py following after credits"}
    return {"state": "absent", "users": [], "note": "not read yet: python3 scripts/x_api.py following"}


# --------------------------------------------------------------------------- build
def build(root: Path, day: date) -> dict[str, Any]:
    root = Path(root)
    companies = load_companies(root)
    by_name = {normalize_company(c["name"]): c for c in companies}
    by_slug = {str(c.get("slug")): c for c in companies}
    people: dict[str, dict[str, Any]] = {}
    alias: dict[str, str] = {}

    def get(name: str, url: str | None) -> dict[str, Any]:
        url = cu.normalize_linkedin_url(url) if url else ""
        nkey = f"name:{cu.normalize_person_name(name)}"
        key = alias.get(url) if url else None
        key = key or alias.get(nkey) or url or nkey
        if key not in people:
            people[key] = {"name": cu.display_name(name) or name, "company": None, "company_slug": None,
                           "title": None, "role_field": None, "school_text": [], "linkedin_url": url or None,
                           "x_handle": None, "prospect": None, "connected": False, "connected_on": None,
                           "last_message": None, "hiring_post": None, "sources": []}
        p = people[key]
        if url:
            alias[url] = key
            p["linkedin_url"] = p["linkedin_url"] or url
        alias[nkey] = key
        return p

    def src(p: dict[str, Any], s: str) -> None:
        if s not in p["sources"]:
            p["sources"].append(s)

    export = latest_export(root)
    li = {"file": str(export.relative_to(root)) if export else None, "connections": 0, "people": 0}
    if export:
        for row in read_jsonl(export):
            kind = row.get("type")
            if kind == "connection":
                li["connections"] += 1
                p = get(row.get("name") or "", row.get("linkedin_url"))
                src(p, "linkedin-connection")
                p["connected"] = True
                p["connected_on"] = row.get("connected_on")
                p["company"] = p["company"] or row.get("company")
                p["title"] = p["title"] or row.get("position")
            elif kind == "person":
                li["people"] += 1
                p = get(row.get("name") or "", row.get("linkedin_url"))
                src(p, "linkedin-messages")
                p["company"] = p["company"] or row.get("company")
                p["title"] = p["title"] or row.get("position")
                p["last_message"] = _latest(p["last_message"], row.get("last_inbound_at"), row.get("last_outbound_at"))
        li["note"] = f"{li['file']}: {li['connections']} connections, {li['people']} people with messages or notes"
    else:
        li["note"] = ("no parsed LinkedIn export (state/harvest/linkedin-<date>.jsonl); request it, then "
                      "python3 scripts/linkedin_export.py parse <zip>")

    touch_last: dict[str, str] = {}
    for t in iter_touches(root):
        pid = t.get("prospect")
        if pid:
            touch_last[pid] = _latest(touch_last.get(pid), t.get("at")) or touch_last.get(pid)
    n_prospects = 0
    for path, rec, body in iter_records(root / "prospects"):
        if not isinstance(rec, dict) or not rec.get("name"):
            continue
        n_prospects += 1
        p = get(str(rec["name"]), rec.get("linkedin_url"))
        src(p, "prospect")
        p["prospect"] = rec.get("id") or path.stem
        p["company"] = rec.get("company") or p["company"]
        p["company_slug"] = rec.get("company_slug") or p["company_slug"]
        p["title"] = rec.get("title") or p["title"] or rec.get("headline")
        p["role_field"] = rec.get("role")
        p["x_handle"] = rec.get("x_handle") or p["x_handle"]
        p["school_text"] += [rec.get("headline"), rec.get("title"), body]
        p["last_message"] = _latest(p["last_message"], rec.get("last_inbound_at"), rec.get("last_outbound_at"),
                                    touch_last.get(str(p["prospect"])))

    n_posters = 0
    try:
        hunt = (root / "hub" / "lanes" / "HUNT.md").read_text(encoding="utf-8").splitlines()
    except OSError:
        hunt = []
    for ln in hunt:
        m = PERSON_LINE.match(ln.strip())
        if not m:
            continue
        for name in re.split(r"\s+and\s+|,\s*", m.group("names").strip()):
            if not name.strip():
                continue
            n_posters += 1
            p = get(name.strip(), None)
            src(p, "hunt-scout")
            p["hiring_post"] = p["hiring_post"] or m.group("post").strip()
            p["company"] = p["company"] or m.group("company").strip()
            p["title"] = p["title"] or (m.group("role") or None)

    xs = x_state(root)
    for u in xs["users"]:
        p = get(str(u.get("name") or u.get("username") or ""), None)
        src(p, "x-following")
        p["x_handle"] = p["x_handle"] or u.get("username")
        p["title"] = p["title"] or u.get("description")        # untrusted: role-kind pattern only

    nu = next_up(root)
    nu_by_key = {r["key"]: r for r in nu}
    rows = []
    cutoff = datetime(day.year, day.month, day.day, tzinfo=timezone.utc) - timedelta(days=WARM_DAYS)
    for p in people.values():
        company = (p["company"] or "").strip()
        match = by_slug.get(str(p["company_slug"])) if p["company_slug"] else None
        match = match or (by_name.get(normalize_company(company)) if company else None)
        tier = str(match.get("tier") or "untracked") if match else ("untracked" if company else "unknown")
        slug = (match or {}).get("slug") or p["company_slug"] or (slugify(company) if company else None)
        last = _ts(p["last_message"])
        warmth = "none" if not last else ("warm" if last >= cutoff else "dormant")
        x_only = p["sources"] == ["x-following"]
        kind = role_kind(p["title"], p["role_field"])
        school = school_of(*p["school_text"])
        nu_row = nu_by_key.get(normalize_company(company)) if company else None
        why = []
        if tier in ("dream", "strong", "good", "fallback"):
            why.append(f"{tier}-tier {company}")
        if nu_row:
            why.append(f"NEXT-UP #{nu_row['rank']} {nu_row['company']}")
        if kind in USEFUL:
            why.append(kind)
        if p["hiring_post"]:
            why.append(f"hiring post {p['hiring_post']}")
        if school != "unknown":
            why.append(f"alum ({school})")
        if warmth == "warm":
            why.append(f"warm tie (last message {str(p['last_message'])[:10]})")
        elif warmth == "dormant":
            why.append(f"dormant tie since {str(p['last_message'])[:10]}")
        rows.append({"name": p["name"], "company": company or "unknown", "company_slug": slug,
                     "linkedin_url": p["linkedin_url"], "why": "; ".join(why), "connected": bool(p["connected"]),
                     "tier": tier, "kind": kind, "title": None if x_only else p["title"], "school": school,
                     "warmth": warmth, "last_message": p["last_message"], "hiring_post": p["hiring_post"],
                     "x_handle": p["x_handle"], "prospect": p["prospect"], "connected_on": p["connected_on"],
                     "next_up": nu_row["rank"] if nu_row else None, "sources": p["sources"]})
    rows.sort(key=lambda r: (TIER_RANK.get(r["tier"], 9), r["name"].lower()))
    counts = {"people": len(rows), "connected": sum(r["connected"] for r in rows),
              "kind": dict(Counter(r["kind"] for r in rows)), "tier": dict(Counter(r["tier"] for r in rows)),
              "school": dict(Counter(r["school"] for r in rows)), "warmth": dict(Counter(r["warmth"] for r in rows)),
              "prospects": n_prospects, "hiring_posters": n_posters}
    return {"date": day.isoformat(), "people": rows, "counts": counts, "next_up": nu, "linkedin": li,
            "x": {"state": xs["state"], "note": xs["note"], "accounts": len(xs["users"])}}


def for_query(net: dict[str, Any], query: str) -> list[dict[str, Any]]:
    q = str(query or "").strip()
    if not q:
        return []
    if q.lower() in KINDS:
        return [r for r in net["people"] if r["kind"] == q.lower()]
    key = normalize_company(q)
    return [r for r in net["people"] if r["company"] != "unknown" and
            (normalize_company(r["company"]) == key or r["company_slug"] == slugify(q))]


# --------------------------------------------------------------------------- render
def _line(r: dict[str, Any]) -> str:
    bits = [r["kind"], _cell(r["title"]) if r["title"] else None, f"{r['company']} ({r['tier']})",
            f"{r['warmth']}" + (f" {str(r['last_message'])[:10]}" if r["last_message"] else ""),
            None if r["school"] == "unknown" else r["school"], "connected" if r["connected"] else "not connected",
            "/".join(r["sources"])]
    return f"- {_cell(r['name'])} · " + " · ".join(b for b in bits if b)


def _capped(rows: list[dict[str, Any]], empty: str) -> list[str]:
    if not rows:
        return [f"- {empty}"]
    out = [_line(r) for r in rows[:LIST_CAP]]
    if len(rows) > LIST_CAP:
        out.append(f"- and {len(rows) - LIST_CAP} more (the MCP tool network_for lists them)")
    return out


def render(net: dict[str, Any]) -> str:
    rows, c = net["people"], net["counts"]
    lines = [HEADER_MD, "# Network", "",
             f"Built for {net['date']} by `scripts/network_map.py` from the records; never hand-edit, re-run it. "
             "`unknown` means no record holds the value. No email address or message text appears here.", "",
             f"- LinkedIn export: {net['linkedin']['note']}",
             f"- Prospects: {c['prospects']}; Scout hiring posters: {c['hiring_posters']}",
             f"- X following: {net['x']['note']}", "",
             "## Referral paths per NEXT-UP company", ""]
    for nu in net["next_up"]:
        lines.append(f"### {_cell(nu['company'])} (NEXT-UP #{nu['rank']} · {_cell(nu['role'])})")
        at = [r for r in rows if r["company"] != "unknown" and normalize_company(r["company"]) == nu["key"]]
        at.sort(key=lambda r: (0 if r["warmth"] == "warm" else 1, USEFUL.index(r["kind"]) if r["kind"] in USEFUL else 9))
        lines += _capped(at, "nobody in the network yet (people_traces.py finds the team; network_plan suggests)")
        lines.append("")
    if not net["next_up"]:
        lines += ["- hub/NEXT-UP.md lists no company", ""]
    lines += ["## Recruiters", ""] + _capped([r for r in rows if r["kind"] == "recruiter"], "none recorded") + [""]
    lines += ["## Hiring posters", ""]
    posters = [r for r in rows if r["hiring_post"]]
    lines += [f"{_line(r)} · post: {_cell(r['hiring_post'])}" for r in posters[:LIST_CAP]] or ["- none recorded"]
    lines.append("")
    dormant = [r for r in rows if r["warmth"] == "dormant" and (r["kind"] in USEFUL or r["tier"] in TIER_RANK and
                                                                 TIER_RANK[r["tier"]] <= 3)]
    dormant.sort(key=lambda r: (TIER_RANK.get(r["tier"], 9), str(r["last_message"] or "")), reverse=False)
    lines += ["## Dormant warm ties (worth reviving)", ""] + _capped(dormant, "none") + [""]
    lines += ["## Counts", "",
              f"- people {c['people']}, connected on LinkedIn {c['connected']}",
              "- by role kind: " + ", ".join(f"{k} {c['kind'].get(k, 0)}" for k in KINDS),
              "- by tier: " + ", ".join(f"{k} {v}" for k, v in sorted(c["tier"].items(), key=lambda kv: TIER_RANK.get(kv[0], 9))),
              "- by school: " + ", ".join(f"{k} {v}" for k, v in sorted(c["school"].items())),
              "- by warmth: " + ", ".join(f"{k} {v}" for k, v in sorted(c["warmth"].items()))]
    return "\n".join(lines) + "\n"


def _replace_file(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name("." + path.name + ".tmp")
    tmp.write_text(text, encoding="utf-8")
    os.replace(tmp, path)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", type=Path, default=JS_ROOT)
    ap.add_argument("--today", type=cli_date)
    ap.add_argument("--dry-run", action="store_true")
    args = ap.parse_args(argv)
    root = Path(args.root)
    net = build(root, args.today or today())
    c = net["counts"]
    print(f"network_map: {c['people']} people ({c['connected']} connected), {len(net['next_up'])} NEXT-UP companies, "
          f"X {net['x']['state']}" + ("; dry run, nothing written" if args.dry_run else ""))
    if not args.dry_run:
        _replace_file(root / "graph" / "NETWORK.md", render(net))
        _replace_file(root / "state" / "network" / "network-map.json",
                json.dumps({"generated_at": net["date"], "source": SELF, "people": net["people"]}, indent=1,
                           ensure_ascii=False) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
