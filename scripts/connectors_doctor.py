def check_linkedin(js_root: Path, now: datetime) -> dict[str, Any]:
    name = "linkedin-export"
    folder = js_root / "profile" / "_inbox" / "linkedin-export"
    drops = [p for p in folder.iterdir() if not p.name.startswith(".") and (p.is_dir() or p.suffix == ".zip")] \
        if folder.is_dir() else []
    if not drops:
        return _record(name, "export", "amber", "no LinkedIn data export yet",
                       "request it (Settings > Data privacy > Get a copy of your data) and drop the zip in "
                       "profile/_inbox/linkedin-export/ (SETUP-CONNECTORS.md step 4)", folder_present=folder.is_dir())

    def when(p: Path) -> date:
        return _date_in_name(p.name) or datetime.fromtimestamp(p.stat().st_mtime, tz=timezone.utc).date()

    latest = max(drops, key=lambda p: (when(p), p.name))
    exported = when(latest)
    parsed = sorted((_date_in_name(p.name) for p in (js_root / "state" / "harvest").glob("linkedin-*.json")
                     if _date_in_name(p.name)), reverse=True)
    last_parse = parsed[0] if parsed else None
    checks = {"latest_export": latest.name, "latest_export_date": exported.isoformat(),
              "last_parsed": last_parse.isoformat() if last_parse else None, "drops": len(drops)}
    today = cu.local_date(now)
    if last_parse is None or last_parse < exported:
        return _record(name, "export", "amber", f"export from {exported.isoformat()} not parsed yet",
                       f"python3 scripts/linkedin_export.py parse profile/_inbox/linkedin-export/{latest.name}",
                       **checks)
    if (today - exported).days > LINKEDIN_STALE_DAYS:
        return _record(name, "export", "amber", f"latest export is from {exported.isoformat()}",
                       "request a fresh export (it arrives by email in about a day)", **checks)
    return _record(name, "export", "green", f"export from {exported.isoformat()}, parsed {last_parse.isoformat()}",
                   None, **checks)


def check_adzuna(env: Mapping[str, str]) -> dict[str, Any]:
    keys = {k: "present" if str(env.get(k) or "").strip() else "missing" for k in ("ADZUNA_APP_ID", "ADZUNA_APP_KEY")}
    if all(v == "present" for v in keys.values()):
        return _record("adzuna", "api-key", "green", "both Adzuna keys are set in the environment", None, **keys)
    missing = ", ".join(k for k, v in keys.items() if v == "missing")
    return _record("adzuna", "api-key", "amber", f"{missing} not set; the Adzuna source is skipped (optional)",
                   "create a free key at developer.adzuna.com and export both variables (SETUP-CONNECTORS.md step 5)",
                   **keys)


def firecrawl_keychain_has() -> bool:
    """Whether the Keychain item exists (asked without reading the value); a seam the tests replace."""
    return ws.keychain_has()


def check_firecrawl(js_root: Path, os_root: Path, env: Mapping[str, str], now: datetime) -> dict[str, Any]:
    """Firecrawl (scripts/web_snapshot.py): the key's place (environment or Keychain, never its value) and the
    credits used against company/policies/budgets.yaml. Optional: amber until the owner adds the key."""
    where = "environment" if str(env.get(ws.ENV_KEY) or "").strip() else "keychain" if firecrawl_keychain_has() else "none"
    day = jc.dept_day(now).isoformat()
    spent = ws.used(js_root, day)
    try:
        cap = ws.caps(os_root)
    except ws.Refused:
        return _record("firecrawl", "api-key", "amber", "no Firecrawl budget line in company/policies/budgets.yaml; "
                       "web_snapshot.py refuses every call", "add `connectors: firecrawl:` caps", key=where)
    checks = {"key": where, "credits_month": f"{spent['month']} of {cap['month']}",
              "credits_today": f"{spent['day']} of {cap['day']}"}
    if where == "none":
        return _record("firecrawl", "api-key", "amber", "no Firecrawl key; web snapshots are off (optional)",
                       "add the key to the Keychain (SETUP-CONNECTORS.md section 10)", **checks)
    if spent["month"] >= 0.9 * cap["month"]:
        return _record("firecrawl", "api-key", "amber", f"{spent['month']} of {cap['month']} Firecrawl credits used "
                       "this month; calls stop at the cap", "wait for the month to turn, or raise the cap",
                       **checks)
    return _record("firecrawl", "api-key", "green", f"key in the {where}; {spent['month']} of {cap['month']} credits "
                   "used this month", None, **checks)


def default_probe() -> dict[str, Any]:
    """Launch the server the way the engines do (uv) and run its stdio selftest."""
    mcp_dir = jc.CODE_ROOT / "mcp"
    uv = shutil.which("uv")
    if not uv:
        return {"ok": False, "error": "uv not found on PATH"}
    try:
        proc = subprocess.run([uv, "run", "--directory", str(mcp_dir), "job-search-mcp", "selftest"],
                              capture_output=True, text=True, timeout=MCP_TIMEOUT, stdin=subprocess.DEVNULL)
    except subprocess.TimeoutExpired:
        return {"ok": False, "error": f"selftest timed out after {MCP_TIMEOUT} s"}
    try:
        result = json.loads((proc.stdout or "").strip().splitlines()[-1])
    except (IndexError, json.JSONDecodeError):
        tail = (proc.stderr or "").strip().splitlines()[-1:] or ["no output"]
        return {"ok": False, "error": f"exit {proc.returncode}: {tail[0][:200]}"}
    return result


def check_mcp(os_root: Path, probe: Callable[[], dict[str, Any]] | None) -> dict[str, Any]:
    name = "mcp-job-search"
    try:
        registered = any("job-search" in (json.loads(f.read_text(encoding="utf-8")).get("mcpServers") or {})
                         for f in [(os_root / ".mcp.json") if (os_root / ".mcp.json").is_file() else (jc.CODE_ROOT / ".mcp.json")] if f.is_file())
    except (OSError, json.JSONDecodeError):
        registered = False
    if not registered:
        return _record(name, "mcp", "red", "job-search is not in .mcp.json; engines cannot start it",
                       "add it to .mcp.json and run python3 scripts/kernel/sync.py", registered=False)
    if probe is None:
        return _record(name, "mcp", "skipped", "registered; launch not checked (--skip-mcp)", None, registered=True)
    result = probe() or {}
    tools = result.get("tools") or []
    if not result.get("ok"):
        why = result.get("error") or f"missing tools: {', '.join(result.get('missing') or [])}"
        return _record(name, "mcp", "red", f"server did not start cleanly: {why}"[:240],
                       "cd mcp && uv sync && uv run pytest; then rerun this doctor", registered=True, tools=len(tools))
    return _record(name, "mcp", "green", f"starts over stdio and lists {len(tools)} tools", None, registered=True,
                   tools=len(tools))


