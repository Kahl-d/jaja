def check_hunt(js_root: Path, now: datetime) -> list[dict[str, Any]]:
    """The hunt's two health numbers from the latest review (scripts/hunt_review.py)."""
    path = js_root / "state" / "hunt" / "review-latest.json"
    run_cmd = "python3 scripts/hunt_review.py (routine js-hunt-review, on the owner's word)"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return [_record("hunt-review", "hunt", "amber", "no fresh-roles review yet", run_cmd),
                _record("hunt-freshness", "hunt", "amber", "no freshness measurement yet", run_cmd)]
    at = datetime.fromisoformat(str(data.get("now") or "1970-01-01T00:00:00Z").replace("Z", "+00:00"))
    age_days = (now - at).total_seconds() / 86400
    cov = data.get("coverage") or {}
    share = cov.get("share")
    checks = {"reviewed_at": data.get("now"), "coverage": cov, "listed": (data.get("counts") or {}).get("listed")}
    if age_days > 2:
        review = _record("hunt-review", "hunt", "amber", f"the last review is {age_days:.0f} days old", run_cmd, **checks)
    elif share is not None and share < 0.95:
        review = _record("hunt-review", "hunt", "amber", f"only {cov.get('scored')} of {cov.get('open')} open jobs "
                         "carry a triage score", "python3 scripts/hunt_score.py", **checks)
    else:
        review = _record("hunt-review", "hunt", "green", f"reviewed {data.get('now')}; {cov.get('scored')} of "
                         f"{cov.get('open')} open jobs scored", None, **checks)
    f = data.get("freshness") or {}
    med, target = f.get("median_hours"), f.get("target_hours", 3)
    if med is None:
        fresh = _record("hunt-freshness", "hunt", "amber", "no dated finds measured yet", run_cmd, **f)
    elif med > target:
        fresh = _record("hunt-freshness", "hunt", "amber", f"median {med} h from posting to first sight (target {target} h;"
                        f" {f.get('within_target')} of {f.get('measured')} within)", _boards_advice(js_root),
                        **f)
    else:
        fresh = _record("hunt-freshness", "hunt", "green", f"median {med} h from posting to first sight (target {target} h)",
                        None, **f)
    return [review, fresh]


X_SCOPES = {"read": ("tweet.read", "users.read", "offline.access"),
            "write": ("tweet.read", "users.read", "tweet.write", "follows.write", "dm.read", "dm.write", "offline.access")}


BOARD_CONNECTORS = {"indeed-connector": "Indeed", "ziprecruiter-connector": "ZipRecruiter", "dice-connector": "Dice"}
CONNECTOR_FRESH_DAYS = 7
_HEAD_FIELD = re.compile(r"^(source|first_seen):\s*['\"]?([^'\"\n]*)", re.M)


def _connector_finds(js_root: Path) -> dict[str, datetime]:
    """source -> the newest first_seen of a job recorded through that Claude connector (jobs_manual.py add --source);
    only each record's front matter is read."""
    newest: dict[str, datetime] = {}
    for path in (js_root / "jobs").glob("*.md") if (js_root / "jobs").is_dir() else []:
        try:
            with path.open(encoding="utf-8") as fh:
                head = fh.read(4096)
        except OSError:
            continue
        front = head.split("\n---", 1)[0] if head.startswith("---") else ""
        fields = dict(_HEAD_FIELD.findall(front))
        source = fields.get("source", "").strip()
        if source not in BOARD_CONNECTORS:
            continue
        try:
            seen = datetime.fromisoformat(fields.get("first_seen", "").strip().replace("Z", "+00:00"))
        except ValueError:
            continue
        if seen.tzinfo is None:
            seen = seen.replace(tzinfo=timezone.utc)
        if source not in newest or seen > newest[source]:
            newest[source] = seen
    return newest


def check_board_connectors(js_root: Path, now: datetime) -> list[dict[str, Any]]:
    """One row per Claude board connector (Indeed, ZipRecruiter, Dice), from the newest job recorded through it:
    green within CONNECTOR_FRESH_DAYS, amber older, and amber when none was ever recorded (a connector not added yet is
    a missing optional piece, not breakage)."""
    finds = _connector_finds(js_root)
    out = []
    for source, board in BOARD_CONNECTORS.items():
        seen = finds.get(source)
        if seen is None:
            out.append(_record(source, "claude-connector", "amber", f"no job ever recorded through the {board} connector",
                               f"the owner adds {board} in Claude Settings, Connectors; then the hunt runs the "
                               "connector-search skill", last_find=None))
            continue
        age = (now - seen).total_seconds() / 86400
        if age > CONNECTOR_FRESH_DAYS:
            out.append(_record(source, "claude-connector", "amber", f"last {board} connector find {age:.0f} days ago",
                               "run the connector-search skill in a session with the connector on",
                               last_find=seen.isoformat()))
        else:
            out.append(_record(source, "claude-connector", "green", f"last {board} connector find "
                               f"{seen.date().isoformat()}", None, last_find=seen.isoformat()))
    return out


def check_x_credits(js_root: Path) -> dict[str, Any] | None:
    """Scout lesson L-6800106c: red from X's last 402 (credits depleted) until a successful call; None before any call.
    Read from state/x/usage.jsonl through x_api.credit_state (no token, no network)."""
    import x_api
    credits = x_api.credit_state(js_root)
    last = credits["last_402"]
    if credits["state"] == "unknown":
        return None
    if credits["state"] == "depleted":
        return _record("x-credits", "x-api", "red", f"X answered 402 (credits depleted) on {str(last['at'])[:10]} "
                       f"({last['endpoint']}); red until a successful call",
                       "add credits in the X developer console; the next X read clears this", credit_state=credits["state"], last_402=last, last_ok=credits["last_ok"])
    seen = f"; last 402 on {str(last['at'])[:10]}" if last else ""
    return _record("x-credits", "x-api", "green", f"last X call succeeded {str(credits['last_ok'])[:10]}{seen}", None,
                   credit_state=credits["state"], last_402=last, last_ok=credits["last_ok"])


def check_x(config_dir: Path) -> list[dict[str, Any]]:
    """The X app's Client ID file and both X tokens (x_api.py); names, modes and scopes only, never a value."""
    out: list[dict[str, Any]] = []
    client = config_dir / "x_client.json"
    if not client.is_file():
        out.append(_record("x-client", "local-oauth", "amber", "no X app Client ID; X reads and actions are unavailable",
                           "create the X app and save its Client ID (SETUP-CONNECTORS.md section 14)",
                           path=_tilde(client), present=False))
    elif stat.S_IMODE(os.stat(client).st_mode) != 0o600:
        out.append(_record("x-client", "local-oauth", "red", "x_client.json must be chmod 600",
                           f"chmod 600 {_tilde(client)}", path=_tilde(client), present=True))
    else:
        out.append(_record("x-client", "local-oauth", "green", "X app Client ID present (a public client, no secret)",
                           None, path=_tilde(client), present=True))
    for kind in ("read", "write"):
        name, login = f"x-{kind}-token", "python3 scripts/x_api.py login" + (" --write" if kind == "write" else "")
        path = config_dir / f"x_token_{kind}.json"
        if not path.is_file():
            out.append(_record(name, "local-oauth", "amber", f"no X {kind} token", f"{login} (SETUP-CONNECTORS.md "
                               "section 14)", path=_tilde(path), present=False))
            continue
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, ValueError) as exc:
            out.append(_record(name, "local-oauth", "red", f"token file unreadable ({type(exc).__name__})",
                               f"delete it and run: {login}", path=_tilde(path)))
            continue
        scopes = sorted(data.get("scopes") or [])
        checks = {"path": _tilde(path), "present": True, "mode": oct(stat.S_IMODE(os.stat(path).st_mode)),
                  "scopes": scopes, "username": data.get("username")}
        missing = [x for x in X_SCOPES[kind] if x not in scopes]
        if checks["mode"] != "0o600":
            out.append(_record(name, "local-oauth", "red", f"token file mode {checks['mode']}, must be 600",
                               f"chmod 600 {checks['path']}", **checks))
        elif kind == "read" and any(x.endswith(".write") for x in scopes):
            out.append(_record(name, "local-oauth", "red", "the X read token carries write scopes",
                               f"delete {checks['path']} and run: {login}", **checks))
        elif missing or not data.get("refresh_token"):
            out.append(_record(name, "local-oauth", "red", f"X {kind} token lacks {missing or ['a refresh token']}",
                               f"run: {login}", **checks))
        else:
            out.append(_record(name, "local-oauth", "green", f"X {kind} token for @{data.get('username')} (refreshes "
                               "itself; log in again only if X revokes it)", None, **checks))
    return out


LEGACY_TOKEN = "gmail_token.json"     # the pre-split single token; nothing loads it any more


def check_legacy_token(config_dir: Path) -> dict[str, Any] | None:
    """Flag the pre-split token: scripts ignore it, but it may still grant gmail.compose (which can send)."""
    path = config_dir / LEGACY_TOKEN
    if not path.is_file():
        return None
    mode = _mode(path)
    try:
        scopes = json.loads(path.read_text(encoding="utf-8")).get("scopes")
    except (json.JSONDecodeError, OSError, AttributeError):
        scopes = None
    scopes = [scopes] if isinstance(scopes, str) else [str(x) for x in scopes or []]
    checks = {"path": _tilde(path), "mode": oct(mode), "scopes": scopes}
    if mode != 0o600:
        return _record("gmail-legacy-token", "local-oauth", "red", f"legacy token file mode {oct(mode)}, must be 600",
                       f"delete it: rm {checks['path']}", **checks)
    return _record("gmail-legacy-token", "local-oauth", "amber",
                   "legacy single Gmail token (before the read/compose split); no script uses it and it may grant "
                   "gmail.compose", f"delete it: rm {checks['path']}", **checks)


def check_calendar_token(config_dir: Path, now: datetime) -> dict[str, Any]:
    name, login = "calendar-token", "python3 scripts/gmail_auth.py login --calendar"
    st, err = _token("calendar", config_dir, now)
    if err:
        return _record(name, "local-oauth", "red", err, f"delete the file and log in again: {login}")
    if not st["exists"]:
        return _record(name, "local-oauth", "amber", "no calendar token; the agenda, holds and invites are unavailable (optional)",
                       f"{login} when the calendar is wanted (SETUP-CONNECTORS.md step 2)", path=_tilde(st["path"]),
                       present=False)
    bad = _token_basics(name, "calendar", st, login)
    if bad:
        return bad
    checks = {"path": _tilde(st["path"]), "present": True, "mode": st["mode"], "scopes": st["scopes"],
              "reauth_due": st["reauth_due"], "days_left": st["days_left"]}
    if ga.SCOPE_CALENDAR not in st["scopes"]:
        return _record(name, "local-oauth", "red", "calendar token lacks calendar.events",
                       f"delete {checks['path']} and run: {login}", **checks)
    if st["needs_reauth"]:
        return _record(name, "local-oauth", "amber", "calendar token expired (Testing mode lasts 7 days)",
                       f"log in again: {login}", **checks)
    broader = sorted(set(st["scopes"]) - {ga.SCOPE_CALENDAR})
    if broader:                                  # least privilege: calendar_events.py needs calendar.events only
        return _record(name, "local-oauth", "amber", f"calendar token is broader than calendar.events: {broader}",
                       f"remove the app at https://myaccount.google.com/permissions, delete {checks['path']} and "
                       f"run: {login}", **checks)
    soon = _expiring(name, st, login, checks)
    if soon:
        return soon
    return _record(name, "local-oauth", "green", f"calendar.events token good until {_due_pt(st)} "
                   "(calendar_events.py agenda and invites, calendar_hold.py holds)", None, **checks)


