# --------------------------------------------------------------------------- small helpers
def _mode(path: Path) -> int:
    return stat.S_IMODE(os.stat(path).st_mode)


def _tilde(path: Path | str) -> str:
    text, home = str(path), str(Path.home())
    return "~" + text[len(home):] if text.startswith(home + os.sep) else text


def _record(name: str, kind: str, state: str, summary: str, action: str | None = None,
            **checks: Any) -> dict[str, Any]:
    return {"name": name, "kind": kind, "state": state, "summary": summary, "action": action, "checks": checks}


def _inside(path: Path, root: Path) -> bool:
    p, r = Path(path).expanduser().resolve(), Path(root).resolve()
    return p == r or r in p.parents


def _date_in_name(name: str) -> date | None:
    m = re.search(r"(\d{4}-\d{2}-\d{2})", name)
    return jc.parse_date(m.group(1)) if m else None


