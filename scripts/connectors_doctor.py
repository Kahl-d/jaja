def check_all(js_root: Path, os_root: Path, config_dir: Path, env: Mapping[str, str], now: datetime,
              mcp_probe: Callable[[], dict[str, Any]] | None) -> dict[str, Any]:
    connectors = [
        check_client_secret(config_dir, env, os_root),
        check_read_token(config_dir, js_root, now),
        check_compose_token(config_dir, os_root, now),
        check_send_token(config_dir, now),
        check_legacy_token(config_dir),
        check_calendar_token(config_dir, now),
        *check_x(config_dir),
        check_x_credits(js_root),
        *check_board_connectors(js_root, now),
        *check_hunt(js_root, now),
        *check_claude_ai(),
        check_linkedin(js_root, now),
        check_adzuna(env),
        check_firecrawl(js_root, os_root, env, now),
        check_mcp(os_root, mcp_probe),
    ]
    connectors = [c for c in connectors if c is not None]
    states = [c["state"] for c in connectors]
    overall = "red" if "red" in states else "amber" if "amber" in states else "green"
    return {"generated_at": now.astimezone(cu.DEPT_TZ).replace(microsecond=0).isoformat(), "overall": overall,
            "counts": {s: states.count(s) for s in ORDER if s in states}, "connectors": connectors}


def render_markdown(report: dict[str, Any]) -> str:
    when = str(report["generated_at"])[:16].replace("T", " ")
    lines = [MD_START, f"### Connectors: {report['overall']} (checked {when} PT)", "",
             "| Connector | State | What it means | Next step |", "|---|---|---|---|"]
    for c in sorted(report["connectors"], key=lambda c: (ORDER.get(c["state"], 9), c["name"])):
        cell = lambda s: str(s or "").replace("|", "/").replace("\n", " ")  # noqa: E731
        lines.append(f"| {c['name']} | {c['state']} | {cell(c['summary'])} | {cell(c['action']) or 'none'} |")
    lines += ["", "Setup and rotation: SETUP-CONNECTORS.md. Rerun: `python3 scripts/connectors_doctor.py`.", MD_END]
    return "\n".join(lines) + "\n"


def write_outputs(js_root: Path, report: dict[str, Any]) -> tuple[Path, Path]:
    state = js_root / "state"
    state.mkdir(parents=True, exist_ok=True)
    jpath, mpath = state / "connectors.json", state / "connectors.md"
    jpath.write_text(json.dumps(report, indent=2, default=str) + "\n", encoding="utf-8")
    mpath.write_text(render_markdown(report), encoding="utf-8")
    return jpath, mpath


def main(argv: list[str] | None = None, now: datetime | None = None, env: Mapping[str, str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--root", type=Path, default=jc.JS_ROOT, help="job-search root")
    ap.add_argument("--os-root", type=Path, default=jc.OS_ROOT, help="runtime root")
    ap.add_argument("--config-dir", type=Path, default=None, help="token folder (default: gmail_auth's)")
    ap.add_argument("--skip-mcp", action="store_true", help="do not launch the MCP server")
    ap.add_argument("--json", action="store_true", help="print the JSON report instead of the markdown block")
    args = ap.parse_args(argv)
    env = os.environ if env is None else env
    now = now or datetime.now(timezone.utc)
    config_dir = (args.config_dir or ga.config_dir()).expanduser()
    probe = None if args.skip_mcp else (lambda: default_probe())   # the server code always lives in this checkout
    report = check_all(args.root, args.os_root, config_dir, env, now, probe)
    write_outputs(args.root, report)
    print(json.dumps(report, indent=2, default=str) if args.json else render_markdown(report), end="")
    return 1 if report["overall"] == "red" else 0


if __name__ == "__main__":
    sys.exit(main())
