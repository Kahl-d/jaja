def check_client_secret(config_dir: Path, env: Mapping[str, str], os_root: Path) -> dict[str, Any]:
    value = env.get("GMAIL_CLIENT_SECRET")
    path = Path(value).expanduser() if value else config_dir / "gmail_client_secret.json"
    where = "$GMAIL_CLIENT_SECRET" if value else _tilde(path)
    if not path.is_file():
        return _record("gmail-client-secret", "local-oauth", "red", "OAuth client JSON not found",
                       f"create a Desktop OAuth client and save its JSON to {where} (SETUP-CONNECTORS.md step 1)",
                       path=where, present=False)
    if _inside(path, jc.OS_ROOT) or _inside(path, os_root):
        return _record("gmail-client-secret", "local-oauth", "red", "client JSON sits inside the repo",
                       "move it to ~/.config/jaja/ and chmod 600 it", path=where, present=True)
    mode = _mode(path)
    try:
        client_type = next(iter(json.loads(path.read_text(encoding="utf-8")) or {}), None)
    except (json.JSONDecodeError, OSError):
        client_type = "unreadable"
    checks = {"path": where, "present": True, "mode": oct(mode), "client_type": client_type}
    if mode != 0o600:
        return _record("gmail-client-secret", "local-oauth", "red", f"mode {oct(mode)}, must be 600",
                       f"chmod 600 {where}", **checks)
    if client_type != "installed":
        return _record("gmail-client-secret", "local-oauth", "amber",
                       f"client type is {client_type!r}; the scripts expect a Desktop app client ('installed')",
                       "create an OAuth client of type Desktop app and replace the file", **checks)
    return _record("gmail-client-secret", "local-oauth", "green", "Desktop OAuth client present, chmod 600", None,
                   **checks)


def _token(kind: str, config_dir: Path, now: datetime) -> tuple[dict[str, Any] | None, str | None]:
    path = config_dir / ga.TOKEN_KINDS[kind]["file"]
    try:
        return ga.token_status(kind, now=now, path=path), None
    except (json.JSONDecodeError, OSError, ValueError) as exc:
        return None, f"token file unreadable ({type(exc).__name__})"


def _last_harvest(js_root: Path) -> date | None:
    path = js_root / "state" / "harvest" / "gmail.state.json"
    if not path.is_file():
        return None
    try:
        state = json.loads(path.read_text(encoding="utf-8"))
    except (json.JSONDecodeError, OSError):
        return None
    runs = state.get("runs") or []
    return cu.local_date(runs[-1].get("at")) if runs else cu.local_date(state.get("last_internal_date"))


def _token_basics(name: str, kind: str, st: dict[str, Any], login: str) -> dict[str, Any] | None:
    """Red for anything unsafe or unusable that all token kinds share; None when those pass."""
    checks = {"path": _tilde(st["path"]), "present": True, "mode": st.get("mode"), "scopes": st.get("scopes"),
              "reauth_due": st.get("reauth_due"), "days_left": st.get("days_left")}
    if not st.get("private"):
        return _record(name, "local-oauth", "red", f"token file mode {st.get('mode')}, must be 600",
                       f"chmod 600 {checks['path']}", **checks)
    if not st.get("has_refresh_token"):
        return _record(name, "local-oauth", "red", "token has no refresh token", f"log in again: {login}", **checks)
    return None


REAUTH_WARN_DAYS = 2      # every Google token warns this many days before Testing mode expires it


def _due_pt(st: dict[str, Any]) -> str:
    """The re-auth time in Pacific, the department's clock (a token due at 04:17Z expires on the evening of the
    day before in Pacific time; the UTC date would read a day late)."""
    from datetime import datetime as _dt
    raw = str(st.get("reauth_due") or "")
    try:
        when = _dt.fromisoformat(raw.replace("Z", "+00:00"))
        return when.astimezone(cu.DEPT_TZ).strftime("%Y-%m-%d %H:%M PT") if when.tzinfo else raw[:16]
    except ValueError:
        return raw[:10]


def _expiring(name: str, st: dict[str, Any], login: str, checks: dict[str, Any]) -> dict[str, Any] | None:
    """Amber once fewer than REAUTH_WARN_DAYS whole days are left (from 48 hours before Testing mode expires it): the
    brief and the cockpit say it while there is time. sitting_order calls the token ok at the same line (days_left >= 2)."""
    if st.get("days_left") is not None and st["days_left"] < REAUTH_WARN_DAYS:
        return _record(name, "local-oauth", "amber", f"re-auth due {_due_pt(st)} (Testing mode)",
                       f"log in again before then: {login}", **checks)
    return None


def check_read_token(config_dir: Path, js_root: Path, now: datetime) -> dict[str, Any]:
    name, login = "gmail-read-token", "python3 scripts/gmail_auth.py login"
    st, err = _token("read", config_dir, now)
    last = _last_harvest(js_root)
    harvest = {"last_harvest": last.isoformat() if last else None}
    if err:
        return _record(name, "local-oauth", "red", err, f"delete the file and log in again: {login}", **harvest)
    if not st["exists"]:
        return _record(name, "local-oauth", "red", "no read-only Gmail token; harvest and mail-triage cannot run",
                       f"{login} (SETUP-CONNECTORS.md step 2)", path=_tilde(st["path"]), present=False, **harvest)
    bad = _token_basics(name, "read", st, login)
    if bad:
        bad["checks"].update(harvest)
        return bad
    checks = {"path": _tilde(st["path"]), "present": True, "mode": st["mode"], "scopes": st["scopes"],
              "reauth_due": st["reauth_due"], "days_left": st["days_left"], **harvest}
    granted, wanted = set(st["scopes"]), set(ga.SCOPES_READ)
    if granted - wanted:
        extra = ", ".join(sorted(s.rsplit("/", 1)[-1] for s in granted - wanted))
        return _record(name, "local-oauth", "red", f"read token carries extra scopes ({extra}); the harvest refuses it",
                       f"delete {checks['path']} and run: {login}", **checks)
    if wanted - granted:
        return _record(name, "local-oauth", "red", "read token lacks gmail.readonly or gmail.labels",
                       f"delete {checks['path']} and run: {login}", **checks)
    if st["needs_reauth"]:
        return _record(name, "local-oauth", "red", "refresh token expired (Testing mode lasts 7 days)",
                       f"log in again: {login}", **checks)
    soon = _expiring(name, st, login, checks)
    if soon:
        return soon
    today = cu.local_date(now)
    if last is None:
        return _record(name, "local-oauth", "amber", "token is good; no harvest has run yet",
                       f"python3 scripts/gmail_pull.py harvest --since {(today - timedelta(days=365)).isoformat()}", **checks)
    if (today - last).days > HARVEST_STALE_DAYS:
        return _record(name, "local-oauth", "amber", f"token is good; last harvest {last.isoformat()}",
                       "python3 scripts/gmail_pull.py harvest", **checks)
    return _record(name, "local-oauth", "green",
                   f"read-only token good until {_due_pt(st)}; last harvest {last.isoformat()}", None,
                   **checks)


def approved_draft_approvals(os_root: Path, today: date) -> list[str]:
    """Approved, unexpired approvals with an email item and no Gmail-draft receipt yet."""
    out = []
    for path, meta, body in jc.iter_records(os_root / "work" / "approvals"):
        if str(meta.get("status")) != "approved":
            continue
        created = jc.parse_date(meta.get("created"))
        expires = jc.parse_date(meta.get("expires")) or (created + timedelta(days=7) if created else None)
        if expires and today > expires:
            continue
        items = meta.get("items") or []
        if not (meta.get("action") == "send-email" or any(str(i.get("channel")) == "email" for i in items
                                                           if isinstance(i, dict))):
            continue
        receipts = cu.section_text(body, "Receipts") or ""
        if re.search(r"draft", receipts, re.I):
            continue
        out.append(str(meta.get("id") or path.stem))
    return out


def check_compose_token(config_dir: Path, os_root: Path, now: datetime) -> dict[str, Any]:
    name, login = "gmail-compose-token", "python3 scripts/gmail_auth.py login --compose"
    st, err = _token("compose", config_dir, now)
    if err:
        return _record(name, "local-oauth", "red", err, "delete the file; create it only for an approved draft run")
    if not st["exists"]:
        return _record(name, "local-oauth", "green",
                       "not on disk (created only for an attended draft run on an approved file)", None,
                       path=_tilde(st["path"]), present=False)
    bad = _token_basics(name, "compose", st, login)
    if bad:
        return bad
    pending = approved_draft_approvals(os_root, cu.local_date(now))
    checks = {"path": _tilde(st["path"]), "present": True, "mode": st["mode"], "scopes": st["scopes"],
              "reauth_due": st["reauth_due"], "approved_draft_approvals": pending}
    if ga.SCOPE_COMPOSE not in st["scopes"]:
        return _record(name, "local-oauth", "red", "compose token lacks gmail.compose",
                       f"delete {checks['path']}; recreate with {login} only when needed", **checks)
    if not pending:
        return _record(name, "local-oauth", "amber",
                       "compose token on disk with no approved draft approval pending (gmail.compose can send)",
                       f"delete it until the next approved batch: rm {checks['path']}", **checks)
    if st["needs_reauth"]:
        return _record(name, "local-oauth", "amber", "compose token expired", f"{login}, then run the draft step",
                       **checks)
    return _record(name, "local-oauth", "green",
                   f"on disk for approved draft approval(s) {', '.join(pending)}; delete it after the drafts exist",
                   None, **checks)


