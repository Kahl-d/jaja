#!/usr/bin/env python3
"""scout_board.py - the day's handed-over roles as one ranked table, generated from the job records, so the day's
ranked list stays readable with no hand-typed numbers.

Rows: the job ids given as arguments, or --from-hunt: every ROW line in hub/lanes/HUNT.md (`ROW <company> · <role> | job <id> |
...`). Every cell comes from jobs/<id>.md (the fit score and verdict fall back to applications/<slug>/fit.md): fit, verdict,
company and role, posted date (posted_at, else first_seen), pay (comp_min to comp_max), the visa line (the record's
sponsorship evidence, else "silent"), status, job id, apply link.

Rank: the verdict band (priority and apply, then maybe, then skip or unscored), then fit (high first), then freshness (the
newer posting first), then chance (sponsorship yes, then unknown, then no), then the job id.

Read only on job records. Prints the board; with --write it saves research/targets/scout-board-<date>.md (written atomically). The HUNT
lane owns that file: it runs --write; other lanes print. Exit 0, or 1 when a job id has no record.

CLI:  python3 scripts/scout_board.py [--root JS] [--today D] [--from-hunt] [--write] [job-id ...]
"""
from __future__ import annotations

import argparse
import os
import re
import sys
import tempfile
from datetime import date
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fetch_ats as fa  # noqa: E402
import js_common as jc  # noqa: E402

ROW_RE = re.compile(r"^ROW\b.*?\|\s*job\s+([a-z0-9][a-z0-9-]*)\s*\|", re.M)
BAND = {"priority": 0, "apply": 0, "maybe": 1}
CHANCE = {"yes": 2, "cap_exempt": 2, "unknown": 1, "": 1, None: 1, "no": 0}


def row_ids(root: Path) -> list[str]:
    path = Path(root) / "hub" / "lanes" / "HUNT.md"
    if not path.is_file():
        return []
    seen: set[str] = set()
    return [i for i in ROW_RE.findall(path.read_text(encoding="utf-8")) if not (i in seen or seen.add(i))]


def _num(v: Any) -> float | None:
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def _fit(root: Path, rec: dict[str, Any]) -> tuple[float | None, str]:
    fit, verdict = _num(rec.get("fit_score")), str(rec.get("fit_verdict") or "")
    if fit is None:
        m = re.search(r"\[\[([^\]|]+)", str(rec.get("application") or ""))
        path = Path(root) / "applications" / (m.group(1) if m else "") / "fit.md"
        if m and path.is_file():
            props, _ = jc.read_record(path)
            fit, verdict = _num(props.get("fit_score")), str(props.get("fit_verdict") or verdict)
    return fit, verdict or "unscored"


def _pay(rec: dict[str, Any]) -> str:
    lo, hi = _num(rec.get("comp_min")), _num(rec.get("comp_max"))
    k = lambda v: f"${int(round(v / 1000))}K"   # noqa: E731
    if lo and hi:
        return f"{k(lo)}-{k(hi)}"
    return k(lo or hi) if (lo or hi) else "-"


def _posted(rec: dict[str, Any]) -> str:
    for key in ("posted_at", "first_seen"):
        ts = fa.parse_ts(rec.get(key))
        if ts:
            return ts.date().isoformat()
    return ""


def collect(root: Path, ids: list[str], today: date) -> list[dict[str, Any]]:
    jobs = fa.load_jobs(root) if (Path(root) / "jobs").is_dir() else {}
    rows = []
    for jid in ids:
        rec = jobs.get(jid)
        if rec is None:
            continue
        fit, verdict = _fit(root, rec)
        posted = _posted(rec)
        visa = _clip(rec.get("sponsorship_evidence"), 90) if rec.get("sponsorship_evidence") else "silent"
        rows.append({"id": jid, "fit": fit, "verdict": verdict, "company": rec.get("company") or "",
                     "title": rec.get("title") or "", "posted": posted, "pay": _pay(rec), "visa": visa,
                     "status": rec.get("status") or "", "link": rec.get("apply_url") or rec.get("source_url") or "",
                     "sponsorship": rec.get("sponsorship")})
    rows.sort(key=lambda r: (BAND.get(r["verdict"], 2), -(r["fit"] or 0.0),
                             -(date.fromisoformat(r["posted"]).toordinal() if r["posted"] else 0),
                             -CHANCE.get(r["sponsorship"], 1), r["id"]))
    return rows


def _clip(v: Any, limit: int) -> str:
    t = " ".join(str(v or "").split())
    return t if len(t) <= limit else t[: limit - 3] + "..."


def cell(v: Any) -> str:
    return str(v).replace("|", "/").replace("\u2014", "-").strip()


def render(rows: list[dict[str, Any]], today: date) -> str:
    L = [f"# Scout board · {today.isoformat()}", "",
         "Generated by scripts/scout_board.py from jobs/*.md (fit falls back to applications/*/fit.md); no number is typed by "
         "hand. Ranked by verdict band (priority and apply, maybe, skip), then fit, then freshness, then chance (sponsorship "
         "yes, unknown, no). Details per role: the ROW posts in hub/lanes/HUNT.md.", "",
         "| # | fit | verdict | company · role | posted | pay | visa line (JD or record) | status | job id | apply link |",
         "|---|---|---|---|---|---|---|---|---|---|"]
    for i, r in enumerate(rows, 1):
        fit = f"{r['fit']:.1f}" if r["fit"] is not None else "-"
        L.append(f"| {i} | {fit} | {r['verdict']} | {cell(r['company'])} · {cell(r['title'])} | {r['posted'] or '-'} | "
                 f"{r['pay']} | {cell(r['visa'])} | {r['status']} | `{r['id']}` | {r['link']} |")
    return "\n".join(L) + "\n"


def write(root: Path, rows: list[dict[str, Any]], today: date) -> Path:
    path = Path(root) / "research" / "targets" / f"scout-board-{today.isoformat()}.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    props = {"title": f"Scout board {today.isoformat()}, the day's handed-over roles, ranked",
            "written_by": "HUNT lane (runs scripts/scout_board.py --write)", "generated_by": "scripts/scout_board.py",
            "date": today.isoformat(), "rows": len(rows), "for": "the orchestrator (rank into hub/NEXT-UP.md), the owner (read any time)"}
    fd, tmp = tempfile.mkstemp(dir=path.parent, prefix=".tmp-")
    with os.fdopen(fd, "w", encoding="utf-8") as fh:
        fh.write(jc.fm.dump(props, render(rows, today)))
    os.chmod(tmp, 0o644)
    os.replace(tmp, path)
    return path


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--root", type=Path, default=jc.JS_ROOT)
    p.add_argument("--today", type=jc.cli_date, default=None)
    p.add_argument("--from-hunt", action="store_true", help="take the job ids from the ROW lines in hub/lanes/HUNT.md")
    p.add_argument("--write", action="store_true", help="save research/targets/scout-board-<date>.md (the HUNT lane runs this)")
    p.add_argument("ids", nargs="*")
    args = p.parse_args(argv)
    today = args.today or jc.today()
    ids = list(dict.fromkeys(list(args.ids) + (row_ids(args.root) if args.from_hunt else [])))
    rows = collect(args.root, ids, today)
    missing = [i for i in ids if i not in {r["id"] for r in rows}]
    for i in missing:
        print(f"no job record: jobs/{i}.md", file=sys.stderr)
    print(render(rows, today), end="")
    if args.write:
        print(f"wrote {write(args.root, rows, today).relative_to(args.root)}")
    return 1 if missing else 0


if __name__ == "__main__":
    sys.exit(main())
