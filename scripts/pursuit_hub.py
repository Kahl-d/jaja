#!/usr/bin/env python3
"""pursuit_hub.py - pursuits/<slug>/HUB.md: one page per pursuit, a deterministic join over every record it names.

A pursuit (pursuits/<slug>/pursuit.md, written by scripts/pursuits.py) says who the way into
a company is, which roles the owner picked, the stage and what it waits on. This hub joins what the other records
hold, on role_hub.py's model (same loader, so company slugs compare canonically):

  State                 stage, waiting on, next action and date, kind, referrer, introducer, closed reason
  People                each person on the pursuit: their part, role, status, priority, last in/out, next touch
  Intake and case       the intake note and the case file (its status)
  Company               the dossier and the legal check; other pursuits into the same company
  Applications          each pick: stage, fit score, variant verdict, its role HUB.md
  Resumes               the master variant: editorial verdict, review.md verdict, its files
  Outreach and approvals  outbox items and touches for these people or picks (ids, channels, statuses only),
                        then each approval they cite: action, status, expiry (named by its repo path,
                        `work/approvals/<id>.md`: work/ is not a vault link target for the OS lint)
  Timeline              touches, outbox items, application events, decisions and the pursuit log, oldest first

Message text is never copied: outbox bodies and touch summaries stay in their records. Anything absent gets a
`missing:` line naming its maker. No clock: a refresh with nothing changed writes nothing. A HUB.md whose
pursuit.md is gone is removed (only when it carries this script's header). Refreshed by scripts/dashboard.py
and on demand:

  python3 scripts/pursuit_hub.py [--root R] [--os-root O] [<slug> ...] [--dry-run | --check]
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import graph_links  # noqa: E402
import pursuits as pu  # noqa: E402
import role_hub as rh  # noqa: E402
import tracker  # noqa: E402
from js_common import JS_ROOT, OS_ROOT, fm  # noqa: E402

SELF = "scripts/pursuit_hub.py"
HUB = "HUB.md"
LINE = re.compile(r"^- (\d{4}-\d{2}-\d{2}) · (.*)$")


def header(source: str) -> str:
    """The repo's GENERATED header (the PreToolUse guard refuses hand edits to files carrying it)."""
    return f"<!-- GENERATED by {SELF} from {source} — do not edit -->"


def _rel(path: str) -> str:
    return f"../../{path}"                         # pursuits/<slug>/HUB.md, the same depth as a role hub


def _section_lines(body: str, name: str) -> list[tuple[str, str]]:
    part = body.split(f"## {name}", 1)[1].split("\n## ", 1)[0] if f"## {name}" in body else ""
    return [(m.group(1), m.group(2)) for m in (LINE.match(l.strip()) for l in part.splitlines()) if m]


def _people(rec: rh.Records, meta: dict[str, Any]) -> list[tuple[str, str, dict[str, Any] | None]]:
    by_id = {p["id"]: p for p in rec.prospects}
    parts = [(meta.get("referrer"), "referrer"), (meta.get("introducer"), "introducer")]
    parts += [(c, "contact") for c in meta.get("contacts") or []]
    seen, out = set(), []
    for pid, part in parts:
        if pid and pid not in seen:
            seen.add(pid)
            out.append((pid, part, by_id.get(pid)))
    return out


def _trail(rec: rh.Records, ids: set[str], apps: set[str]) -> list[dict[str, Any]]:
    """Outbox items and touches for these people or these applications (never their text), oldest first."""
    def mine(item: dict[str, Any]) -> bool:
        return str(item.get("prospect") or "") in ids or (rh._link(item.get("application")) or "") in apps

    names = {p["id"]: str(p.get("name") or p["id"]) for p in rec.prospects}
    rows, folded = [], {}
    for o in rec.outbox:
        if mine(o):
            at = o.get("sent_at") or o.get("approved_at") or o.get("created")
            row = {"at": at, "sort": rh._sort_key(at), "what": "outbox", "direction": "out",
                   "channel": o.get("channel") or "?", "kind": o.get("kind") or "?", "status": o.get("status") or "drafted",
                   "prospect": o.get("prospect"), "link": f"outbox/{o['_file']}", "label": o["id"],
                   "approval": o.get("approval"), "touch": None}
            folded[f"outbox/{o['_file']}"] = row
            rows.append(row)
    for t in rec.touches:
        if not mine(t):
            continue
        draft = str(t.get("draft_path") or "")
        if draft in folded:
            folded[draft]["touch"] = rh._stamp(t.get("at"))
            continue
        month = rh._day(t.get("at"))[:7]
        rows.append({"at": t.get("at"), "sort": rh._sort_key(t.get("at")), "what": "touch",
                     "direction": t.get("direction") or "?", "channel": t.get("channel") or "?",
                     "kind": t.get("kind") or "?", "status": t.get("status") or "?", "prospect": t.get("prospect"),
                     "link": f"touches/{month}.jsonl", "label": f"touch {t.get('key') or month}",
                     "approval": t.get("approval_id"), "touch": None})
    for r in rows:
        r["name"] = names.get(str(r.get("prospect") or ""), r.get("prospect") or "no prospect")
    rows.sort(key=lambda r: (r["sort"], r["label"]))
    return rows


def render(rec: rh.Records, slug: str, meta: dict[str, Any], body: str, os_root: Path,
           others: dict[str, dict[str, Any]]) -> str:
    root = rec.root
    title = meta.get("title") or slug
    L = [header(f"pursuits/{slug}/pursuit.md and the records it names"), f"# {title}", "",
         "One direction into a company: every line links the file that holds the fact. Refreshed by "
         "`scripts/pursuit_hub.py` (and every `scripts/dashboard.py` run); never hand-edited. Change the pursuit "
         "with `scripts/pursuits.py`.", ""]

    # ---- state
    L += ["## State", ""]
    nxt = (f"next: {meta['next_action']}" + (f" · due {rh._day(meta['next_action_at'])}" if meta.get("next_action_at")
                                             else " · no date")) if meta.get("next_action") else "next: none"
    L.append(f"- {graph_links.wikilink(f'pursuits/{slug}/pursuit', 'pursuit.md')} · stage {meta.get('stage')} · "
             f"waiting on {meta.get('waiting_on')} · {nxt}")
    L.append(f"- {meta.get('kind')} · {meta.get('company') or meta.get('company_slug')} · updated "
             f"{rh._day(meta.get('updated'))}" + (f" · closed: {meta['closed_reason']}" if meta.get("closed_reason") else ""))
    L.append("")

    # ---- people
    L += ["## People", ""]
    people = _people(rec, meta)
    for pid, part, p in people:
        if p is None:
            L.append(f"- missing: prospects/{pid}.md ({part} on this pursuit, no record; prospector)")
            continue
        L.append(f"- [{p.get('name') or pid}]({_rel('prospects/' + p['_file'])}) · {part} · "
                 f"{p.get('role') or 'role unknown'} · {p.get('status') or 'status unknown'} · "
                 f"{p.get('priority') or 'no priority'} · last in "
                 f"{rh._day(p['last_inbound_at']) if p.get('last_inbound_at') else 'never'}, last out "
                 f"{rh._day(p['last_outbound_at']) if p.get('last_outbound_at') else 'never'} · next touch "
                 f"{rh._day(p['next_touch_at']) if p.get('next_touch_at') else 'none'}")
    if not people:
        L.append("- missing: nobody named on this pursuit (pursuits.py set --referrer / --add-contact)")
    L.append("")

    # ---- intake and case
    L += ["## Intake and case", ""]
    for key, maker in (("intake", "the orchestrator or the recruiter lane"), ("case", "company-researcher, research-company")):
        rel = meta.get(key)
        if rel and (root / rel).is_file():
            status = rh._meta(root / rel).get("status") if rel.endswith(".md") else None
            L.append(f"- {key}: [{rel}]({_rel(rel)})" + (f" · status {status}" if status else ""))
        else:
            L.append(f"- missing: {key} {rel + ' (named, not on disk)' if rel else 'not named'} ({maker}; "
                     f"pursuits.py set --{key})")
    L.append("")

    # ---- company
    L += ["## Company", ""]
    cs = meta.get("company_slug")
    dossier = root / "companies" / f"{cs}.md"
    if cs and dossier.is_file():
        d = rh._meta(dossier)
        L.append(f"- [companies/{cs}.md]({_rel(f'companies/{cs}.md')}) · tier {d.get('tier') or '?'} · "
                 f"E-Verify {d.get('e_verify') or 'unknown'} · researched {rh._day(d.get('last_researched'))}")
    else:
        L.append(f"- missing: companies/{cs}.md (the dossier; company-researcher)")
    check = root / "legal" / "checks" / f"{cs}.md"
    if cs and check.is_file():
        c = rh._meta(check)
        L.append(f"- [legal/checks/{cs}.md]({_rel(f'legal/checks/{cs}.md')}) · verdict {c.get('verdict') or '?'} · "
                 f"E-Verify {c.get('e_verify') or 'unknown'} · checked {rh._day(c.get('checked_at'))}")
    else:
        L.append(f"- missing: legal/checks/{cs}.md (the visa gate; legal-visa)")
    for other in sorted(o for o, m in others.items() if o != slug and m.get("company_slug") == cs):
        L.append(f"- also into this company: {graph_links.wikilink(f'pursuits/{other}/HUB', other)} · "
                 f"stage {others[other].get('stage')}")
    L.append("")

    # ---- applications
    L += ["## Applications (the owner's picks)", ""]
    apps = {s: (m, b) for s, m, b in rec.apps}
    picks = list(meta.get("applications") or [])
    for a in picks:
        if a not in apps:
            L.append(f"- missing: applications/{a}/application.md (named here, gone; tracker-ops)")
            continue
        am, _ = apps[a]
        fit = rh._meta(root / "applications" / a / "fit.md")
        score = fit.get("fit_score") if fit.get("fit_score") is not None else fit.get("score")   # either key
        vrel = rh.variant_path(root, am.get("resume_variant"))      # recorded only, never guessed (change 3)
        verdict = rh._yaml(root / vrel / "meta.yaml").get("editorial_verdict") if vrel else None
        state = (verdict or "verdict not recorded") if vrel and (root / vrel).is_dir() else \
            ("missing" if vrel else "not recorded")
        hub = (graph_links.wikilink(f"applications/{a}/HUB", a) if (root / "applications" / a / rh.HUB).is_file()
               else graph_links.wikilink(f"applications/{a}/application", a))
        L.append(f"- {hub} · stage {am.get('stage') or 'unknown'} · fit "
                 f"{score if score is not None else 'unscored'} · variant {state}")
    if not picks:
        L.append("- none picked yet (pursuits.py set --add-application)")
    L.append("")

    # ---- resumes
    L += ["## Resumes", ""]
    master = meta.get("master_variant")
    if master and (root / "resumes" / "variants" / master).is_dir():
        vdir = root / "resumes" / "variants" / master
        vmeta = rh._yaml(vdir / "meta.yaml")
        L.append(f"- master: [resumes/variants/{master}/]({_rel(f'resumes/variants/{master}/')}) · editorial_verdict "
                 f"{vmeta.get('editorial_verdict') or 'not recorded'}")
        for f in sorted(p for p in vdir.iterdir() if p.is_file() and p.suffix in (".md", ".pdf")):
            verdict = rh._meta(f).get("verdict") if f.name.startswith("review") else None
            L.append(f"  - [{f.name}]({_rel(f'resumes/variants/{master}/{f.name}')})"
                     + (f" · verdict {verdict}" if verdict else ""))
        if not (vdir / "review.md").is_file():
            L.append(f"  - missing: resumes/variants/{master}/review.md (resume-editor)")
    elif master:
        L.append(f"- missing: resumes/variants/{master}/ (named, not on disk; resume-tailor)")
    elif meta.get("kind") == "referral":
        L.append("- missing: no master resume named (resume-tailor; pursuits.py set --master-variant)")
    else:
        L.append("- none: each pick carries its own variant (Applications above)")
    L.append("")

    # ---- outreach and approvals
    L += ["## Outreach and approvals", ""]
    trail = _trail(rec, {pid for pid, _, _ in people}, set(picks))
    L += rh._trail_lines(trail, _rel) or ["- missing: no outbox item or touch for these people (messenger, prospector)"]
    for aid in sorted({str(r["approval"]) for r in trail if r.get("approval")}):
        path = Path(os_root) / "work" / "approvals" / f"{aid}.md"
        if path.is_file():
            am = rh._meta(path)
            L.append(f"- `work/approvals/{aid}.md` · {am.get('action') or '?'} · status {am.get('status') or '?'} · "
                     f"expires {rh._day(am.get('expires'))}"
                     + (f" · decided {rh._day(am['decided_at'])}" if am.get("decided_at") else ""))
        else:
            L.append(f"- missing: work/approvals/{aid}.md (cited by an outbox item or touch)")
    L.append("")

    # ---- timeline
    L += ["## Timeline (oldest first)", ""]
    events: list[tuple[str, int, str]] = []
    for r in trail:
        events.append((r["sort"], 0, f"- {rh._stamp(r['at'])} · {r['what']} · {r['direction']} · {r['channel']} · "
                                     f"{r['kind']} · {r['status']} · {r['name']} · {r['label']}"))
    for a in picks:
        if a in apps:
            for e in tracker.parse_events(apps[a][1]):
                events.append((rh._sort_key(e.at), 1, f"- {rh._stamp(e.at)} · {a} · {e.type} · {e.source}"))
    for name, order in (("Decisions", 2), ("Log", 3)):
        for day, text in _section_lines(body, name):
            events.append((rh._sort_key(day), order, f"- {day} · {'decision · ' if name == 'Decisions' else ''}{text}"))
    L += [line for _, _, line in sorted(events, key=lambda e: (e[0], e[1], e[2]))] or ["- nothing yet"]
    L.append("")
    return "\n".join(L)


def plan(root: Path, os_root: Path, slugs: list[str] | None = None) -> dict[Path, str | None]:
    root = Path(root)
    known = {s: (m, b) for s, m, b in pu.iter_pursuits(root)}
    changes: dict[Path, str | None] = {}
    if not slugs:
        base = root / "pursuits"
        for hub in sorted(base.glob(f"*/{HUB}")) if base.is_dir() else []:
            if hub.parent.name not in known and SELF in hub.read_text(encoding="utf-8").split("\n", 1)[0]:
                changes[hub] = None
    if not known and not slugs:
        return changes
    rec = rh.Records.load(root)
    others = {s: m for s, (m, _) in known.items()}
    for slug in slugs or sorted(known):
        if slug not in known:
            raise KeyError(f"no pursuit {slug}: pursuits/{slug}/pursuit.md not found")
        path = root / "pursuits" / slug / HUB
        text = render(rec, slug, *known[slug], os_root=os_root, others=others)
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            changes[path] = text
    return changes


def apply(changes: dict[Path, str | None]) -> None:
    for path, text in changes.items():
        if text is None:
            path.unlink()
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")


def refresh(root: Path, os_root: Path = OS_ROOT) -> dict[Path, str | None]:
    changes = plan(root, os_root)
    apply(changes)
    return changes


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("slugs", nargs="*", help="pursuit slugs (default: every pursuit, and pruning)")
    ap.add_argument("--root", type=Path, default=JS_ROOT)
    ap.add_argument("--os-root", type=Path, default=OS_ROOT, help="where work/approvals/ lives")
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--dry-run", action="store_true")
    mode.add_argument("--check", action="store_true", help="exit 1 when any pursuit hub is stale; write nothing")
    args = ap.parse_args(argv)
    try:
        changes = plan(args.root, args.os_root, args.slugs or None)
    except KeyError as exc:
        print(str(exc).strip("'\""), file=sys.stderr)
        return 2
    for path, text in changes.items():
        verb = "remove" if text is None else ("update" if path.is_file() else "create")
        print(f"{'would ' if args.dry_run or args.check else ''}{verb} {path.relative_to(args.root).as_posix()}")
    if args.check:
        print(f"stale: {len(changes)}")
        return 1 if changes else 0
    if not args.dry_run:
        apply(changes)
    print(f"pursuit hubs: {len(changes)} changed" + (" (dry-run, nothing written)" if args.dry_run else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
