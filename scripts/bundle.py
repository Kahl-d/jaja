#!/usr/bin/env python3
"""bundle.py - pursuits/<P>/BUNDLE.md: the one page the owner reviews before approving anything on a pursuit.

A deterministic join, read-only on every record it names, in the order the owner reviews:

  1 Dates                the last working day (clock.yaml) and where a send today falls against it; present_check
                         on the master and the messages when scripts/present_check.py is in the tree; every pending
                         approval the page names, soonest expiry first
  2 Public profile first each pending edit-linkedin-profile, edit-portal-profile or publish approval (the owner's own
                         public surfaces, which a referrer reads before the note): its items, the apply list, and the
                         required, recommended, optional and other items by their drafts' labels (the first check line)
  3 Resumes              the master variant first, then each pick's: the PDFs, the resume.yaml sha256, the review.md
                         verdict and whether it signs the CURRENT hash (else STALE), and the ats_check verdict
  4 Messages             each outbox draft to the referrer or introducer: id, channel, characters against the channel's
                         limit in outbox.py, its approval and status, the attachments
  5 Decisions still open the rows of hub/REVIEW-LIST.md whose last cell is not closed, answered or done
  6 Checks               the command that reproduces each section

Message text is never copied (only counted). Anything absent gets a `missing:` line naming its maker. The page
depends only on the records and --today, so a rebuild with nothing changed writes nothing. Nothing here sends.

    python3 scripts/bundle.py <pursuit> [--root R] [--os-root O] [--today YYYY-MM-DD] [--print]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from datetime import date, datetime, timedelta, timezone
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import clock as job_clock  # noqa: E402
import agency_config as acfg  # noqa: E402
import js_comms_util as cu  # noqa: E402
import outbox as ob  # noqa: E402
import pursuits as pu  # noqa: E402
from js_common import JS_ROOT, OS_ROOT, cli_date, dept_day, fm  # noqa: E402

SELF = "scripts/bundle.py"
BUNDLE = "BUNDLE.md"
PRESENT_CHECK = Path(__file__).resolve().parent / "present_check.py"      # optional
RESUME_PDF = acfg.get("identity.resume_pdf_name", "Resume.pdf")                  # the PDF name a variant builds
PUBLIC_ACTIONS = ("edit-linkedin-profile", "edit-portal-profile", "publish")
LABELS = ("required", "recommended", "optional")
DONE = ("closed", "answered", "done")
QUIET = ("withdrawn", "superseded")
APPLY_LIST = re.compile(r"apply list:\s*`?([\w./-]+)")
APPROVALS_FROM_JS = "../../../../work/approvals"                           # commands run from the department folder


def header(slug: str) -> str:
    return f"<!-- GENERATED by {SELF} from pursuits/{slug}/pursuit.md and the records it names; do not edit -->"


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _plural(n: int, noun: str) -> str:
    return f"{n} {noun}" + ("" if n == 1 else "s")


def _outbox(root: Path) -> list[dict[str, Any]]:
    out = []
    for path in sorted((root / "outbox").glob("O-*.md")):
        meta, body = fm.load(path)
        out.append({**meta, "_file": path.name, "_chars": len(cu.canonical_text(body))})
    return out


def _approval(os_root: Path, aid: str) -> dict[str, Any] | None:
    path = os_root / "work" / "approvals" / f"{aid}.md"
    return fm.load(path)[0] if path.is_file() else None


def _expires(meta: dict[str, Any]) -> date | None:
    created = cu.jc.parse_date(meta.get("created"))
    return cu.jc.parse_date(meta.get("expires")) or (created + timedelta(days=7) if created else None)


def _front(path: Path) -> tuple[dict[str, Any], bool]:
    """review.md front matter; when it is not valid YAML, its `key: value` lines read one by one (flagged)."""
    try:
        return fm.load(path)[0], True
    except Exception:  # noqa: BLE001  (any YAML or front matter error: fall back to the lines)
        text = path.read_text(encoding="utf-8").split("\n---", 1)[0]
        return {m.group(1): m.group(2).strip().strip("'\"") for m in
                (re.match(r"^(\w+):\s*(.*)$", l) for l in text.splitlines()[1:]) if m}, False


# ----------------------------------------------------------------------------- sections
def dates(root: Path, os_root: Path, meta: dict[str, Any], today: date, named: list[str],
          masters: list[Path], messages: list[dict[str, Any]], checks: list[str]) -> list[str]:
    L = ["## 1. Dates", ""]
    try:
        cfg = job_clock.load(root)
    except job_clock.ClockError as exc:
        cfg = None
        L.append(f"- missing: a readable clock.yaml ({exc}; the Recruiter)")
    else:
        if cfg is None:
            L.append("- missing: clock.yaml (the Recruiter; `python3 scripts/clock.py set`)")
    if cfg:
        end = cfg["employment_end"]
        L.append(f"- last working day: {end} (clock.yaml `employment_end`, employer {cfg.get('employer') or 'unnamed'})")
        gap = (today - end).days
        where = ("is on the last working day" if gap == 0 else
                 f"is {_plural(-gap, 'day')} before the last working day" if gap < 0 else
                 f"is {_plural(gap, 'day')} after the last working day")
        L.append(f"- a send today, {today}, {where}")
        checks.append("- 1: `python3 scripts/clock.py status` (the last working day)")
    files = [p.relative_to(root).as_posix() for p in masters] + [f"outbox/{m['_file']}" for m in messages]
    if not PRESENT_CHECK.is_file():
        L.append("- present_check: not run: scripts/present_check.py is not in this tree (an optional check)")
    elif files:
        cmd = ["--root", str(root), "--send-date", today.isoformat(), *files]
        run = subprocess.run([sys.executable, str(PRESENT_CHECK), *cmd], capture_output=True, text=True, cwd=root)
        word = {0: "clear", 1: "STOP"}.get(run.returncode, "could not run")
        said = next((l for l in run.stdout.splitlines() if l.strip()), "no output")
        shown = f"--send-date {today} {' '.join(files)}"
        L.append(f"- present_check: {word} (exit {run.returncode}) on `{shown}`: {said}")
        checks.append(f"- 1: `python3 scripts/present_check.py {shown}`")
    L.append("- approvals on this page, soonest expiry first:" if named else "- approvals: none pending on this page")
    rows = []
    for aid in named:
        a = _approval(os_root, aid) or {}
        exp = _expires(a)
        if exp is None:
            when = "no expiry recorded"
        elif exp < today:
            when = f"EXPIRED on {exp} ({_plural((today - exp).days, 'day')} ago)"
        else:
            when = f"expires {exp} (in {_plural((exp - today).days, 'day')})"
        rows.append((exp or date.max, aid, f"  - {aid} · {a.get('action') or '?'} · {a.get('status') or '?'} · {when}"))
    L += [r[2] for r in sorted(rows)]
    if named:
        checks.append(f"- 1: `grep -E '^(action|status|expires):' "
                      + " ".join(f"{APPROVALS_FROM_JS}/{a}.md" for a in named) + "`")
    return L + [""]


def public(os_root: Path, drafts: list[dict[str, Any]], checks: list[str]) -> tuple[list[str], list[str]]:
    L = ["## 2. Public profile first", "",
         "Pending edits to the owner's own public surfaces; the referrer reads these before the note.", ""]
    folder = os_root / "work" / "approvals"
    pending = [(str(a.get("id") or path.stem), a) for path in (sorted(folder.glob("A-*.md")) if folder.is_dir() else [])
               for a in [fm.load(path)[0]] if a.get("action") in PUBLIC_ACTIONS and a.get("status") == "pending"]
    ids = []
    for aid, a in pending:
        ids.append(aid)
        links = [f"supersedes {a['supersedes']}"] if a.get("supersedes") else []
        links += [f"superseded by {oid}" for oid, o in pending
                  if oid != aid and re.match(rf"{re.escape(aid)}\b", str(o.get("supersedes") or ""))]
        tail = "".join(f" · {x}" for x in links)
        items = [d for d in drafts if d.get("approval") == aid]
        if not items:
            L.append(f"- {aid} · {a['action']} · no outbox items; draft: {a.get('draft_ref') or 'none named'}{tail}")
            continue
        klass: dict[str, list[str]] = {k: [] for k in (*LABELS, "other")}
        lists = set()
        for d in items:
            first = str((d.get("checks") or [""])[0]).strip().lower()
            klass[next((k for k in LABELS if first.startswith(k)), "other")].append(str(d["id"]))
            lists |= {m.group(1) for c in d.get("checks") or [] for m in [APPLY_LIST.search(str(c))] if m}
        where = ", ".join(f"`{x}`" for x in sorted(lists)) or "none named"
        L.append(f"- {aid} · {a['action']} · {_plural(len(items), 'item')} · apply list {where} · "
                 + " · ".join(f"{k} {len(v)}" for k, v in klass.items()) + tail)
        L += [f"  - {k}: {', '.join(v)}" for k, v in klass.items() if v]
    if not ids:
        L.append("- none: no pending edit-linkedin-profile, edit-portal-profile or publish approval")
    checks.append("- 2: `python3 scripts/outbox.py list --status pending` (each item and its approval)")
    return L + [""], ids


def resumes(root: Path, meta: dict[str, Any], checks: list[str]) -> tuple[list[str], list[Path]]:
    L = ["## 3. Resumes", ""]
    order: list[tuple[str, str]] = []
    if meta.get("master_variant"):
        order.append(("master", str(meta["master_variant"])))
    for app in meta.get("applications") or []:
        am = fm.load(root / "applications" / app / "application.md")[0] \
            if (root / "applications" / app / "application.md").is_file() else {}
        vid = str(am.get("resume_variant") or app).strip("/").split("/")[-1]
        if vid not in [v for _, v in order]:
            order.append(("variant", vid))
    masters = []
    for part, vid in order:
        rel = f"resumes/variants/{vid}"
        v = root / rel
        if not v.is_dir():
            L.append(f"- missing: {rel}/ (resume-tailor)")
            continue
        y = v / "resume.yaml"
        if part == "master" and y.is_file():
            masters.append(y)
        pdfs = sorted(p.relative_to(root).as_posix() for p in [*v.glob("*.pdf"), *v.glob("inline/*.pdf")])
        bits = [f"PDF {', '.join(f'`{p}`' for p in pdfs)}" if pdfs else "missing: no PDF (build-resume-pdf)"]
        current = _sha(y) if y.is_file() else None
        bits.append(f"resume.yaml sha256 {current}" if current else "missing: resume.yaml (resume-tailor)")
        note = None
        if (v / "review.md").is_file():
            rv, clean = _front(v / "review.md")
            signed = str(rv.get("variant_hash") or "").replace("sha256:", "")
            said = f"review.md {rv.get('verdict') or 'no verdict'} (round {rv.get('round') or '?'})"
            bits.append(f"{said}, signs the current hash" if signed and signed == current else
                        f"{said}, STALE: review.md signs sha256 {signed or 'nothing'}, resume.yaml is now {current}")
            note = None if clean else "  - note: review.md front matter is not valid YAML; read line by line (resume-editor)"
        else:
            bits.append("missing: review.md (resume-editor)")
        report = v / "ats-report.json"
        built = str((fm.parse_yaml((v / "meta.yaml").read_text(encoding="utf-8")) or {}).get("built_at") or "") \
            if (v / "meta.yaml").is_file() else ""
        if report.is_file():
            r = json.loads(report.read_text(encoding="utf-8"))
            verdict = "passed" if r.get("passed") else "FAILED"
            at = str(r.get("checked_at") or "")
            bits.append(f"ats_check {verdict}, STALE: checked {at}, before the build of {built}" if built and at < built
                        else f"ats_check {verdict} ({_plural(len(r.get('failures') or []), 'failure')}, checked {at})")
            jd = f" --jd {r['jd']}" if r.get("jd") else ""
            checks.append(f"- 3: `python3 scripts/ats_check.py check --pdf {r.get('pdf') or rel + '/' + RESUME_PDF}{jd}`")
        else:
            bits.append("missing: ats-report.json (resume-tailor runs ats_check)")
        L.append(f"- {part} `{vid}`: " + " · ".join(bits))
        if note:
            L.append(note)
        checks.append(f"- 3: `shasum -a 256 {rel}/resume.yaml` against `grep variant_hash {rel}/review.md`")
    if not order:
        L.append("- missing: no master and no picks named (pursuits.py set --master-variant)")
    return L + [""], masters


def messages(root: Path, os_root: Path, meta: dict[str, Any], drafts: list[dict[str, Any]],
             checks: list[str]) -> tuple[list[str], list[dict[str, Any]]]:
    L = ["## 4. Messages", ""]
    parts = {str(meta[k]): k for k in ("introducer", "referrer") if meta.get(k)}
    master = meta.get("master_variant")
    master_pdf = f"resumes/variants/{master}/{RESUME_PDF}" if master else None
    mine = [d for d in drafts if str(d.get("prospect") or "") in parts and d.get("status") not in QUIET]
    for d in mine:
        pid, channel, n = str(d["prospect"]), str(d.get("channel") or "?"), d["_chars"]
        name = pu.person_name(root, pid) or pid
        if channel == "linkedin-connect":
            limit, why = ob.CONNECT_NOTE_LIMIT[bool(d.get("premium"))], \
                ("Premium" if d.get("premium") else "free account") + "; outbox.py"
        elif channel == "linkedin-comment":
            limit, why = ob.COMMENT_LIMIT, "outbox.py"
        else:
            limit, why = None, ""
        size = (f"{_plural(n, 'character')}, no limit in outbox.py" if limit is None else
                f"{_plural(n, 'character')}, OVER the limit of {limit} ({why})" if n > limit else
                f"{_plural(n, 'character')}, limit {limit} ({why})")
        aid = d.get("approval")
        a = _approval(os_root, str(aid)) if aid else None
        appr = ("approval: none requested" if not aid else
                f"approval {aid} {a.get('status') or '?'}" if a is not None else
                f"approval {aid} missing: work/approvals/{aid}.md")
        att = [str(x).split()[0] for x in d.get("attachments") or []]
        if att:
            attach = "attachments: " + ", ".join(f"`{x}`" for x in att)
        elif channel in ("email", "linkedin-message") and master_pdf and (root / master_pdf).is_file():
            attach = f"attachments: none (the master PDF `{master_pdf}` is not attached)"
        else:
            attach = "attachments: none"
        L.append(f'- {d["id"]} · {channel} · to "{name}" ({parts[pid]}) · {size} · {appr} · {attach}')
        checks.append(f"- 4: `awk 'f>=2;/^---$/{{f++}}' outbox/{d['_file']} | wc -m` (wc counts the final newline: "
                      "one more)")
    if not mine:
        L.append("- none: no draft to the referrer or the introducer")
    return L + [""], mine


def decisions(root: Path, checks: list[str]) -> list[str]:
    L = ["## 5. Decisions still open", ""]
    path = root / "hub" / "REVIEW-LIST.md"
    if not path.is_file():
        return L + ["- missing: hub/REVIEW-LIST.md (the orchestrator)", ""]
    lines = path.read_text(encoding="utf-8").splitlines()
    sep = re.compile(r"^\|(\s*:?-+:?\s*\|)+\s*$")
    found, heading, shown = 0, "", None
    for i, line in enumerate(lines):
        if re.match(r"^#{1,3} ", line):
            heading = line.lstrip("#").strip()
        if not line.startswith("|") or sep.match(line) or (i + 1 < len(lines) and sep.match(lines[i + 1])):
            continue
        cells = [c.strip().replace("**", "").replace("`", "") for c in line.strip().strip("|").split("|")]
        if len(cells) < 2:
            continue
        last = cells[-1]
        word = re.sub(r"[^a-z]", "", (last.split() or [""])[0].lower())
        if word in DONE:
            continue
        what = cells[1] if len(cells[1]) <= 100 else cells[1][:97].rstrip() + "..."
        if shown != heading:
            L.append(f'- in "{heading}":')
            shown = heading
        L.append(f"  - #{cells[0]} · {what} · {last}")
        found += 1
    if not found:
        L.append("- none: every row is closed, answered or done")
    checks.append("- 5: `grep -n '^|' hub/REVIEW-LIST.md`")
    return L + [""]


def render(root: Path, os_root: Path, slug: str, today: date) -> str:
    root, os_root = Path(root), Path(os_root)
    meta, _ = pu.load(root, slug)
    drafts = _outbox(root) if (root / "outbox").is_dir() else []
    checks: list[str] = []
    later: list[str] = []
    sec2, public_ids = public(os_root, drafts, later)
    sec3, masters = resumes(root, meta, later)
    sec4, mine = messages(root, os_root, meta, drafts, later)
    named = sorted(set(public_ids) | {str(d["approval"]) for d in mine if d.get("approval")
                                      and (_approval(os_root, str(d["approval"])) or {}).get("status") == "pending"})
    sec1 = dates(root, os_root, meta, today, named, masters, mine, checks)
    sec5 = decisions(root, later)
    L = [header(slug), f"# Review bundle: {meta.get('title') or slug}", "",
         f"The one page to read before approving anything on this pursuit, as of {today}. Every line names the file "
         f"it read; section 6 gives the command that reproduces each line. Rebuilt by `python3 scripts/bundle.py {slug}`; "
         "never hand-edited. Nothing here sends.", ""]
    L += sec1 + sec2 + sec3 + sec4 + sec5
    L += ["## 6. Checks", "", "Run from your data folder.", ""]
    L += checks + later + [f"- 6: `python3 scripts/bundle.py {slug} --print` (this whole page)"]
    return "\n".join(L) + "\n"


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("pursuit")
    ap.add_argument("--root", type=Path, default=JS_ROOT)
    ap.add_argument("--os-root", type=Path, default=OS_ROOT, help="where work/approvals/ lives")
    ap.add_argument("--today", type=cli_date, default=None)
    ap.add_argument("--print", action="store_true", help="print the page; write nothing")
    args = ap.parse_args(argv)
    today = args.today or dept_day(datetime.now(timezone.utc))
    if not pu.record_path(args.root, args.pursuit).is_file():
        print(f"bundle: no pursuit {args.pursuit}: pursuits/{args.pursuit}/pursuit.md not found", file=sys.stderr)
        return 2
    text = render(args.root, args.os_root, args.pursuit, today)
    if args.print:
        sys.stdout.write(text)
        return 0
    out = Path(args.root) / "pursuits" / args.pursuit / BUNDLE
    rel = out.relative_to(args.root).as_posix()
    if out.is_file() and out.read_text(encoding="utf-8") == text:
        print(f"bundle: {rel} unchanged")
        return 0
    out.write_text(text, encoding="utf-8")
    print(f"bundle: wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
