"""scout_board.py: the day's handed-over roles (ROW lines in hub/lanes/HUNT.md, or job ids) rendered
from the job records into one ranked table, no hand-typed numbers, for the orchestrator to rank into NEXT-UP. Read only on job records;
it writes research/targets/scout-board-<date>.md only with --write (the HUNT lane owns that file)."""
from __future__ import annotations

from datetime import date, timedelta

from disc_harness import *  # noqa: F401,F403  (puts scripts/ on sys.path; fixtures; no-network guard)
from disc_harness import NOW

import fetch_ats as fa  # noqa: E402
import scout_board as sb  # noqa: E402
from js_common import fm  # noqa: E402

TODAY = date(2026, 10, 1)


def _job(root, jid, company, title, *, fit, verdict, days_old, sponsorship="unknown", evidence=None, comp=(None, None)):
    rec = fa.make_record({"name": company, "slug": company.lower()}, title=title, source="ashby",
                         source_url=f"https://jobs.example.com/{jid}", apply_url=f"https://jobs.example.com/{jid}/apply",
                         ats_vendor="ashby", posted_at=(TODAY - timedelta(days=days_old)).isoformat(),
                         location="San Francisco, CA", remote="onsite", comp=(comp[0], comp[1], "USD" if comp[0] else None),
                         employment_type="full-time", jd_text="JD", now=NOW)
    rec.update({"id": jid, "fit_score": fit, "fit_verdict": verdict, "sponsorship": sponsorship,
                "sponsorship_evidence": evidence, "status": "queued"})
    fa.save_job(root, rec)
    return jid


def world(root):
    a = _job(root, "acme-1", "Acme", "AI Engineer", fit=4.2, verdict="apply", days_old=9, sponsorship="yes",
             evidence="We sponsor visas.", comp=(180000, 250000))
    b = _job(root, "beta-1", "Beta", "Agent Engineer", fit=4.2, verdict="apply", days_old=1)              # same fit, fresher
    c = _job(root, "gizmo-1", "Gizmo", "ML Engineer", fit=3.7, verdict="maybe", days_old=0, sponsorship="yes")
    d = _job(root, "delta-1", "Delta", "Data Engineer", fit=4.5, verdict="skip", days_old=0)               # a skip ranks last
    e = _job(root, "eps-1", "Eps", "AI Engineer", fit=4.2, verdict="apply", days_old=1, sponsorship="yes")  # chance breaks the tie
    return [a, b, c, d, e]


def test_rank_is_verdict_band_then_fit_then_freshness_then_chance(root):
    ids = world(root)
    rows = sb.collect(root, ids, TODAY)
    assert [r["id"] for r in rows] == ["eps-1", "beta-1", "acme-1", "gizmo-1", "delta-1"]
    acme = next(r for r in rows if r["id"] == "acme-1")
    assert acme["pay"] == "$180K-$250K" and acme["posted"] == "2026-09-22" and acme["visa"] == "We sponsor visas."


def test_rows_come_from_hunt_md_row_lines(root):
    world(root)
    hunt = root / "hub" / "lanes" / "HUNT.md"
    hunt.parent.mkdir(parents=True)
    hunt.write_text("# HUNT\n\nROW Acme · AI Engineer | job acme-1 | fit 4.2 (apply) | posted 2026-09-22 | chance: x | why: y\n"
                    "ROW Gizmo · ML Engineer | job gizmo-1 | fit 3.7 (maybe) | posted ...\n"
                    "ROW Ghost · Role | job ghost-404 | fit 4.0 | ...\n"
                    "| ROW lines posted | 3 |\n")
    assert sb.row_ids(root) == ["acme-1", "gizmo-1", "ghost-404"]


def test_render_and_unknown_ids(root, capsys):
    world(root)
    assert sb.main(["--root", str(root), "--today", TODAY.isoformat(), "acme-1", "ghost-404"]) == 1
    out = capsys.readouterr()
    assert "| 1 | 4.2 | apply | Acme · AI Engineer |" in out.out and "Generated by scripts/scout_board.py" in out.out
    assert "ghost-404" in out.err and "\u2014" not in out.out


def test_read_only_by_default_and_write_on_request(root, capsys):
    ids = world(root)
    before = {p: p.read_bytes() for p in (root / "jobs").glob("*.md")}
    assert sb.main(["--root", str(root), "--today", TODAY.isoformat(), *ids]) == 0
    assert not (root / "research").exists()
    assert {p: p.read_bytes() for p in (root / "jobs").glob("*.md")} == before
    assert sb.main(["--root", str(root), "--today", TODAY.isoformat(), "--write", *ids]) == 0
    props, body = fm.load(root / "research" / "targets" / "scout-board-2026-10-01.md")
    assert props["written_by"].startswith("HUNT lane") and props["generated_by"] == "scripts/scout_board.py" and props["rows"] == 5
