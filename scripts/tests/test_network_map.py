def people(net):
    return {p["name"]: p for p in net["people"]}


def test_every_person_is_classified_by_company_tier_role_kind_school_and_warmth(js):
    net = nm.build(js, TODAY)
    p = people(net)
    assert (p["Marta Lopez"]["tier"], p["Marta Lopez"]["kind"], p["Marta Lopez"]["warmth"]) == ("dream", "hiring-manager", "dormant")
    assert p["Derek Osei"]["kind"] == "recruiter" and p["Derek Osei"]["tier"] == "untracked"
    assert (p["Leila Haddad"]["kind"], p["Leila Haddad"]["tier"], p["Leila Haddad"]["warmth"]) == ("founder", "strong", "warm")
    assert p["Priyanka Das"]["kind"] == "ai-engineer" and p["Sanjay Rao"]["kind"] == "engineer"
    assert p["Omar Siddiqui"]["kind"] == "other"
    assert p["Rebecca Stone"]["company"] == "unknown" and p["Rebecca Stone"]["kind"] == "unknown"
    jane = p["Jane Roe"]
    assert (jane["kind"], jane["school"], jane["warmth"], jane["tier"]) == ("recruiter", "EXSU", "warm", "dream")
    assert p["Marta Lopez"]["school"] == "unknown"                              # a silent record says unknown
    assert "email" not in json.dumps(net["people"]).lower().replace("emails", "")   # never an email address
    assert "jane@tidewater.example.com" not in json.dumps(net)


def test_hiring_posters_from_the_scout_join_the_network_connected_or_not(js):
    p = people(nm.build(js, TODAY))
    assert p["Leila Haddad"]["hiring_post"].startswith("news.ycombinator.com/item?id=1, 2026-09-30")
    assert p["Ana Ruiz"]["company"] == "Quarry" and p["Bo Chen"]["hiring_post"]
    assert p["Ana Ruiz"]["warmth"] == "none" and "hunt-scout" in p["Ana Ruiz"]["sources"]


def test_network_md_is_generated_with_referral_paths_per_next_up_company_and_the_lists(js):
    assert nm.main(["--root", str(js), "--today", "2026-10-01"]) == 0
    text = (js / "graph" / "NETWORK.md").read_text()
    assert text.startswith("<!-- GENERATED by scripts/network_map.py")
    paths = text.split("## Referral paths per NEXT-UP company", 1)[1].split("\n## ", 1)[0]
    assert "### Tidewater AI" in paths and "Jane Roe" in paths and "Marta Lopez" in paths
    assert "### Acme" in paths and "nobody in the network yet" in paths
    for section in ("## Recruiters", "## Hiring posters", "## Dormant warm ties", "## Counts"):
        assert section in text
    assert "Derek Osei" in text.split("## Recruiters", 1)[1].split("\n## ", 1)[0]
    dormant = text.split("## Dormant warm ties", 1)[1].split("\n## ", 1)[0]
    assert "Marta Lopez" in dormant and "Leila Haddad" not in dormant
    assert "X following: not read" in text


def test_x_following_is_read_from_its_cache_and_skipped_cleanly_while_credits_are_depleted(js):
    led = js / "state" / "x" / "usage.jsonl"
    led.parent.mkdir(parents=True)
    led.write_text(json.dumps({"at": "2026-10-01T19:10:34Z", "day": "2026-10-01", "endpoint": "search", "status": 402,
                               "usd": 0.0}) + "\n")
    net = nm.build(js, TODAY)
    assert net["x"]["state"] == "skipped" and "credits depleted" in net["x"]["note"] and "2026-10-01" in net["x"]["note"]
    (js / "state" / "x" / "following.json").write_text(json.dumps({"fetched_at": "2026-10-02T08:00:00Z", "users": [
        {"name": "Kai Lee", "username": "kailee", "description": "Recruiting for agents teams at Tidewater AI"}]}))
    net = nm.build(js, TODAY)
    kai = people(net)["Kai Lee"]
    assert net["x"]["state"] == "read" and kai["kind"] == "recruiter" and kai["x_handle"] == "kailee"
    assert kai["company"] == "unknown"                     # a bio is untrusted text: never parsed into a company


def test_for_query_filters_by_company_or_role_kind(js):
    net = nm.build(js, TODAY)
    names = {r["name"] for r in nm.for_query(net, "Tidewater AI")}
    assert names == {"Jane Roe", "Marta Lopez"}
    assert {r["name"] for r in nm.for_query(net, "recruiter")} == {"Jane Roe", "Derek Osei"}
    assert nm.for_query(net, "Nonexistent Co") == []


def test_a_missing_export_still_maps_prospects_and_says_the_export_is_missing(js):
    for p in (js / "state" / "harvest").glob("*.jsonl"):
        p.unlink()
    net = nm.build(js, TODAY)
    assert set(people(net)) == {"Jane Roe", "Leila Haddad", "Ana Ruiz", "Bo Chen"}
    assert "no parsed LinkedIn export" in net["linkedin"]["note"]


def test_records_are_never_written(js):
    before = {p: p.read_bytes() for p in js.rglob("*") if p.is_file()}
    nm.main(["--root", str(js), "--today", "2026-10-01"])
    changed = {p for p in js.rglob("*") if p.is_file() and before.get(p) != p.read_bytes()}
    assert changed == {js / "graph" / "NETWORK.md", js / "state" / "network" / "network-map.json"}


def test_the_json_rows_match_network_plans_shape(js):
    import network_plan
    nm.main(["--root", str(js), "--today", "2026-10-01"])
    rows = network_plan._yaml(js / "state" / "network" / "network-map.json", "people")
    marta = [r for r in rows if r["name"] == "Marta Lopez"][0]
    assert {"name", "company", "company_slug", "linkedin_url", "why", "connected"} <= set(marta)
    assert marta["connected"] is True and marta["company_slug"] == "tidewater-ai"
    assert "NEXT-UP" in marta["why"] and "dream" in marta["why"]
    ana = [r for r in rows if r["name"] == "Ana Ruiz"][0]
    assert ana["connected"] is False and ana["linkedin_url"] is None and "hiring post" in ana["why"]
