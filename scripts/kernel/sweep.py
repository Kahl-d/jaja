def parse_ts(value: Any) -> dt.datetime | None:
    """An aware datetime from an ISO timestamp (naive = UTC), or None."""
    if isinstance(value, dt.datetime):
        return value if value.tzinfo else value.replace(tzinfo=dt.timezone.utc)
    if not isinstance(value, str) or not re.match(r"^\d{4}-\d{2}-\d{2}", value.strip()):
        return None
    try:
        stamp = dt.datetime.fromisoformat(value.strip().replace("Z", "+00:00"))
    except ValueError:
        return None
    return stamp if stamp.tzinfo else stamp.replace(tzinfo=dt.timezone.utc)


def _feed_structure_errors(data: Any) -> list[str]:
    if not isinstance(data, dict):
        return ["top level is not a JSON object"]
    errors = []
    if not isinstance(data.get("project"), str) or not data["project"].strip():
        errors.append("project must be a non-empty string")
    if parse_ts(data.get("generated_at")) is None:
        errors.append(f"generated_at {data.get('generated_at')!r} is not an ISO timestamp")
    errors += [f"{key} must be a list" for key in FEED_LISTS if not isinstance(data.get(key), list)]
    return errors


def _feed_item_error(key: str, item: Any) -> str | None:
    if not isinstance(item, dict):
        return "not an object"
    if not isinstance(item.get("title"), str) or not item["title"].strip():
        return "title must be a non-empty string"
    if not isinstance(item.get("link"), str):
        return "link must be a string"
    if key == "needs_you" and not isinstance(item.get("why"), str):
        return "why must be a string"
    if key == "deadlines":
        date = item.get("date")
        if not isinstance(date, str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", date) or as_date(date) is None:
            return f"date {date!r} is not YYYY-MM-DD"
        if not isinstance(item.get("hard"), bool):
            return f"hard {item.get('hard')!r} is not true or false"
    return None


def validate_feed(data: Any) -> list[str]:
    """Every problem in a home-feed.json object: the structure first, then each item as `<list>[<i>]: ...`."""
    errors = _feed_structure_errors(data)
    if errors[:1] == ["top level is not a JSON object"]:
        return errors
    for key in FEED_LISTS:
        for i, item in enumerate(data.get(key) if isinstance(data.get(key), list) else []):
            problem = _feed_item_error(key, item)
            if problem:
                errors.append(f"{key}[{i}]: {problem}")
    return errors


def load_feeds(root: Path) -> tuple[list[dict[str, Any]], list[str]]:
    """(feeds, errors): readable feeds with only their valid items; one error per bad feed or bad item."""
    feeds: list[dict[str, Any]] = []
    errors: list[str] = []
    for path in sorted(p for g in FEED_GLOBS for p in Path(root).glob(g) if p.is_file()):
        where = rel(root, path)
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except (OSError, UnicodeDecodeError, json.JSONDecodeError) as exc:
            errors.append(f"{where}: unreadable ({exc})")
            continue
        problems = _feed_structure_errors(data)
        if problems:
            errors.append(f"{where}: " + "; ".join(problems))
            continue
        feed = {"project": data["project"].strip(), "path": where, "generated_at": data["generated_at"]}
        for key in FEED_LISTS:
            kept = []
            for i, item in enumerate(data[key]):
                problem = _feed_item_error(key, item)
                if problem:
                    errors.append(f"{where}: {key}[{i}]: {problem}")
                else:
                    kept.append(item)
            feed[key] = kept
        feeds.append(feed)
    return feeds, errors


def _default_now(today: dt.date) -> dt.datetime:
    """The wall clock when the sweep is for today, else 12:00 UTC of the given day (replayable runs)."""
    if today == dt.date.today():
        return dt.datetime.now(dt.timezone.utc)
    return dt.datetime.combine(today, dt.time(12, 0), tzinfo=dt.timezone.utc)


def _merge_feeds(docs: dict[str, Any], today: dt.date, now: dt.datetime, horizon: dt.date, needs_you: list,
                 overdue: list, due_soon: list, today_items: list) -> list[dict[str, Any]]:
    summary = []
    for feed in docs.get("feeds", []):
        project = feed["project"]
        built = parse_ts(feed["generated_at"])
        stale = bool(built and (now - built).total_seconds() > FEED_STALE_HOURS * 3600)
        summary.append({"project": project, "path": feed["path"], "generated_at": feed["generated_at"], "stale": stale})
        tag = {"id": project, "kind": "feed", "project": project}
        if stale:
            needs_you.append({**tag, "title": f"{project} board is stale (last built {built.date().isoformat()})",
                              "why": f"stale: its feed is older than {FEED_STALE_HOURS} h; rerun its board script",
                              "path": feed["path"]})
        for item in feed["needs_you"]:
            needs_you.append({**tag, "title": item["title"], "why": item["why"], "path": item["link"]})
        for item in feed["deadlines"]:
            day = as_date(item["date"])
            entry = {**tag, "title": item["title"], "date": day.isoformat(), "hard": item["hard"],
                     "days": (day - today).days, "path": item["link"]}
            if day < today:
                overdue.append(entry)
            elif day <= horizon:
                due_soon.append(entry)
        for item in feed["today"]:
            today_items.append({**tag, "title": item["title"], "path": item["link"]})
    return summary


def _schema_error_count(root: Any) -> int:
    try:
        import lint  # local module; may be absent while the kernel is being built

        return len(lint.check_schemas(root))
    except Exception:
        return 0


# --------------------------------------------------------------------------- #
# computing
# --------------------------------------------------------------------------- #
def _task_row(doc: dict[str, Any]) -> dict[str, Any]:
    m = doc["meta"]
    return {
        "id": str(m.get("id") or Path(doc["path"]).stem),
        "title": str(m.get("title") or Path(doc["path"]).stem),
        "status": m.get("status"),
        "type": m.get("type"),
        "owner": m.get("owner"),
        "priority": m.get("priority"),
        "domain": m.get("domain"),
        "due": iso(m.get("due")),
        "hard_deadline": iso(m.get("hard_deadline")),
        "path": doc["path"],
    }


def compute(docs: dict[str, Any], today: dt.date, now: dt.datetime | None = None) -> dict[str, Any]:
    horizon = today + dt.timedelta(days=DUE_SOON_DAYS)
    now = now or _default_now(today)
    needs_you: list[dict[str, Any]] = []
    overdue: list[dict[str, Any]] = []
    due_soon: list[dict[str, Any]] = []
    today_items: list[dict[str, Any]] = []
    windows_open: list[dict[str, Any]] = []
    waiting: list[dict[str, Any]] = []

    for doc in docs.get("tasks", []):
        m = doc["meta"]
        if "_error" in m:
            continue
        status = str(m.get("status") or "open")
        if status in CLOSED:
            continue
        row = _task_row(doc)
        if status == "needs-human":
            needs_you.append({**row, "kind": "task", "why": "needs-human"})
        if status == "waiting":
            waiting.append({**row, "waiting_on": m.get("waiting_on"), "follow_up": iso(m.get("follow_up"))})
        due = as_date(m.get("due"))
        hard = as_date(m.get("hard_deadline"))
        clock = min(d for d in (due, hard) if d) if (due or hard) else None
        if clock:
            entry = {**row, "date": clock.isoformat(), "hard": bool(hard), "days": (clock - today).days}
            if clock < today:
                overdue.append(entry)
            elif clock <= horizon:
                due_soon.append(entry)
        scheduled = as_date(m.get("scheduled"))
        if (scheduled and scheduled <= today) or (clock and clock == today) or status == "in-progress":
            today_items.append(row)
        opens = as_date(m.get("window_opens"))
        if opens and opens <= today and (clock is None or clock >= today):
            windows_open.append({**row, "window_opens": opens.isoformat(), "closes": clock.isoformat() if clock else None})

    for doc in docs.get("approvals", []):
        m = doc["meta"]
        if "_error" in m or str(m.get("status", "pending")) != "pending":
            continue
        needs_you.append(
            {
                "id": str(m.get("id") or Path(doc["path"]).stem),
                "title": f"{m.get('action', 'approval')} → {m.get('target', '')}".strip(" →"),
                "kind": "approval",
                "why": "pending approval",
                "requested_by": m.get("requested_by"),
                "ticket": m.get("ticket"),
                "path": doc["path"],
            }
        )

    feeds = _merge_feeds(docs, today, now, horizon, needs_you, overdue, due_soon, today_items)
    overdue.sort(key=lambda e: e["date"])
    due_soon.sort(key=lambda e: e["date"])
    prio = {"P0": 0, "P1": 1, "P2": 2, "P3": 3}
    today_items.sort(key=lambda r: (prio.get(str(r.get("priority")), 9), r["id"]))
    needs_you.sort(key=lambda e: (e["kind"] != "approval", e["id"]))

    roles, roles_by_status = [], {}
    for doc in docs.get("roles", []):
        m = doc["meta"]
        name = str(m.get("name") or Path(doc["path"]).stem)
        status = str(m.get("status") or "unknown")
        roles.append(
            {
                "name": name,
                "title": m.get("title"),
                "department": m.get("department"),
                "tier_max": m.get("tier_max"),
                "model": m.get("model"),
                "status": status,
                "purpose": m.get("purpose"),
                "path": doc["path"],
            }
        )
        roles_by_status.setdefault(status, []).append(name)
    roles.sort(key=lambda r: r["name"])
    roles_by_status = {k: sorted(v) for k, v in sorted(roles_by_status.items())}

    runs = docs.get("runs", {})
    routines = []
    for doc in docs.get("routines", []):
        m = doc["meta"]
        name = str(m.get("name") or Path(doc["path"]).stem)
        routines.append(
            {
                "name": name,
                "enabled": m.get("enabled"),
                "runs_on": m.get("runs_on"),
                "schedule": m.get("schedule"),
                "action": m.get("action"),
                "owner": m.get("owner"),
                "last_run": runs.get(name),
                "path": doc["path"],
            }
        )

    return {
        "date": today.isoformat(),
        "needs_you": needs_you,
        "today_items": today_items,
        "windows_open": windows_open,
        "waiting": waiting,
        "deadlines": {"overdue": overdue, "due_soon": due_soon},
        "inbox_count": docs.get("inbox_count", 0),
        "roles": roles,
        "roles_by_status": roles_by_status,
        "routines": routines,
        "skills": docs.get("skills", []),
        "lanes": docs.get("lanes", []),
        "schema_errors": docs.get("schema_errors", 0),
        "feeds": feeds,
        "feed_errors": list(docs.get("feed_errors", [])),
    }


# --------------------------------------------------------------------------- #
# rendering
# --------------------------------------------------------------------------- #
def _rows(lines: list[str], rows: list[str], empty: str = "- nothing") -> None:
    if not rows:
        lines.append(empty)
        return
    lines.extend(rows[:ROW_CAP])
    if len(rows) > ROW_CAP:
        lines.append(f"- ... and {len(rows) - ROW_CAP} more")


def _hard_tag(entry: dict[str, Any]) -> str:
    """' HARD' when the task carries a hard deadline; shows the hard date when the soft due wins the clock."""
    if not entry.get("hard"):
        return ""
    hd = entry.get("hard_deadline")
    return f" HARD {hd}" if hd and hd != entry["date"] else " HARD"


def _fit(lines: list[str], footer: str) -> list[str]:
    """Keep the document within HOME_MAX_LINES by trimming from the bottom sections up."""
    while len(lines) + 2 > HOME_MAX_LINES:
        # drop the last plain row that is not a heading / blank
        for i in range(len(lines) - 1, 0, -1):
            if lines[i].startswith("- ") and not lines[i].startswith("- ..."):
                del lines[i]
                break
        else:
            break
    return lines + ["", footer]


def render(data: dict[str, Any], generated_at: str) -> str:
    L: list[str] = [md_header(), f"# Agency status · {data['date']}", ""]

    L.append("## Needs you")
    _rows(
        L,
        [f"- [{e['id']}] {e['title']} ({e['why']}) → `{e['path']}`" for e in data["needs_you"]],
        "- nothing needs you",
    )
    L.append("")

    L.append("## Today")
    rows = [f"- [{r['id']}] {r['title']}" if r.get("kind") == "feed" else
            f"- [{r['id']}] {r['title']} · {r.get('priority') or ''} · {r.get('status')}" for r in data["today_items"]]
    rows += [f"- window open: [{w['id']}] {w['title']} (closes {w['closes'] or 'n/a'})" for w in data["windows_open"]]
    rows += [f"- waiting: [{w['id']}] {w['title']} on {w.get('waiting_on') or '?'} (follow up {w.get('follow_up') or 'n/a'})" for w in data["waiting"]]
    _rows(L, rows, "- nothing scheduled")
    L.append("")

    L.append("## Deadlines")
    rows = [f"- OVERDUE {e['date']} ({-e['days']}d){_hard_tag(e)} [{e['id']}] {e['title']}" for e in data["deadlines"]["overdue"]]
    rows += [f"- {e['date']} (in {e['days']}d){_hard_tag(e)} [{e['id']}] {e['title']}" for e in data["deadlines"]["due_soon"]]
    _rows(L, rows, f"- nothing overdue or due within {DUE_SOON_DAYS} days")
    L.append("")

    L.append("## Inbox")
    L.append(f"- {data['inbox_count']} item(s) in `work/inbox/` (the runtime folder)")
    L.append("")

    L.append("## Agents")
    if data["roles"]:
        counts = ", ".join(f"{k}: {len(v)}" for k, v in data["roles_by_status"].items())
        lanes = ", ".join(x["type"] for x in data["lanes"]) or "none"
        L.append(f"- {len(data['roles'])} role card(s) ({counts}) · {len(data['skills'])} skill(s) · lanes: {lanes}")
        _rows(L, [f"- {r['name']} · {r.get('title')} · {r.get('tier_max')} · {r['status']}" for r in data["roles"]])
    else:
        L.append("- no role cards yet")
    L.append("")

    L.append("## Routines")
    _rows(
        L,
        [
            f"- {r['name']} · {'on' if r.get('enabled') else 'off'} · {r.get('runs_on')} `{r.get('schedule')}` · last run {r.get('last_run') or 'never'}"
            for r in data["routines"]
        ],
        "- no routines yet",
    )

    footer = f"last sweep {generated_at} · {data['schema_errors']} schema errors"
    return "\n".join(_fit(L, footer)) + "\n"


def build_home(docs: dict[str, Any], today: dt.date, generated_at: str | None = None,
               now: dt.datetime | None = None) -> tuple[str, dict[str, Any]]:
    """Pure: docs (from load_docs) + today → (HOME.md text, HOME.json data). `now` (aware) dates the
    36-hour feed staleness check; default: the wall clock for today, else 12:00 UTC of `today`."""
    generated_at = generated_at or dt.datetime.now().isoformat(timespec="seconds")
    data = compute(docs, today, now)
    data["generated_at"] = generated_at
    md = render(data, generated_at)
    return md, data


# --------------------------------------------------------------------------- #
# writing
# --------------------------------------------------------------------------- #
def _write_json(path: Path, source: str, payload: dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    body = {"_generated": generated_note(source), **payload}
    path.write_text(json.dumps(body, indent=2, ensure_ascii=False, default=str) + "\n", encoding="utf-8")


def write_registries(root: Any, data: dict[str, Any]) -> list[Path]:
    reg = as_roots(root).runtime / "registry"
    written = []
    for name, source, payload in (
        ("agents", "agents", {"agents": data["roles"]}),
        ("skills", "skills", {"skills": data["skills"]}),
        ("routines", "routines, logs/runs", {"routines": data["routines"]}),
        ("lanes", "lanes", {"lanes": data["lanes"]}),
    ):
        p = reg / f"{name}.json"
        _write_json(p, source, {"generated_at": data["generated_at"], **payload})
        written.append(p)
    return written


def main(root: Any = None, today: dt.date | None = None) -> None:
    r = as_roots(root)
    today = today or dt.date.today()
    docs = load_docs(r)
    md, data = build_home(docs, today)
    r.runtime.mkdir(parents=True, exist_ok=True)
    (r.runtime / "HOME.md").write_text(md, encoding="utf-8")
    _write_json(r.runtime / "HOME.json", SOURCES, data)
    write_registries(r, data)


def _cli() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    add_root_args(ap)
    ap.add_argument("--today", default=None, help="YYYY-MM-DD (default: today)")
    args = ap.parse_args()
    today = dt.date.fromisoformat(args.today) if args.today else dt.date.today()
    r = from_args(args)
    main(r, today)
    home = r.runtime / "HOME.md"
    print(f"sweep: wrote {home} ({len(home.read_text(encoding='utf-8').splitlines())} lines)")
