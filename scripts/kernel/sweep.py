#!/usr/bin/env python3
"""sweep.py - rebuild the status briefing (HOME.md / HOME.json) and the registries from files.

No LLM, no network. Reads (three roots, scripts/kernel/roots.py; `--root R` treats one folder as all three):

    runtime  work/tasks/*.md              tasks (schemas/task.yaml; optional)
             work/approvals/*.md          approvals (the queue approvals.py writes)
             work/inbox/*                 counted only (watchdog alerts land here)
             logs/runs/<routine>/<date>.md   receipts
    code     agents/*.md                  role cards
             routines/*.yaml              routine specs (all ship disabled)
             skills/*/SKILL.md            skills
             lanes/*/LANE.yaml            lane types
    data     state/home-feed.json         the board feed (below); projects/*/state/home-feed.json for more than one

Department feed. The board script (scripts/dashboard.py) writes state/home-feed.json = {"project", "generated_at": ISO,
"needs_you": [{"title","why","link"}], "deadlines": [{"title","date": "YYYY-MM-DD","hard": bool,"link"}],
"today": [{"title","link"}]}. The sweep merges needs_you (tagged with the project), deadlines (overdue / due within 7
days, the task rule) and today items; a feed older than 36 hours adds a needs-you line saying that board is stale. An
unreadable or malformed feed, or a malformed item, is skipped and counted as a schema error. Naive timestamps are UTC.

Writes (all with the GENERATED header / "_generated" key), under the RUNTIME root:

    HOME.md (<=150 lines), HOME.json         the briefing: needs you, today, deadlines, inbox, agents, routines
    registry/{agents,skills,routines,lanes}.json

(The file names are kept: scripts/recruiter_sweep.py reads <runtime>/HOME.json for needs-you rows.)

Interface:
    load_docs(root) -> dict
    build_home(docs, today, generated_at=None, now=None) -> (markdown, data)      pure, for tests
    validate_feed(data) -> list[str]                 every problem in a home-feed.json object
    main(root, today) -> None
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import frontmatter as fm  # noqa: E402
from roots import Roots, add_root_args, from_args, roots as as_roots  # noqa: E402

SELF = "scripts/kernel/sweep.py"
SOURCES = "work/, logs/runs/, state/home-feed.json, agents/, routines/, skills/, lanes/"
HOME_MAX_LINES = 150
ROW_CAP = 12  # rows per list before "... and N more"
DUE_SOON_DAYS = 7
CLOSED = {"done", "cancelled", "archived"}
FEED_GLOBS = ("state/home-feed.json", "projects/*/state/home-feed.json")   # under the data folder
FEED_STALE_HOURS = 36
FEED_LISTS = ("needs_you", "deadlines", "today")


def md_header(source: str = SOURCES) -> str:
    return f"<!-- GENERATED by {SELF} from {source} - do not edit -->"


def generated_note(source: str = SOURCES) -> str:
    return f"GENERATED by {SELF} from {source} - do not edit"


# --------------------------------------------------------------------------- #
# helpers
# --------------------------------------------------------------------------- #
def as_date(value: Any) -> dt.date | None:
    if value is None or value == "":
        return None
    if isinstance(value, dt.datetime):
        return value.date()
    if isinstance(value, dt.date):
        return value
    s = str(value).strip().strip('"').strip("'")
    try:
        return dt.date.fromisoformat(s[:10])
    except ValueError:
        return None


def iso(value: Any) -> str | None:
    d = as_date(value)
    return d.isoformat() if d else None


def rel(root: Path, path: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return path.as_posix()


def _plain(value: Any) -> Any:
    """Make a frontmatter value JSON-safe."""
    if isinstance(value, (dt.date, dt.datetime)):
        return value.isoformat()
    if isinstance(value, dict):
        return {str(k): _plain(v) for k, v in value.items()}
    if isinstance(value, list):
        return [_plain(v) for v in value]
    return value


def _load_yaml_file(path: Path) -> dict[str, Any]:
    try:
        data = fm.parse_yaml(path.read_text(encoding="utf-8"))
    except (fm.FrontmatterError, UnicodeDecodeError) as exc:
        return {"_error": str(exc)}
    return data if isinstance(data, dict) else {"_error": "top level is not a mapping"}


def _docs(root: Path, glob: str, skip_readme: bool = True) -> list[dict[str, Any]]:
    out = []
    for path, meta, body in fm.iter_docs(root, glob):
        if skip_readme and path.name.upper() == "README.MD":
            continue
        if path.name.startswith((".", "_")):
            continue
        out.append({"path": rel(root, path), "meta": meta, "body": body})
    return out


# --------------------------------------------------------------------------- #
# loading
# --------------------------------------------------------------------------- #
def load_docs(root: Any = None) -> dict[str, Any]:
    r = as_roots(root)
    docs: dict[str, Any] = {"root": str(r.runtime)}
    docs["tasks"] = _docs(r.runtime, "work/tasks/*.md")
    docs["approvals"] = _docs(r.runtime, "work/approvals/*.md")
    inbox = r.runtime / "work" / "inbox"
    docs["inbox_count"] = (
        sum(1 for p in inbox.iterdir() if p.is_file() and not p.name.startswith(".") and p.name.upper() != "README.MD")
        if inbox.is_dir()
        else 0
    )
    docs["roles"] = _docs(r.code, "agents/*.md")

    routines = []
    for path in sorted((r.code / "routines").glob("*.yaml")) if (r.code / "routines").is_dir() else []:
        if "fixtures" in path.parts or path.name.startswith((".", "_")):
            continue
        routines.append({"path": rel(r.code, path), "meta": _load_yaml_file(path)})
    docs["routines"] = routines

    runs: dict[str, str] = {}
    runs_dir = r.runtime / "logs" / "runs"
    if runs_dir.is_dir():
        for rdir in sorted(p for p in runs_dir.iterdir() if p.is_dir()):
            receipts = sorted(p.stem for p in rdir.iterdir() if p.is_file() and not p.name.startswith("."))
            if receipts:
                runs[rdir.name] = receipts[-1][:10]
    docs["runs"] = runs

    docs["skills"] = [
        {"name": meta.get("name") or path.parent.name, "description": meta.get("description", ""), "path": rel(r.code, path.parent)}
        for path, meta, _ in fm.iter_docs(r.code, "skills/*/SKILL.md")
    ]
    lanes = []
    for path in sorted((r.code / "lanes").glob("*/LANE.yaml")) if (r.code / "lanes").is_dir() else []:
        meta = _load_yaml_file(path)
        lanes.append({"type": str(meta.get("type") or path.parent.name), "title": meta.get("title"),
                      "roster": meta.get("roster") or [], "path": rel(r.code, path)})
    docs["lanes"] = lanes

    docs["feeds"], docs["feed_errors"] = load_feeds(r.data)
    docs["schema_errors"] = _schema_error_count(r) + len(docs["feed_errors"])
    return docs


