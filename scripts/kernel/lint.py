def _ruling_rows(r: Roots) -> tuple[list[dict[str, Any]] | None, str | None]:
    path = r.data / "hub" / "rulings.yaml"
    if not path.is_file():
        return None, None
    try:
        data = fm.parse_yaml(path.read_text(encoding="utf-8")) or {}
    except fm.FrontmatterError as exc:
        return None, str(exc)
    rows = data.get("rulings") if isinstance(data, dict) else data
    if rows is None:
        return [], None
    if not isinstance(rows, list):
        return None, "rulings: is not a list"
    return rows, None


def check_rulings(root: Any = None) -> list[Finding]:
    """Well-formedness of <data>/hub/rulings.yaml: unique ids, ISO dates, a known status, scope lanes that exist.
    No registry is fine (a new data folder has none)."""
    r = as_roots(root)
    rows, err = _ruling_rows(r)
    where = "hub/rulings.yaml"
    if err:
        return [Finding(where, "frontmatter-error", err)]
    if rows is None:
        return []
    out: list[Finding] = []
    seen: set[str] = set()
    for i, row in enumerate(rows):
        if not isinstance(row, dict):
            out.append(Finding(where, "ruling-shape", f"entry {i} is not a mapping"))
            continue
        rid = str(row.get("id") or "")
        if not RULING_ID_RE.fullmatch(rid):
            out.append(Finding(where, "ruling-id", f"entry {i}: id {rid!r} is not <LETTERS>-<number> (R-12, R-12a)"))
        elif rid in seen:
            out.append(Finding(where, "ruling-id", f"{rid}: duplicate id"))
        seen.add(rid)
        if row.get("date") not in (None, "") and not _is_date(row["date"]):
            out.append(Finding(where, "ruling-date", f"{rid}: date {row['date']!r} is not an ISO date"))
        status = str(row.get("status") or "")
        if status not in RULING_STATUSES:
            out.append(Finding(where, "ruling-status", f"{rid}: status {status!r} not in {sorted(RULING_STATUSES)}"))
    return out


def check_ruling_scopes(root: Any = None) -> list[Finding]:
    """Warning: a standing ruling's scope names a lane that is neither a lane type of this repo, a lane of the
    programme (hub/programme.json), nor all/orch."""
    r = as_roots(root)
    rows, _ = _ruling_rows(r)
    known = {p.name.lower() for p in (r.code / "lanes").glob("*") if p.is_dir()} | {"all", "orch", "orchestrator", "main"}
    try:
        import json
        prog = json.loads((r.data / "hub" / "programme.json").read_text(encoding="utf-8"))
        known |= {str(x.get("scope") or "").lower() for x in prog.get("lanes") or [] if isinstance(x, dict)}
    except (OSError, ValueError, AttributeError):
        pass
    out: list[Finding] = []
    for row in rows or []:
        if not isinstance(row, dict) or str(row.get("status")) != "standing":
            continue
        scope = row.get("scope") or {}
        for lane in (scope.get("lanes") if isinstance(scope, dict) else None) or []:
            if str(lane).lower() not in known:
                out.append(Finding("hub/rulings.yaml", "ruling-scope", f"{row.get('id')}: scope lane {lane!r} is not a lane "
                                                                       "type of this repo, a programme lane, or all/orch"))
    return out


def check_ruling_cites(root: Any = None) -> list[Finding]:
    """Warning: a card, skill, lane or playbook cites a ruling id the registry does not hold."""
    r = as_roots(root)
    rows, _ = _ruling_rows(r)
    ids = {str(x.get("id")) for x in rows or [] if isinstance(x, dict)}
    if not ids:
        return []
    # the citation pattern follows the registry's own id prefixes (R-12, X-7, ...)
    prefixes = sorted({i.split("-")[0] for i in ids if "-" in i and RULING_ID_RE.fullmatch(i)})
    if not prefixes:
        return []
    cite = re.compile(r"(?<![\w-])(?:" + "|".join(map(re.escape, prefixes)) + r")-\d+[a-z]?(?![\w-])")
    out: list[Finding] = []
    for pattern in ("agents/*.md", "skills/*/SKILL.md", "lanes/*/AGENT.md", "playbooks/**/*.md"):
        for path in sorted(r.code.glob(pattern)):
            try:
                text = path.read_text(encoding="utf-8")
            except (OSError, UnicodeDecodeError):
                continue
            missing = sorted({m.group(0) for m in cite.finditer(text)} - ids)
            if missing:
                out.append(Finding(_rel(r.code, path), "ruling-cited", "cites " + ", ".join(missing) + " (not in hub/rulings.yaml)"))
    return out


def warnings(root: Any = None) -> list[Finding]:
    """Findings that are reported but do not fail the run: tag-unknown (while enforcement is 'warning') and ruling-cited."""
    r = as_roots(root)
    out: list[Finding] = []
    if load_tag_vocabulary(r)["enforcement"] == "warning":
        out += check_tags(r)
    out += check_ruling_scopes(r)
    out += check_ruling_cites(r)
    return out


# --------------------------------------------------------------------------- #
# skills
# --------------------------------------------------------------------------- #
def check_skills(root: Any = None) -> list[Finding]:
    r = as_roots(root)
    out: list[Finding] = []
    for path, meta, _ in fm.iter_docs(r.code, "skills/*/SKILL.md"):
        rel = _rel(r.code, path)
        if "_error" in meta:
            out.append(Finding(rel, "frontmatter-error", meta["_error"]))
            continue
        desc = meta.get("description")
        if not desc:
            out.append(Finding(rel, "skill-description-missing", "SKILL.md needs a description saying when to use it"))
        elif len(str(desc)) > SKILL_DESC_MAX:
            out.append(Finding(rel, "skill-description-length", f"description is {len(str(desc))} chars (max {SKILL_DESC_MAX})"))
        name = meta.get("name")
        if name and str(name) != path.parent.name:
            out.append(Finding(rel, "skill-name-mismatch", f"name '{name}' differs from folder '{path.parent.name}'"))
    return out


# --------------------------------------------------------------------------- #
# AGENTS.md budget
# --------------------------------------------------------------------------- #
def check_agents_md(root: Any = None) -> list[Finding]:
    r = as_roots(root)
    out: list[Finding] = []
    for base in dict.fromkeys([r.code, r.data]):
        p = base / "AGENTS.md"
        if p.is_file():
            n = len(p.read_text(encoding="utf-8").splitlines())
            if n > AGENTS_MAX_LINES:
                out.append(Finding(_rel(base, p), "agents-md-lines", f"{n} lines (max {AGENTS_MAX_LINES})"))
    return out


# --------------------------------------------------------------------------- #
# generated files
# --------------------------------------------------------------------------- #
def check_generated(root: Any = None) -> list[Finding]:
    code = as_roots(root).code
    report = sync.diff(code)
    out = [Finding(p, "generated-missing", "adapter not generated yet; run python3 scripts/kernel/sync.py") for p in report["missing"]]
    out += [Finding(p, "generated-edited", "differs from regeneration (hand edit?); edit the source, then run sync.py") for p in report["changed"]]
    out += [Finding(p, "generated-stale", "carries a GENERATED header but no source produces it; run sync.py to remove") for p in report["stale"]]
    return out


# --------------------------------------------------------------------------- #
# entry points
# --------------------------------------------------------------------------- #
def run(root: Any = None) -> list[Finding]:
    r = as_roots(root)
    findings: list[Finding] = []
    findings += check_schemas(r)
    findings += check_links(r)
    findings += check_rulings(r)
    findings += check_skills(r)
    findings += check_agents_md(r)
    findings += check_generated(r)
    if load_tag_vocabulary(r)["enforcement"] == "error":
        findings += check_tags(r)
    return findings


def main(root: Any = None, list_warnings: bool = False) -> int:
    """Print errors (they set the return value) and warnings (counted per code; listed with list_warnings)."""
    findings = run(root)
    for f in findings:
        print(str(f))
    print(f"lint: {len(findings)} finding(s)" if findings else "lint: clean")
    warns = warnings(root)
    if warns:
        if list_warnings:
            for w in warns:
                print(f"warning: {w}")
        counts: dict[str, int] = {}
        for w in warns:
            counts[w.code] = counts.get(w.code, 0) + 1
        print(f"lint: {len(warns)} warning(s) (" + ", ".join(f"{c}: {n}" for c, n in sorted(counts.items()))
              + ")" + ("" if list_warnings else "; --warnings lists them"))
    return len(findings)


def _cli() -> int:
    ap = argparse.ArgumentParser(description="Validate schemas, links, rulings, skills, AGENTS.md budgets and generated adapters.")
    add_root_args(ap)
    ap.add_argument("--warnings", action="store_true", help="list every warning (tag-unknown, ruling-cited), not only counts")
    args = ap.parse_args()
    return 1 if main(from_args(args), list_warnings=args.warnings) else 0


if __name__ == "__main__":
    sys.exit(_cli())
