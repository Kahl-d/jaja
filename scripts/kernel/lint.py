#!/usr/bin/env python3
"""lint.py - validate the agency's files. Prints findings, returns their count.

Where things are (scripts/kernel/roots.py): role cards, skills, lanes, routines, schemas and templates are CODE
(this repo); records (applications, companies, prospects, jobs, outbox ...) are DATA (your data folder); approvals
and run receipts are RUNTIME. `--root R` treats one folder as all three (the layout of the repo itself).

Checks
    schema        every record against schemas/<type>.yaml (required keys, enums, date fields, patterns, the
                  done->evidence rule, role-tools-empty: a role card's tools_allow may not be an empty list).
                  Cards and routines are read from the code root, approvals from the runtime root, the rest from the data root.
    links         broken [[wikilinks]] in the data folder: the slug must be a file or folder there (or a card or skill);
                  a path-qualified link ([[companies/acme|acme]]) must name that file (or a unique path suffix)
    schema-links  a schema's `wikilink_lists:` fields (records' `links:`) hold a list of [[...]] strings
    rulings       <data>/hub/rulings.yaml: unique well-formed ids, ISO dates, a known status
    tag-unknown   a `tags:` value in the data folder outside schemas/tags.yaml (a warning while the file says
                  `enforcement: warning`, an error once it says `enforcement: error`)
    skills        SKILL.md description present, <= 300 chars, name = folder
    agents-md     AGENTS.md (code root and data folder) <= 200 lines
    generated     adapters unchanged vs `sync --check` (missing / hand-edited / stale)
Warnings (printed and counted; the exit code ignores them):
    ruling-scope  a standing ruling names a lane that is neither a lane type, a programme lane, nor all/orch
    ruling-cited  a card, skill, lane or playbook cites a ruling id (R-12) that the registry does not hold (only
                  when the registry holds at least one ruling)

Interface:
    run(root=None) -> list[Finding]            errors: what fails the run (root: a path = one folder for all three
                                               roots, a roots.Roots, or None for the configured roots)
    warnings(root=None) -> list[Finding]
    check_schemas(root) -> list[Finding]       also used by sweep for its footer count
    main(root, list_warnings=False) -> int     number of findings (0 = clean)

CLI:  python3 scripts/kernel/lint.py [--root PATH | --code P --data P --runtime P] [--warnings]
      (--warnings lists every warning; without it only their counts per code are printed)
"""
from __future__ import annotations

import argparse
import datetime as dt
import os
import re
import sys
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Iterable
from urllib.parse import unquote

sys.path.insert(0, str(Path(__file__).resolve().parent))
import frontmatter as fm  # noqa: E402
import sync  # noqa: E402
from roots import Roots, add_root_args, from_args, roots as as_roots  # noqa: E402

AGENTS_MAX_LINES = 200
SKILL_DESC_MAX = 300
SKIP_DIR_NAMES = {".git", ".claude", ".codex", ".agents", "node_modules", "__pycache__", ".obsidian", "fixtures",
                  "runtime", ".cache", "vault", "archive"}

WIKILINK_RE = re.compile(r"\[\[([^\]\|#]+)(?:#[^\]\|]*)?(?:\|[^\]]*)?\]\]")
TAGS_FILE = Path("schemas") / "tags.yaml"
GENERATED_RE = re.compile(r"GENERATED by ")
FENCE_RE = re.compile(r"```.*?```", re.DOTALL)
INLINE_CODE_RE = re.compile(r"`[^`\n]*`")
RULING_ID_RE = re.compile(r"[A-Z]{1,6}-\d+[a-z]?")
RULING_STATUSES = {"standing", "history", "superseded", "withdrawn", "expired"}

# top-level folders of the code repo: not data, skipped by the link scan when one folder is all three roots
CODE_DIRS = {"agents", "skills", "lanes", "routines", "schemas", "templates", "hooks", "scripts", "docs", "playbooks",
             "mcp", "tools", "dashboard", "config", "examples", "evals"}

# which root a record type lives in; every other type lives in the data folder
RECORD_ROOT = {"role": "code", "routine": "code", "automation": "code", "approval": "runtime", "task": "runtime"}
# schema globs are written relative to the root that holds the record type; no re-pointing is needed
LEGACY_GLOBS: dict[str, str] = {}

@dataclass(frozen=True)
class Finding:
    path: str
    code: str
    message: str

    def __str__(self) -> str:
        return f"{self.path}: [{self.code}] {self.message}"


def _rel(root: Path, path: Path) -> str:
    try:
        return path.relative_to(root).as_posix()
    except ValueError:
        return path.as_posix()


def _skip(path: Path) -> bool:
    return path.name.upper() == "README.MD" or path.name.startswith((".", "_"))


def _is_date(value: Any) -> bool:
    if isinstance(value, (dt.date, dt.datetime)):
        return True
    s = str(value).strip()
    for fmt in (dt.date.fromisoformat, dt.datetime.fromisoformat):
        try:
            fmt(s.replace("Z", "+00:00"))
            return True
        except ValueError:
            continue
    return False


def _routine_stamp(value: Any) -> dt.datetime | None:
    """A routine's `installed:` or `last_reviewed:` as naive local time (a zoned value converted); None if unreadable."""
    if isinstance(value, dt.datetime):
        return value.astimezone().replace(tzinfo=None) if value.tzinfo else value
    if isinstance(value, dt.date):
        return dt.datetime.combine(value, dt.time.min)
    try:
        stamp = dt.datetime.fromisoformat(str(value).strip().replace("Z", "+00:00"))
    except ValueError:
        return None
    return stamp.astimezone().replace(tzinfo=None) if stamp.tzinfo else stamp


