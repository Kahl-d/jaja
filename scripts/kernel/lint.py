def _walk(r: Roots) -> Iterable[tuple[Path, list[str], list[str]]]:
    """os.walk over the data folder pruning dot folders and SKIP_DIR_NAMES (and, when the data folder is the code
    repo itself as in the single-tree form, the code folders); yields (folder, dirnames, filenames)."""
    base = r.data
    if not base.is_dir():
        return
    for dirpath, dirnames, filenames in os.walk(base):
        skip = SKIP_DIR_NAMES | (CODE_DIRS if r.data == r.code and Path(dirpath) == base else set())
        dirnames[:] = sorted(d for d in dirnames if not d.startswith(".") and d not in skip)
        yield Path(dirpath), dirnames, sorted(filenames)


def data_pages(root: Any = None) -> list[Path]:
    """Every Markdown file in the data folder (dot folders, fixtures, runtime and archive left out)."""
    r = as_roots(root)
    return [folder / n for folder, _, names in _walk(r) for n in names if n.endswith(".md")]


def _add_suffixes(paths: set[str], key: str) -> None:
    """Add `key` and every tail of it on a folder boundary (a/b/c -> a/b/c, b/c, c), with and without .md: a
    path-qualified link resolves to its file by any unique-enough suffix (Obsidian does the same)."""
    parts = key.split("/")
    for i in range(len(parts)):
        tail = "/".join(parts[i:])
        paths.add(tail)
        if tail.endswith(".md"):
            paths.add(tail[:-3])


def known_slugs(root: Any = None) -> tuple[set[str], set[str]]:
    """(slugs, lower-case relative paths with and without .md) of every file and folder in the data folder, plus the
    stems of the cards and skills (a note may link a role by name)."""
    r = as_roots(root)
    slugs: set[str] = set()
    paths: set[str] = set()
    for folder, dirnames, names in _walk(r):
        rel_dir = folder.relative_to(r.data).as_posix()
        rel_dir = "" if rel_dir == "." else rel_dir + "/"
        for d in dirnames:
            slugs.add(d.lower())
            _add_suffixes(paths, (rel_dir + d).lower())
        for n in names:
            slugs.add(Path(n).stem.lower())
            slugs.add(n.lower())     # [[name.ext]] links
            _add_suffixes(paths, (rel_dir + n).lower())
    for card in (r.code / "agents").glob("*.md"):
        slugs.add(card.stem.lower())
    for skill in (r.code / "skills").glob("*/SKILL.md"):
        slugs.add(skill.parent.name.lower())
    return slugs, paths


def path_link_resolves(key: str, paths: set[str]) -> bool:
    """A path-qualified link ([[a/b/c]]) resolves to that path, or to a path that ends with it on a folder boundary
    (`paths` holds every such tail, see _add_suffixes); a matching basename alone is not enough."""
    key = key.strip("/").lower()
    key = key[:-3] if key.endswith(".md") else key
    return key in paths


def check_links(root: Any = None) -> list[Finding]:
    r = as_roots(root)
    slugs, paths = known_slugs(r)
    out: list[Finding] = []
    for path in data_pages(r):
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        if "[[" not in text or sync.is_generated(text):
            continue
        text = INLINE_CODE_RE.sub("", FENCE_RE.sub("", text))
        seen: set[str] = set()
        for m in WIKILINK_RE.finditer(text):
            target = m.group(1).strip()
            key = target.lower()
            if not target or key in seen:
                continue
            seen.add(key)
            if "/" in key.strip("/"):
                ok = path_link_resolves(key, paths)
            else:
                ok = key in slugs or Path(key).name in slugs
            if not ok:
                out.append(Finding(_rel(r.data, path), "broken-link", f"[[{target}]] not found in the data folder"))
    return out


# --------------------------------------------------------------------------- #
# tag vocabulary (warning or error, as schemas/tags.yaml says)
# --------------------------------------------------------------------------- #
def load_tag_vocabulary(root: Any = None) -> dict[str, Any]:
    """schemas/tags.yaml of the code root -> {enforcement, allowed (set), project_prefix, projects (set), merge (dict)}.
    No file: an empty vocabulary with enforcement 'off' (nothing is checked). `root` may be a folder that holds
    schemas/tags.yaml itself (js_common passes the folder it found the file in)."""
    base = as_roots(root)
    path = base.code / TAGS_FILE
    if not path.is_file():
        return {"enforcement": "off", "allowed": set(), "project_prefix": None, "projects": set(), "merge": {}}
    data = fm.parse_yaml(path.read_text(encoding="utf-8")) or {}
    allowed = {f"domain/{d}" for d in data.get("domains") or []}
    allowed |= {str(t) for t in (data.get("topics") or {})}
    allowed |= {str(t) for t in (data.get("records") or {})}
    projects = {str(x) for x in (data.get("projects") or [])}        # the agency's own projects (schemas/tags.yaml)
    projects |= {p.name for p in base.data.glob("projects/*") if p.is_dir()}
    return {"enforcement": str(data.get("enforcement") or "warning"), "allowed": allowed,
            "project_prefix": data.get("project_prefix"), "projects": projects,
            "merge": dict(data.get("merge") or {})}


def _is_generated_text(text: str) -> bool:
    return bool(GENERATED_RE.search("\n".join(text[:600].splitlines()[:2])))


def _frontmatter_block(text: str) -> str | None:
    try:
        raw, _ = fm.split(text)
    except fm.FrontmatterError:
        return None
    return raw


_TAG_LINE_RE = re.compile(r"^tags:[ \t]*(.*)$", re.MULTILINE)


def tags_of(text: str) -> list[str]:
    """The page's tags: from the YAML frontmatter, or (when that block is not valid YAML, e.g. pages with
    `links: [[a]], [[b]]`) from the `tags:` line and its list on their own."""
    raw = _frontmatter_block(text)
    if not raw or "tags:" not in raw:
        return []
    try:
        value = fm.parse_yaml(raw).get("tags")
    except fm.FrontmatterError:
        m = _TAG_LINE_RE.search(raw)
        if not m:
            return []
        value = m.group(1).strip()
        if not value:                                   # block list below the key
            items = []
            for line in raw[m.end():].splitlines()[1:]:
                item = re.match(r"^\s*-\s+(.*)$", line)
                if not item:
                    break
                items.append(item.group(1))
            value = items
        elif value.startswith("[") and value.endswith("]"):
            value = value[1:-1]
    if value in (None, ""):
        return []
    items = value if isinstance(value, list) else re.split(r"[,\s]+", str(value))
    return [str(t).strip().strip("'\"").lstrip("#") for t in items if str(t).strip().strip("'\"")]


def tag_known(tag: str, vocab: dict[str, Any]) -> bool:
    if tag in vocab["allowed"]:
        return True
    prefix = vocab.get("project_prefix")
    return bool(prefix) and tag.startswith(prefix) and tag[len(prefix):] in vocab["projects"]


def check_tags(root: Any = None) -> list[Finding]:
    """Tags on the data folder's records (the files the record schemas glob: applications, companies, jobs, outbox,
    prospects, pursuits ...). Free-form notes and research pages carry no controlled tags."""
    r = as_roots(root)
    vocab = load_tag_vocabulary(r)
    if vocab["enforcement"] == "off":
        return []
    out: list[Finding] = []
    for type_name, schema in load_schemas(r).items():
        if _base_of(r, type_name) != r.data:
            continue
        for glob in _schema_globs(type_name, schema):
            for path in sorted(p for p in r.data.glob(glob) if p.is_file() and p.suffix == ".md"):
                if _skip(path):
                    continue
                try:
                    text = path.read_text(encoding="utf-8")
                except (OSError, UnicodeDecodeError):
                    continue
                if not text.startswith("---") or "tags:" not in text[:4000] or _is_generated_text(text):
                    continue
                rel = _rel(r.data, path)
                for tag in dict.fromkeys(tags_of(text)):
                    if not tag_known(tag, vocab):
                        hint = vocab["merge"].get(tag)
                        more = f"; merge to {hint}" if hint else ("; drop it" if hint == [] else "")
                        out.append(Finding(rel, "tag-unknown", f"tag '{tag}' is not in {TAGS_FILE.as_posix()}{more}"))
    return out


