# schemas
# --------------------------------------------------------------------------- #
def load_schemas(root: Any = None) -> dict[str, dict[str, Any]]:
    schemas: dict[str, dict[str, Any]] = {}
    sdir = as_roots(root).code / "schemas"
    if not sdir.is_dir():
        return schemas
    for path in sorted(sdir.glob("*.yaml")):
        if path.name == TAGS_FILE.name:
            continue                                   # the tag vocabulary, not a record schema
        try:
            data = fm.parse_yaml(path.read_text(encoding="utf-8"))
        except fm.FrontmatterError:
            continue
        if isinstance(data, dict):
            schemas[str(data.get("type") or path.stem)] = data
    return schemas


def _schema_globs(type_name: str, schema: dict[str, Any]) -> list[str]:
    """The schema's glob, re-pointed from a legacy prefix to the repo layout."""
    out = []
    for g in [schema["glob"]] if schema.get("glob") else []:
        for old, new in LEGACY_GLOBS.items():
            if g.startswith(old):
                g = new + g[len(old):]
        out.append(g)
    return out


def _base_of(r: Roots, type_name: str) -> Path:
    return getattr(r, RECORD_ROOT.get(type_name, "data"))


def _records(root: Any, type_name: str, schema: dict[str, Any]) -> Iterable[tuple[str, dict[str, Any]]]:
    """Yield (display path, mapping) for every record of this type."""
    r = as_roots(root)
    base = _base_of(r, type_name)
    for glob in _schema_globs(type_name, schema):
        for path in sorted(p for p in base.glob(glob) if p.is_file()):
            if _skip(path):
                continue
            rel = _rel(base, path)
            if path.suffix.lower() == ".md":
                try:
                    meta, _ = fm.load(path)
                except fm.FrontmatterError as exc:
                    meta = {"_error": str(exc)}
                yield rel, meta
                continue
            try:
                data = fm.parse_yaml(path.read_text(encoding="utf-8"))
            except fm.FrontmatterError as exc:
                yield rel, {"_error": str(exc)}
                continue
            if type_name == "connector":
                entries = data.get("connectors", data) if isinstance(data, dict) else data
                if isinstance(entries, dict):
                    for name, spec in entries.items():
                        if str(name).startswith("_"):
                            continue
                        spec = dict(spec) if isinstance(spec, dict) else {}
                        spec.setdefault("name", name)
                        yield f"{rel}#{name}", spec
                elif isinstance(entries, list):
                    for i, spec in enumerate(entries):
                        spec = dict(spec) if isinstance(spec, dict) else {}
                        yield f"{rel}#{spec.get('name', i)}", spec
                continue
            yield rel, data if isinstance(data, dict) else {"_error": "top level is not a mapping"}


def validate(meta: dict[str, Any], schema: dict[str, Any], path: str, type_name: str) -> list[Finding]:
    out: list[Finding] = []
    if "_error" in meta:
        return [Finding(path, "frontmatter-error", meta["_error"])]
    for key in schema.get("required", []) or []:
        if key not in meta or meta[key] is None or meta[key] == "":
            out.append(Finding(path, "schema-missing", f"{type_name}: required field '{key}' is missing"))
    for key, allowed in (schema.get("enums") or {}).items():
        if key in meta and meta[key] not in (None, "") and str(meta[key]) not in [str(a) for a in allowed]:
            out.append(Finding(path, "schema-enum", f"{type_name}: '{key}: {meta[key]}' not in {list(allowed)}"))
    for key in schema.get("dates", []) or []:
        if key in meta and meta[key] not in (None, "") and not _is_date(meta[key]):
            out.append(Finding(path, "schema-date", f"{type_name}: '{key}: {meta[key]}' is not an ISO date"))
    for key, pattern in (schema.get("patterns") or {}).items():
        if key in meta and meta[key] not in (None, "") and not re.fullmatch(pattern, str(meta[key])):
            out.append(Finding(path, "schema-pattern", f"{type_name}: '{key}: {meta[key]}' does not match {pattern}"))
    for key in schema.get("wikilink_lists", []) or []:
        value = meta.get(key)
        if value in (None, "", []):
            continue
        if not isinstance(value, list) or not all(isinstance(v, str) and re.fullmatch(r"\[\[[^\[\]]+\]\]", v.strip())
                                                  for v in value):
            out.append(Finding(path, "schema-links", f"{type_name}: '{key}' must be a list of [[...]] wikilinks"))
    if type_name == "role" and meta.get("tools_allow") not in (None, "") and sync.tools_refusal(meta):
        # missing is already schema-missing; an empty list renders as "all tools", so sync refuses it
        out.append(Finding(path, "role-tools-empty", f"role: {sync.tools_refusal(meta)}"))
    if type_name == "task" and str(meta.get("status")) == "done" and not meta.get("evidence"):
        out.append(Finding(path, "schema-rule", "task: status done requires a non-empty evidence field"))
    if type_name == "routine":
        # the watchdog restarts its clock at `installed:` and `last_reviewed:`; an unreadable or future value would
        # hide a stopped routine, so both are checked here
        for key in ("installed", "last_reviewed"):
            stamp = _routine_stamp(meta.get(key))
            if meta.get(key) in (None, ""):
                continue
            if stamp is None and key not in (schema.get("dates") or []):
                out.append(Finding(path, "schema-date", f"routine: '{key}: {meta[key]}' is not a date or a local "
                                                        "'YYYY-MM-DDTHH:MM'"))
            elif stamp is not None and stamp > dt.datetime.now():
                out.append(Finding(path, "schema-rule", f"routine: '{key}: {meta[key]}' is in the future"))
        #: a routine that runs a model stays paused until the owner asks; switching one on names who said so
        if str(meta.get("engine")) in ("claude", "codex") and meta.get("enabled") is True and not str(meta.get("enabled_by") or "").strip():
            out.append(Finding(path, "routine-enabled", "routine: a model routine is enabled without enabled_by "
                                                        "(paused until the owner asks; name the ticket or approval id that switched it on)"))
        if str(meta.get("engine")) in ("claude", "codex") and not meta.get("model"):
            out.append(Finding(path, "routine-model", "routine: a model routine names no model: (model policy v2)"))
    if type_name == "task" and meta.get("hard_deadline") not in (None, "") and not str(meta.get("derived_from") or "").strip():
        out.append(Finding(path, "schema-rule", "task: hard_deadline requires a non-empty derived_from (its provenance)"))
    return out


def check_schemas(root: Any = None) -> list[Finding]:
    r = as_roots(root)
    out: list[Finding] = []
    for type_name, schema in load_schemas(r).items():
        for path, meta in _records(r, type_name, schema):
            out.extend(validate(meta, schema, path, type_name))
    return out


