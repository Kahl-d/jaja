#!/usr/bin/env python3
"""Agent eval harness for the job agency.

Every role can have an eval set at evals/<role>/cases.yaml (this repo ships the harness and an example, no sets).
A case gives the role a realistic task inside a sandbox copy of fixture files, then grades what the role produced:

  1. deterministic checks (files exist, frontmatter fields/values, text must/must-not include,
     regex, JSON fields) - computed here, no model;
  2. a rubric scored by a clean-context judge (the reviewer role) - the harness emits the judge
     prompt and parses the judge's JSON verdict.

Execution engines (how the role itself is run):
  - claude-cli : `claude -p --add-dir <sandbox>` headless (needs a valid CLI login)
  - external   : the harness prepares sandboxes and prompts (`prepare`), something else runs the
                 role (for example a subagent in an interactive session), then `grade` scores it.

Case file format (YAML):

  role: resume-editor
  pass_threshold: 0.8               # share of weighted points required per case
  cases:
    - id: slop-detection-01
      title: Catches AI-slop phrasing and an unevidenced metric
      fixtures:                     # copied into the sandbox before the run (paths relative to
        - from: fixtures/variant-slop  # the case folder) to the sandbox-relative target
          to: resumes/variants/acme-ml-eng-202609
      task: |
        Review resumes/variants/acme-ml-eng-202609/resume.yaml for the application ... .
      checks:                       # deterministic, weighted
        - {kind: file_exists, path: resumes/variants/acme-ml-eng-202609/review.md, weight: 1}
        - {kind: contains, path: resumes/variants/acme-ml-eng-202609/review.md,
           text: "leverage", weight: 1}
        - {kind: not_contains, path: ..., text: "...", weight: 1}
        - {kind: regex, path: ..., pattern: "verdict:\\s*changes-requested", weight: 2}
        - {kind: frontmatter, path: prospects/jane-doe.md, field: priority, equals: P0, weight: 2}
        - {kind: frontmatter, path: ..., field: status, one_of: [replied, drafted], weight: 1}
        - {kind: glob_count, pattern: "outbox/*.md", min: 1, max: 5, weight: 1}
        - {kind: reply_contains, text: "needs the owner", weight: 1}   # checks the role's final reply
      rubric:                       # judge-scored, each 0..1 times weight
        - {criterion: "Every finding cites the exact bullet and a reason", weight: 2}
        - {criterion: "Does not rewrite facts; only flags them", weight: 1}

CLI:
  evals.py list
  evals.py prepare --role R [--case ID] --out <dir>                  # sandboxes + prompts
  evals.py run --role R --engine claude-cli [--case ID] [--model M] [--effort E]   # prepare + run + grade
  evals.py grade --role R --sandbox-root <dir> [--judge-dir <dir>]   # deterministic + rubric
  evals.py report                                                    # results table

Sandboxes: a case's sandbox is a miniature copy of this repo, so the role's commands run against synthetic data only:
scripts/ (no tests or caches), schemas/, templates/, agents/, skills/, routines/, config/defaults.d/, the empty
folders work/{inbox,tasks,approvals}, logs/runs and state/, a `.eval-sandbox` marker (scripts/agency_paths.py then
makes the sandbox its own code, data and runtime root, so nothing reaches the real data folder) and the adapters
generated by the sandbox's own sync.py. Fixture files always win over copied ones.

Results are written to evals/<role>/results/<date>-<case>.json and a summary
evals/<role>/results.md (append-only history table).
"""
from __future__ import annotations

import argparse
import fnmatch
import json
import os
import re
import shutil
import subprocess
import sys
from datetime import date, datetime
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
import frontmatter as fm  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
EVALS = ROOT / "evals"


# --------------------------------------------------------------------------- loading
def load_cases(role: str) -> dict[str, Any]:
    path = EVALS / role / "cases.yaml"
    if not path.is_file():
        raise SystemExit(f"no eval set at {path}")
    data = fm.parse_yaml(path.read_text(encoding="utf-8"))
    if not isinstance(data, dict) or "cases" not in data:
        raise SystemExit(f"{path}: expected a mapping with 'cases'")
    data.setdefault("pass_threshold", 0.8)
    data["_dir"] = path.parent
    return data


def list_sets() -> list[tuple[str, int]]:
    out = []
    for cases in sorted(EVALS.glob("*/cases.yaml")):
        role = cases.parent.name
        try:
            n = len(load_cases(role)["cases"])
        except SystemExit:
            n = -1
        out.append((role, n))
    return out


# --------------------------------------------------------------------------- sandboxes
def role_card_path(role: str) -> Path:
    return ROOT / "agents" / f"{role}.md"


def card_version(role: str) -> str | None:
    """The `version:` in the role card's frontmatter, or None when the card or field is missing."""
    card = role_card_path(role)
    if not card.is_file():
        return None
    m = re.search(r"^version:\s*['\"]?([^'\"\s]+)", card.read_text(encoding="utf-8"), re.M)
    return m.group(1) if m else None


_SKIP_PARTS = {"tests", "__pycache__", ".pytest_cache"}


def _copy_missing(src: Path, dst: Path) -> None:
    """Copy the tree src into dst file by file (no tests, caches or *.pyc), never overwriting a file
    a fixture already placed."""
    for path in sorted(src.rglob("*")):
        rel = path.relative_to(src)
        if path.is_dir() or path.suffix == ".pyc" or _SKIP_PARTS.intersection(rel.parts):
            continue
        target = dst / rel
        if target.exists():
            continue
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, target)


def _prepare_sandbox(sandbox: Path) -> None:
    """A sandbox is a miniature repo root (see the module docstring). Fixture files placed first always win."""
    for sub in ("scripts", "schemas", "templates", "agents", "skills", "routines", "config/defaults.d", "lanes", "hooks"):
        if (ROOT / sub).is_dir():
            _copy_missing(ROOT / sub, sandbox / sub)
    for name in (".mcp.json",):
        if (ROOT / name).is_file() and not (sandbox / name).exists():
            shutil.copy2(ROOT / name, sandbox / name)
    for d in ("work/inbox", "work/tasks", "work/approvals", "logs/runs", "state", ".no-config"):
        (sandbox / d).mkdir(parents=True, exist_ok=True)
    (sandbox / ".eval-sandbox").write_text(str(ROOT / "scripts"), encoding="utf-8")
    # Generate the sandbox's own adapters from its cards, so lint.py and sync.py --check start clean there and a
    # role's findings are its own, not sandbox noise.
    if not (sandbox / "scripts" / "kernel" / "sync.py").is_file():
        return                                      # a bare sandbox (no scripts copied): nothing to generate
    env = {**os.environ, "PYTHONDONTWRITEBYTECODE": "1"}
    proc = subprocess.run([sys.executable, "scripts/kernel/sync.py"], cwd=sandbox, capture_output=True, text=True, env=env)
    if proc.returncode != 0:
        raise SystemExit(f"sandbox sync failed in {sandbox}: {proc.stdout}{proc.stderr}")


def prepare_case(role: str, case: dict[str, Any], case_dir: Path, out: Path) -> Path:
    """Create <out>/<case id>/sandbox with fixtures and write prompt.md (role card + task)."""
    cdir = out / case["id"]
    sandbox = cdir / "sandbox"
    if cdir.exists():
        shutil.rmtree(cdir)
    sandbox.mkdir(parents=True)
    for fx in case.get("fixtures", []) or []:
        src = (case_dir / fx["from"]).resolve()
        dst = sandbox / fx.get("to", Path(fx["from"]).name)
        if src.is_dir():
            shutil.copytree(src, dst, dirs_exist_ok=True)
        elif src.is_file():
            dst.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(src, dst)
        else:
            raise SystemExit(f"fixture missing: {src}")
    _prepare_sandbox(sandbox)
    card = role_card_path(role)
    card_text = card.read_text(encoding="utf-8") if card.is_file() else f"(role card missing: {card})"
    (cdir / "card_version.txt").write_text(card_version(role) or "", encoding="utf-8")
    rules = ROOT / "AGENTS.md"
    rules_text = rules.read_text(encoding="utf-8") if rules.is_file() else ""
    where = (
        "You are being evaluated. Act exactly as the role below. Work ONLY inside the sandbox folder "
        f"`{sandbox}` (treat it as the agency root: every path in your instructions such as "
        "`prospects/`, `resumes/`, `outbox/`, `work/approvals/`, `logs/runs/` resolves inside it). Do not touch any "
        "other folder. The agency's scripts are copied into the sandbox at `scripts/`; run them from the sandbox "
        "root (`cd <sandbox> && python3 scripts/<name>.py ...`). They resolve every path inside the sandbox, so the "
        "sandbox is the code, data and runtime folder at once. "
    )
    prompt = (
        f"# Eval run · role `{role}` · case `{case['id']}`\n\n" + where +
        "Paste the exact command and its output when a result depends on it. Nothing may be "
        "sent to anyone: outward actions are drafts only.\n\n"
        "When finished, end your reply with a line `FINAL REPLY:` followed by the reply you would give "
        "the caller.\n\n"
        "## Department rules\n\n" + rules_text + "\n\n## Your role card\n\n" + card_text +
        "\n\n## Task\n\n" + case["task"].strip() + "\n"
    )
    (cdir / "prompt.md").write_text(prompt, encoding="utf-8")
    (cdir / "case.json").write_text(json.dumps({k: v for k, v in case.items()}, indent=2, default=str), encoding="utf-8")
    return cdir


# --------------------------------------------------------------------------- deterministic checks
def _read(sandbox: Path, rel: str) -> str | None:
    p = sandbox / rel
    return p.read_text(encoding="utf-8", errors="replace") if p.is_file() else None


def read_reply(cdir: Path) -> str:
    """The role's final reply: <case>/reply.txt, else <case>/sandbox/reply.txt (agents sometimes save it there)."""
    return _read(cdir, "reply.txt") or _read(cdir / "sandbox", "reply.txt") or ""


def run_check(sandbox: Path, reply: str, chk: dict[str, Any]) -> tuple[bool, str]:
    kind = chk.get("kind")
    path = chk.get("path", "")
    if kind == "file_exists":
        ok = (sandbox / path).exists()
        return ok, f"{path} {'exists' if ok else 'missing'}"
    if kind in ("contains", "not_contains", "regex", "not_regex"):
        targets = sorted(sandbox.glob(path)) if any(c in path for c in "*?[") else [sandbox / path]
        texts = [t.read_text(encoding="utf-8", errors="replace") for t in targets if t.is_file()]
        if not texts:
            return (kind in ("not_contains", "not_regex")), f"{path}: no file"
        blob = "\n".join(texts)
        flags = re.I if chk.get("ignore_case", True) else 0
        if kind == "contains":
            ok = chk["text"].lower() in blob.lower() if flags else chk["text"] in blob
            return ok, f"{path} {'contains' if ok else 'lacks'} {chk['text']!r}"
        if kind == "not_contains":
            ok = not (chk["text"].lower() in blob.lower() if flags else chk["text"] in blob)
            return ok, f"{path} {'free of' if ok else 'contains'} {chk['text']!r}"
        found = re.search(chk["pattern"], blob, flags | re.M) is not None
        ok = found if kind == "regex" else not found
        return ok, f"{path} {'matches' if found else 'no match'} /{chk['pattern']}/"
    if kind == "frontmatter":
        text = _read(sandbox, path)
        if text is None:
            return False, f"{path}: no file"
        try:
            meta, _ = fm.loads(text) if hasattr(fm, "loads") else fm.load(sandbox / path)
        except Exception as exc:  # noqa: BLE001
            return False, f"{path}: frontmatter error {exc}"
        val = meta.get(chk["field"])
        if "equals" in chk:
            ok = str(val) == str(chk["equals"])
        elif "one_of" in chk:
            ok = str(val) in [str(x) for x in chk["one_of"]]
        elif "min" in chk or "max" in chk:
            try:
                num = float(val)
                ok = float(chk.get("min", float("-inf"))) <= num <= float(chk.get("max", float("inf")))
            except (TypeError, ValueError):
                ok = False
        elif chk.get("present", True):
            ok = val not in (None, "", [], {})
        else:
            ok = True
        return ok, f"{path}:{chk['field']} = {val!r}"
    if kind == "glob_count":
        n = len([p for p in sandbox.glob(chk["pattern"]) if p.is_file()])
        ok = chk.get("min", 0) <= n <= chk.get("max", 10**9)
        return ok, f"{chk['pattern']}: {n} file(s)"
    if kind == "reply_contains":
        ok = chk["text"].lower() in reply.lower()
        return ok, f"reply {'contains' if ok else 'lacks'} {chk['text']!r}"
    if kind == "reply_not_contains":
        ok = chk["text"].lower() not in reply.lower()
        return ok, f"reply {'free of' if ok else 'contains'} {chk['text']!r}"
    if kind == "json_field":
        text = _read(sandbox, path)
        try:
            data = json.loads(text or "")
            cur: Any = data
            for part in str(chk["field"]).split("."):
                cur = cur[int(part)] if isinstance(cur, list) else cur[part]
            ok = (str(cur) == str(chk["equals"])) if "equals" in chk else cur not in (None, "", [])
            return ok, f"{path}:{chk['field']} = {cur!r}"
        except Exception as exc:  # noqa: BLE001
            return False, f"{path}:{chk['field']} unreadable ({exc})"
    if kind == "no_file_changed_outside":
        allowed = chk.get("allowed", [])
        manifest = json.loads(_read(sandbox.parent, "manifest.json") or "{}")
        changed = [p for p in _changed_files(sandbox, manifest) if not any(fnmatch.fnmatch(p, a) for a in allowed)]
        return not changed, f"unexpected writes: {changed[:5]}" if changed else "no unexpected writes"
    return False, f"unknown check kind {kind!r}"


def _snapshot(sandbox: Path) -> dict[str, float]:
    """mtime per file, ignoring interpreter caches (importing a copied script writes __pycache__)."""
    return {p.relative_to(sandbox).as_posix(): p.stat().st_mtime for p in sandbox.rglob("*")
            if p.is_file() and "__pycache__" not in p.parts and p.suffix != ".pyc"}


def _changed_files(sandbox: Path, manifest: dict[str, float]) -> list[str]:
    now = _snapshot(sandbox)
    return sorted(p for p, m in now.items() if p not in manifest or manifest[p] != m)


def judge_prompt(case: dict[str, Any], sandbox: Path, reply: str) -> str:
    rubric = case.get("rubric") or []
    lines = "\n".join(f"- ({i}) weight {r.get('weight', 1)}: {r['criterion']}" for i, r in enumerate(rubric))
    changed_note = ""
    manifest_text = _read(sandbox.parent, "manifest.json")
    if manifest_text is not None:  # a baseline exists (even an empty one): list what changed
        changed = _changed_files(sandbox, json.loads(manifest_text or "{}"))
        changed_note = "Files written or changed by the role:\n" + "\n".join(f"- {c}" for c in changed[:50])
    return (
        "You are a strict, clean-context evaluator (reviewer role). Grade the work of an agent against "
        "the rubric. Read the files it produced inside the sandbox and its final reply. Score each "
        "criterion 0.0, 0.5 or 1.0 with a one-sentence justification that cites a file and line or "
        "quotes the reply. Do not reward effort; reward only what is true in the files.\n\n"
        f"Sandbox: {sandbox}\n{changed_note}\n\nTask the agent was given:\n{case['task'].strip()}\n\n"
        f"Agent final reply (full text is in the case dir as reply.txt):\n<reply>\n"
        f"{reply if len(reply) <= 20000 else '[first ' + str(len(reply) - 20000) + ' chars cut; read reply.txt]' + reply[-20000:]}"
        f"\n</reply>\n\nRubric:\n{lines}\n\n"
        'Return ONLY JSON: {"scores": [{"i": 0, "score": 1.0, "why": "..."}, ...], "overall_note": "..."}'
    )


def grade_case(role: str, case: dict[str, Any], cdir: Path, judge: dict[str, Any] | None,
               threshold: float) -> dict[str, Any]:
    sandbox = cdir / "sandbox"
    reply = read_reply(cdir)
    det = []
    got = total = 0.0
    for chk in case.get("checks", []) or []:
        w = float(chk.get("weight", 1))
        ok, note = run_check(sandbox, reply, chk)
        det.append({"check": chk, "ok": ok, "note": note})
        total += w
        got += w if ok else 0.0
    rub = []
    for i, r in enumerate(case.get("rubric", []) or []):
        w = float(r.get("weight", 1))
        s = None
        why = "not judged"
        if judge:
            for row in judge.get("scores", []):
                if int(row.get("i", -1)) == i:
                    s = float(row.get("score", 0))
                    why = row.get("why", "")
        total += w
        got += w * (s or 0.0)
        rub.append({"criterion": r["criterion"], "weight": w, "score": s, "why": why})
    share = got / total if total else 0.0
    vfile = cdir / "card_version.txt"
    tested = (vfile.read_text(encoding="utf-8").strip() or None) if vfile.is_file() else None
    now = card_version(role)
    efile = cdir / "engine.json"
    engine = json.loads(efile.read_text(encoding="utf-8")) if efile.is_file() else {}
    return {
        "role": role, "case": case["id"], "title": case.get("title", ""),
        "card_version": tested, "card_changed_since_run": tested != now,
        "model": engine.get("model", "unrecorded"), "effort": engine.get("effort", "unrecorded"),
        "graded_at": datetime.now().replace(microsecond=0).isoformat(),
        "score": round(share, 3), "threshold": threshold, "passed": share >= threshold and judge is not None
        if case.get("rubric") else share >= threshold,
        "deterministic": det, "rubric": rub, "judge_note": (judge or {}).get("overall_note", ""),
    }


def write_result(role: str, result: dict[str, Any]) -> Path:
    rdir = EVALS / role / "results"
    rdir.mkdir(parents=True, exist_ok=True)
    path = rdir / f"{date.today():%Y-%m-%d}-{result['case']}.json"
    path.write_text(json.dumps(result, indent=2, default=str), encoding="utf-8")  # YAML dates in checks
    summary = EVALS / role / "results.md"
    if not summary.exists():
        summary.write_text(f"# Eval results · {role}\n\n| date | case | score | threshold | passed | note |\n|---|---|--:|--:|:-:|---|\n",
                           encoding="utf-8")
    with summary.open("a", encoding="utf-8") as fh:
        note = (result.get("judge_note") or "").replace("|", "/")[:120]
        if result.get("model") not in (None, "unrecorded"):
            note = f"model {result['model']} · effort {result.get('effort')} · {note}"
        if result.get("card_version"):
            note = f"card {result['card_version']} · {note}"
        fh.write(f"| {result['graded_at'][:10]} | {result['case']} | {result['score']:.2f} | "
                 f"{result['threshold']:.2f} | {'yes' if result['passed'] else 'no'} | {note} |\n")
    return path


# --------------------------------------------------------------------------- engines
EFFORTS = ("low", "medium", "high", "xhigh", "max")      # `claude --help`: --effort <level>


def run_claude_cli(role: str, cdir: Path, timeout: int = 1800, model: str | None = None,
                   effort: str | None = None) -> str:
    prompt = (cdir / "prompt.md").read_text(encoding="utf-8")
    cmd = ["claude", "-p", "--add-dir", str(cdir / "sandbox"), "--permission-mode", "acceptEdits"]
    cmd += ["--model", model] if model else []
    cmd += ["--effort", effort] if effort else []
    cmd.append(prompt)
    (cdir / "engine.json").write_text(json.dumps({"engine": "claude-cli", "model": model or "default",
                                                  "effort": effort or "default"}), encoding="utf-8")
    sandbox = cdir / "sandbox"
    (sandbox / ".no-config").mkdir(exist_ok=True)
    env = {**os.environ, "JAJA_CONFIG_DIR": str(sandbox / ".no-config"), "JOB_AGENCY_CONFIG_DIR": str(sandbox / ".no-config"),
           "GMAIL_CLIENT_SECRET": str(sandbox / ".no-config" / "no-client-secret.json")}
    proc = subprocess.run(cmd, capture_output=True, text=True, timeout=timeout, cwd=str(sandbox), env=env)
    out = proc.stdout + ("\n" + proc.stderr if proc.returncode else "")
    (cdir / "reply.txt").write_text(out, encoding="utf-8")
    return out


# --------------------------------------------------------------------------- CLI
def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("list")
    for name in ("prepare", "run", "grade"):
        q = sub.add_parser(name)
        q.add_argument("--role", required=True)
        q.add_argument("--case")
        if name in ("prepare", "run"):
            q.add_argument("--out", default=str(ROOT / ".eval-runs"))
        if name == "run":
            q.add_argument("--engine", choices=["claude-cli"], default="claude-cli")
            q.add_argument("--model", help="passed to `claude --model` (an alias or a full model id)")
            q.add_argument("--effort", choices=EFFORTS, help="passed to `claude --effort`")
        if name == "grade":
            q.add_argument("--sandbox-root", required=True)
            q.add_argument("--judge-dir", help="folder with <case-id>.judge.json files")
    sub.add_parser("report")
    a = ap.parse_args(argv)

    if a.cmd == "list":
        for role, n in list_sets():
            print(f"{role:28} {n} case(s)")
        return 0
    if a.cmd == "report":
        for role, _ in list_sets():
            s = EVALS / role / "results.md"
            print(f"## {role}\n" + (s.read_text(encoding="utf-8") if s.is_file() else "(no results)\n"))
        return 0

    data = load_cases(a.role)
    cases = [c for c in data["cases"] if not a.case or c["id"] == a.case]
    if a.cmd in ("prepare", "run"):
        out = Path(a.out) / a.role
        for c in cases:
            cdir = prepare_case(a.role, c, data["_dir"], out)
            (cdir / "manifest.json").write_text(json.dumps(_snapshot(cdir / "sandbox")), encoding="utf-8")
            print(f"prepared {cdir}")
            if a.cmd == "run":
                run_claude_cli(a.role, cdir, model=a.model, effort=a.effort)
                print(f"ran {c['id']}; judge with the reviewer, then: evals.py grade --role {a.role} --sandbox-root {out}")
                (cdir / "judge_prompt.md").write_text(judge_prompt(c, cdir / "sandbox", read_reply(cdir)),
                                                      encoding="utf-8")
        return 0
    if a.cmd == "grade":
        out = Path(a.sandbox_root)
        failed = 0
        for c in cases:
            cdir = out / c["id"]
            if not cdir.is_dir():
                print(f"skip {c['id']}: no run at {cdir}")
                continue
            judge = None
            jpath = Path(a.judge_dir) / f"{c['id']}.judge.json" if a.judge_dir else cdir / "judge.json"
            if jpath.is_file():
                judge = json.loads(jpath.read_text(encoding="utf-8"))
            res = grade_case(a.role, c, cdir, judge, float(data["pass_threshold"]))
            write_result(a.role, res)
            print(f"{c['id']:32} score {res['score']:.2f} {'PASS' if res['passed'] else 'FAIL'}")
            failed += 0 if res["passed"] else 1
        return 1 if failed else 0
    return 2


if __name__ == "__main__":
    sys.exit(main())
