#!/usr/bin/env python3
"""sync.py - regenerate the engine adapters from the canonical files of this repo.

Sources (hand-edited)                         Generated outputs (never edit; every one carries the GENERATED marker)
    agents/*.md             role cards       -> .claude/agents/<name>.md           Claude Code agent files
                                                .codex/agents/<name>.toml           Codex agent files
    lanes/<type>/AGENT.md + LANE.yaml        -> .claude/agents/lane-<type>.md      the lane agent (initialPrompt, hooks)
                                                .codex/agents/lane-<type>.toml
                                                .claude/lane-settings/<type>.json   per-lane settings, see "Lanes" below
    skills/<name>/**                         -> .agents/skills/<name>/**           mirror for Codex only (Claude Code
                                                                                   loads ./skills natively as a plugin)
    hooks/hooks.json                         -> .claude/settings.json["hooks"]     merged, for sessions in this repo
                                                .codex/hooks.json
    .mcp.json                                -> .codex/config.toml [mcp_servers]

The plugin manifests (.claude-plugin/plugin.json and marketplace.json) are written by hand. Sync only CHECKS them:
the two agree on name and version, the marketplace name is `jaja`, and every path plugin.json names
(skills, agents, hooks, mcpServers) exists. A plugin that points `agents` at the source cards (agents/) instead of
the generated agent files (.claude/agents/) is reported as a note: Claude Code reads `tools:`, not `tools_allow:`.

Marker: every generated file starts with `GENERATED by scripts/kernel/sync.py` (an HTML comment, a `#` line, a
second-line YAML comment in files whose first line must be the `---` fence, or a "_generated" key in JSON).
hooks/guard_generated_files.py refuses edits to any file that carries it. Strict JSON that an engine validates
(.claude/settings.json, .claude/lane-settings/*.json) carries no marker: sync owns the `hooks` key of the first and the
whole folder of the second.

Lanes. A lane is a session type, not a role. Sync renders its AGENT.md as the agent `lane-<type>` and writes
.claude/lane-settings/<type>.json = {"agent": "lane-<type>", "env": {CLAUDE_CODE_MAX_SUBAGENT_SPAWN_DEPTH: "1", ...
LANE.yaml env}}. There is no per-lane .claude/ folder. Start a lane in your DATA folder (the folder that holds
hub/, applications/ ...):
    cd <data folder> && claude --agent lane-<type> --settings <repo>/.claude/lane-settings/<type>.json --name AG-<TYPE>
With the plugin installed the agent is `jaja:lane-<type>`, and the plugin's hooks (hooks.json) run in every
folder; the hooks do nothing unless the session is a lane or a programme hub exists.

A role card whose `tools_allow` is missing or empty is refused, never rendered: Claude Code reads an empty or absent
`tools:` as "every tool". A refused card produces no adapter (a previously generated one is pruned: fail closed), is
reported as "refused" drift, and makes sync exit 1. lint.py reports it as `role-tools-empty`.

Interface:
    plan(root)  -> dict[relpath, str|bytes]   what would be written
    diff(root)  -> dict[str, list[str]]       {"changed", "missing", "stale", "refused", "plugin"}
    check(root) -> same as diff
    plugin_drift(root, registry=None) -> list the manifests disagree, a path does not resolve, or the installed
                                              plugin is another version
    plugin_notes(root) -> list                non-fatal remarks about the manifests
    tools_refusal(meta) -> str | None         why a role card cannot be rendered
    main(root, check=False) -> int            0 ok; 1 when a card is refused, or (check=True) on drift

CLI:  python3 scripts/kernel/sync.py [--root PATH] [--check] [--plugin-registry PATH]
      --check exits 1 on drift and writes nothing. It also compares the installed plugin (default
      ~/.claude/plugins/installed_plugins.json, or $JAJA_PLUGIN_REGISTRY); no registry or no entry is not drift.
"""
