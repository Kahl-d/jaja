PLUGIN_JSON = ".claude-plugin/plugin.json"
MARKET_JSON = ".claude-plugin/marketplace.json"
DEFAULT_REGISTRY = Path.home() / ".claude" / "plugins" / "installed_plugins.json"
_PATH_KEYS = ("skills", "agents", "hooks", "mcpServers")


def _plugin_paths(meta: dict[str, Any]) -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for key in _PATH_KEYS:
        v = meta.get(key)
        if isinstance(v, str):
            out[key] = [v]
        elif isinstance(v, list):
            out[key] = [x for x in v if isinstance(x, str)]
    return out


def plugin_drift(root: str | Path, registry: str | Path | None = None) -> list[str]:
    """Drift in the hand-written manifests: unreadable, names or versions that disagree, a path that does not exist,
    and (with a registry) an installed copy at another version. No manifests at all is not drift."""
    root = Path(root).resolve()
    out: list[str] = []
    plugin_p, market_p = root / PLUGIN_JSON, root / MARKET_JSON
    if not plugin_p.is_file() and not market_p.is_file():
        return out
    meta = _load_json(plugin_p) if plugin_p.is_file() else None
    market = _load_json(market_p) if market_p.is_file() else None
    if not isinstance(meta, dict):
        return [f"{PLUGIN_JSON} is missing or not a JSON object"]
    pname, pver = str(meta.get("name") or ""), str(meta.get("version") or "")
    if not pname or not pver:
        out.append(f"{PLUGIN_JSON} needs a name and a version")
    for key, paths in _plugin_paths(meta).items():
        for p in paths:
            if not (root / p).exists():
                out.append(f"{PLUGIN_JSON}: {key} path {p} does not exist")
    if not isinstance(market, dict):
        out.append(f"{MARKET_JSON} is missing or not a JSON object")
    else:
        if str(market.get("name")) != MARKETPLACE_NAME:
            out.append(f"{MARKET_JSON}: name is {market.get('name')!r}, expected {MARKETPLACE_NAME!r}")
        entries = [e for e in market.get("plugins") or [] if isinstance(e, dict) and e.get("name") == pname]
        if not entries:
            out.append(f"{MARKET_JSON} lists no plugin named {pname!r}")
        for e in entries:
            if str(e.get("version")) != pver:
                out.append(f"{MARKET_JSON} lists {pname} {e.get('version')} but {PLUGIN_JSON} is {pver}")
    reg = _load_json(Path(registry)) if registry and Path(registry).is_file() else None
    installed = (reg.get("plugins", reg) if isinstance(reg, dict) else {}).get(f"{pname}@{MARKETPLACE_NAME}") or []
    for e in installed if isinstance(installed, list) else []:
        where = f"installed {pname}@{MARKETPLACE_NAME} ({e.get('scope', '?')} scope)"
        if pver and str(e.get("version")) != pver:
            out.append(f"{where} is {e.get('version')}, the repo is {pver}: update the plugin")
        if not Path(str(e.get("installPath") or "")).is_dir():
            out.append(f"{where}: install path {e.get('installPath')} is missing")
    return out


def plugin_notes(root: str | Path) -> list[str]:
    """Remarks about the manifests that do not fail the check."""
    root = Path(root).resolve()
    meta = _load_json(root / PLUGIN_JSON) if (root / PLUGIN_JSON).is_file() else None
    notes: list[str] = []
    if isinstance(meta, dict):
        for p in _plugin_paths(meta).get("agents", []):
            if os.path.normpath(p) == "agents":
                notes.append(f"{PLUGIN_JSON}: agents is ./agents (the source cards, whose `tools_allow:` Claude Code does "
                             "not read, so a plugin agent would get every tool); point it at ./.claude/agents, the "
                             "generated agent files")
    return notes


# --------------------------------------------------------------------------- #
# plugin-native fields on the source cards
# --------------------------------------------------------------------------- #
NATIVE_KEYS = ("description", "tools", "disallowedTools")


def card_native_updates(root: str | Path) -> dict[str, str]:
    """{rel path: new text} for every card in agents/ whose Claude-native fields (description, tools, disallowedTools)
    differ from what its purpose, tools_allow and disallowed_tools say.

    The repo root is a Claude Code plugin and Claude loads agents/*.md as agents. A card without `tools:` would get
    every tool, so each card carries the native fields, derived here from the card's own fields and never edited by hand.
    """
    root = Path(root).resolve()
    out: dict[str, str] = {}
    for rel, meta, _body in _role_cards(root):
        path = root / rel
        text = path.read_text(encoding="utf-8")
        if not text.startswith("---\n"):
            continue
        end = text.find("\n---\n", 4)
        if end < 0:
            continue
        head, tail = text[4:end].split("\n"), text[end:]
        want = [f"description: {json.dumps(one_line(meta.get('purpose') or meta.get('title') or meta.get('name')), ensure_ascii=False)}"]
        tools = _as_list(meta.get("tools_allow"))
        if tools:
            want.append("tools: " + ", ".join(tools))
        disallowed = _as_list(meta.get("disallowed_tools"))
        if disallowed:
            want.append("disallowedTools: " + ", ".join(disallowed))
        kept = [ln for ln in head if not any(ln.startswith(k + ":") for k in NATIVE_KEYS)]
        at = next((i for i, ln in enumerate(kept) if ln.startswith("purpose:")), None)
        if at is None:
            at = next((i for i, ln in enumerate(kept) if ln.startswith("name:")), 0)
        new = kept[: at + 1] + want + kept[at + 1:]
        new_text = "---\n" + "\n".join(new) + tail
        if new_text != text:
            out[rel] = new_text
    return out


def check(root: str | Path, registry: str | Path | None = None) -> dict[str, list[str]]:
    """Alias of diff(); kept as the name the docs use."""
    return diff(root, registry=registry)


def apply(root: str | Path) -> dict[str, list[str]]:
    root = Path(root).resolve()
    outputs = plan(root)
    report = diff(root, outputs)   # one plan: a source edited mid-run (another session) cannot desync the two
    for rel in report["changed"] + report["missing"]:
        p = root / rel
        p.parent.mkdir(parents=True, exist_ok=True)
        content = outputs[rel]
        if isinstance(content, bytes):
            p.write_bytes(content)
        else:
            p.write_text(content, encoding="utf-8")
    for rel in report["stale"]:
        p = root / rel
        p.unlink()
        parent = p.parent
        while parent != root and parent.is_dir() and not any(parent.iterdir()):
            parent.rmdir()
            parent = parent.parent
    return report


def main(root: str | Path, check: bool = False, registry: str | Path | None = None) -> int:
    """Regenerate adapters (or, with check=True, report drift without writing). `registry` (the engine's
    installed_plugins.json) adds the installed-plugin comparison to the check."""
    root = Path(root).resolve()
    if check:
        report = diff(root, registry=registry)
        for kind, items in report.items():
            for rel in items:
                print(f"drift: {kind} {rel}")
        native = card_native_updates(root)
        for rel in sorted(native):
            print(f"drift: card-native {rel}")
        for remark in plugin_notes(root):
            print(f"note: {remark}")
        n = sum(len(v) for k, v in report.items() if k != "plugin") + len(native)
        if n:
            print(f"sync --check: {n} file(s) out of date; run python3 {SELF}")
        if report["plugin"]:
            print(f"sync --check: {len(report['plugin'])} plugin manifest problem(s): fix .claude-plugin/ by hand "
                  "(sync only checks it), then `claude plugin marketplace update` and `claude plugin update`")
        if n or report["plugin"]:
            return 1
        print("sync --check: adapters up to date; plugin manifests in step")
        return 0
    for rel, text in card_native_updates(root).items():
        (root / rel).write_text(text, encoding="utf-8")
    report = apply(root)
    n = sum(len(report[k]) for k in ("missing", "changed", "stale"))
    print(f"sync: {len(report['missing'])} created, {len(report['changed'])} updated, {len(report['stale'])} removed" if n else "sync: nothing to do")
    for item in report["refused"]:
        print(f"sync: refused {item}")
    if report["refused"]:
        print(f"sync: {len(report['refused'])} card(s) refused; no adapter was written for them")
        return 1
    return 0


def _cli() -> int:
    ap = argparse.ArgumentParser(description="Regenerate engine adapters from canonical files.")
    ap.add_argument("--root", default=str(Path(__file__).resolve().parents[2]))
    ap.add_argument("--check", action="store_true", help="exit 1 on drift, write nothing")
    ap.add_argument("--plugin-registry", default=os.environ.get("JAJA_PLUGIN_REGISTRY") or os.environ.get("JOB_AGENCY_PLUGIN_REGISTRY") or str(DEFAULT_REGISTRY),
                    help="installed_plugins.json to compare the installed plugin against (--check only)")
    args = ap.parse_args()
    return main(args.root, check=args.check, registry=args.plugin_registry)


if __name__ == "__main__":
    sys.exit(_cli())
