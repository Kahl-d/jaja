# --------------------------------------------------------------------------- #
# headers
# --------------------------------------------------------------------------- #
def note(source: str) -> str:
    return f"{MARK} from {source} - do not edit"


def html_header(source: str) -> str:
    return f"<!-- {note(source)} -->"


def hash_header(source: str) -> str:
    return f"# {note(source)}"


def is_generated(text: str) -> bool:
    """True when the first two lines carry the marker or a JSON object has a _generated key."""
    head = text[:600]
    if MARK in "\n".join(head.splitlines()[:2]):
        return True
    if head.lstrip().startswith("{") and '"_generated"' in head:
        return True
    return False


def stamp(rel_out: str, content: str, source: str) -> str:
    """Add the GENERATED header appropriate to the file type."""
    ext = Path(rel_out).suffix.lower()
    if ext == ".md":
        if content.startswith("---\n"):
            return "---\n" + hash_header(source) + "\n" + content[4:]
        return html_header(source) + "\n" + content
    if ext == ".json":
        try:
            data = json.loads(content)
        except json.JSONDecodeError:
            return content
        if isinstance(data, dict):
            data = {"_generated": note(source), **{k: v for k, v in data.items() if k != "_generated"}}
            return dump_json(data)
        return content
    if ext in (".py", ".sh", ".bash", ".zsh", ".toml", ".yaml", ".yml", ".rules", ".cfg", ".ini", ".env"):
        if content.startswith("#!"):
            first, _, rest = content.partition("\n")
            return f"{first}\n{hash_header(source)}\n{rest}"
        return hash_header(source) + "\n" + content
    return content  # unknown type: copied verbatim, not stamped, not pruned


def dump_json(data: Any) -> str:
    return json.dumps(data, indent=2, ensure_ascii=False) + "\n"


# --------------------------------------------------------------------------- #
# small TOML emitter (stdlib has tomllib for reading only)
# --------------------------------------------------------------------------- #
def toml_str(s: Any) -> str:
    return json.dumps(str(s), ensure_ascii=False)


def toml_value(v: Any) -> str:
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, list):
        return "[" + ", ".join(toml_value(x) for x in v) + "]"
    if isinstance(v, dict):
        return "{ " + ", ".join(f"{toml_key(k)} = {toml_value(x)}" for k, x in v.items()) + " }"
    return toml_str(v)


def toml_key(k: str) -> str:
    return k if re.fullmatch(r"[A-Za-z0-9_-]+", k) else toml_str(k)


def toml_multiline(s: str) -> str:
    body = s.replace("\\", "\\\\").replace('"""', '\\"\\"\\"')
    if not body.endswith("\n"):
        body += "\n"
    return '"""\n' + body + '"""'


def toml_table(name: str, data: dict[str, Any]) -> list[str]:
    lines = [f"[{name}]"]
    nested = []
    for k, v in data.items():
        if isinstance(v, dict):
            nested.append((f"{name}.{toml_key(k)}", v))
        else:
            lines.append(f"{toml_key(k)} = {toml_value(v)}")
    for sub, v in nested:
        lines.append("")
        lines.extend(toml_table(sub, v))
    return lines


# --------------------------------------------------------------------------- #
# agents
# --------------------------------------------------------------------------- #

def one_line(text: Any) -> str:
    return " ".join(str(text or "").split())


def _as_list(v: Any) -> list[str]:
    if v is None or v == "":
        return []
    if isinstance(v, str):
        return [x.strip() for x in v.split(",") if x.strip()]
    return [str(x) for x in v]


def tools_refusal(meta: dict[str, Any]) -> str | None:
    """Why this role card must not be rendered, or None. An empty or missing allowlist is refused
    because engines treat an empty tool list as unrestricted."""
    if "tools_allow" not in meta or meta.get("tools_allow") in (None, ""):
        return "tools_allow is missing; list the tools the role needs (an absent list means ALL tools to Claude Code)"
    if not _as_list(meta.get("tools_allow")):
        return "tools_allow is empty; list the tools the role needs (an empty list means ALL tools to Claude Code)"
    return None


def render_claude_agent(meta: dict[str, Any], body: str, source: str) -> str:
    name = str(meta.get("name") or Path(source).stem)
    reason = tools_refusal(meta)
    if reason:
        raise ValueError(f"{source}: {reason}")
    lines = ["---", hash_header(source), f"name: {name}", f"description: {toml_str(one_line(meta.get('purpose') or meta.get('title') or name))}"]
    lines.append("tools: " + ", ".join(_as_list(meta.get("tools_allow"))))
    if meta.get("model"):
        lines.append(f"model: {meta['model']}")
    memory = meta.get("memory")
    if memory is True or str(memory).lower() in ("project", "user", "local"):
        lines.append(f"memory: {'project' if memory is True else str(memory).lower()}")
    skills = _as_list(meta.get("skills"))
    if skills:
        lines.append("skills: [" + ", ".join(skills) + "]")
    # Engine fields the card may carry (card key -> Claude Code frontmatter key). A tier or a stop
    # condition only binds when the engine sees it, so these reach the agent file verbatim.
    disallowed = _as_list(meta.get("disallowed_tools"))
    if disallowed:
        lines.append("disallowedTools: " + ", ".join(disallowed))
    for card_key, agent_key in (("effort", "effort"), ("permission_mode", "permissionMode"),
                                ("max_turns", "maxTurns"), ("omit_claude_md", "omitClaudeMd"),
                                ("background", "background")):
        v = meta.get(card_key)
        if v not in (None, ""):
            lines.append(f"{agent_key}: {str(v).lower() if isinstance(v, bool) else v}")
    deny = _as_list(meta.get("deny_commands"))
    if deny:
        # shell patterns the role may never run; enforced by hooks/role_deny.py (PreToolUse on Bash).
        # Never put these in disallowed_tools: a "Bash(...)" entry there removes the whole Bash tool (measured).
        lines.append("denyCommands:")
        lines.extend(f"  - {d}" for d in deny)
    hooks = meta.get("hooks")
    if isinstance(hooks, dict) and hooks:
        lines.append("hooks:")
        lines.extend("  " + ln for ln in json.dumps(hooks, indent=2).splitlines())
    initial = meta.get("initial_prompt")
    if isinstance(initial, str) and initial.strip():
        lines.append("initialPrompt: |")
        lines.extend("  " + ln for ln in initial.rstrip("\n").splitlines())
    lines.append("---")
    return "\n".join(lines) + "\n" + body.lstrip("\n")


# --------------------------------------------------------------------------- #
# lanes: a lane type is a session type (see the module docstring)
# --------------------------------------------------------------------------- #
def _lane_bundles(root: Path) -> list[tuple[Path, dict[str, Any], dict[str, Any], str]]:
    """(lane dir, LANE.yaml data, AGENT.md meta, AGENT.md body) for every `lanes/<type>/` that carries both
    files. A lane whose AGENT.md has no name is named lane-<type>."""
    found = []
    for agent_md in sorted(root.glob("lanes/*/AGENT.md")):
        lane_dir = agent_md.parent
        lane_yaml = lane_dir / "LANE.yaml"
        if lane_dir.name.startswith((".", "_")) or not lane_yaml.is_file():
            continue
        try:
            meta, body = fm.load(agent_md)
            lane = fm.parse_yaml(lane_yaml.read_text(encoding="utf-8")) or {}
        except (fm.FrontmatterError, OSError):
            continue
        if not isinstance(lane, dict):
            continue
        meta = dict(meta)
        meta.setdefault("name", f"lane-{lane.get('type') or lane_dir.name}")
        found.append((lane_dir, lane, meta, body))
    return found


def render_codex_agent(meta: dict[str, Any], body: str, source: str) -> str:
    name = str(meta.get("name") or Path(source).stem)
    preamble = [
        f"Role: {meta.get('title') or name} - department: {meta.get('department') or 'agency'} - "
        f"autonomy tier max: {meta.get('tier_max') or 'T0'}.",
        "Tools allowed: " + (", ".join(_as_list(meta.get("tools_allow"))) or "none") + ".",
    ]
    if _as_list(meta.get("skills")):
        preamble.append("Skills: " + ", ".join(_as_list(meta.get("skills"))) + ".")
    if _as_list(meta.get("connectors")):
        preamble.append("Connectors: " + ", ".join(_as_list(meta.get("connectors"))) + ".")
    instructions = "\n".join(preamble) + "\n\n" + body.strip() + "\n"
    lines = [
        hash_header(source),
        f"name = {toml_str(name)}",
        f"description = {toml_str(one_line(meta.get('purpose') or meta.get('title') or name))}",
        f"developer_instructions = {toml_multiline(instructions)}",
    ]
    return "\n".join(lines) + "\n"


def _rewrite_command(cmd: str, engine: str) -> str:
    if engine == "claude":
        # a project session in this repo: the plugin root is the project dir
        return cmd.replace("${CLAUDE_PLUGIN_ROOT}", "$CLAUDE_PROJECT_DIR").replace("$CLAUDE_PLUGIN_ROOT", "$CLAUDE_PROJECT_DIR")
    cmd = cmd.replace("${CLAUDE_PLUGIN_ROOT}", ".").replace("$CLAUDE_PLUGIN_ROOT", ".")
    cmd = cmd.replace("${CLAUDE_PROJECT_DIR}/", "").replace("$CLAUDE_PROJECT_DIR/", "")
    return cmd.replace("${CLAUDE_PROJECT_DIR}", ".").replace("$CLAUDE_PROJECT_DIR", ".")


def _hook_events(hooks_json: Any) -> dict[str, list[dict[str, Any]]]:
    if isinstance(hooks_json, dict) and isinstance(hooks_json.get("hooks"), dict):
        hooks_json = hooks_json["hooks"]
    return hooks_json if isinstance(hooks_json, dict) else {}


def _rewrite_hooks(events: dict[str, list[dict[str, Any]]], engine: str) -> dict[str, list[dict[str, Any]]]:
    out: dict[str, list[dict[str, Any]]] = {}
    for event, groups in events.items():
        if event.startswith("_") or not isinstance(groups, list):
            continue
        new_groups = []
        for group in groups:
            if not isinstance(group, dict):
                continue
            g = dict(group)
            g["hooks"] = [
                {**h, "command": _rewrite_command(h["command"], engine)} if isinstance(h, dict) and isinstance(h.get("command"), str) else h
                for h in group.get("hooks", [])
            ]
            new_groups.append(g)
        out[event] = new_groups
    return out


def _is_managed_command(cmd: Any) -> bool:
    """A hook command that runs one of this repo's hooks through the project dir: sync wrote it and may drop it."""
    return isinstance(cmd, str) and "$CLAUDE_PROJECT_DIR/hooks/" in cmd


def merge_hooks(existing: dict[str, Any], plugin_events: dict[str, list[dict[str, Any]]]) -> dict[str, Any]:
    """Merge hooks.json into settings hooks: hand-written hooks stay, a managed hook command that hooks.json no
    longer lists is dropped, and a listed one is added once (same matcher + command)."""
    wanted = {h.get("command") for groups in plugin_events.values() for g in groups if isinstance(g, dict)
              for h in g.get("hooks", []) if isinstance(h, dict)}
    merged: dict[str, Any] = {}
    for event, groups in (existing or {}).items():
        if not isinstance(groups, list):
            merged[event] = groups
            continue
        kept = []
        for g in groups:
            if not isinstance(g, dict) or "hooks" not in g:
                kept.append(g)
                continue
            hs = [h for h in g["hooks"] if not (isinstance(h, dict) and _is_managed_command(h.get("command"))
                                                and h.get("command") not in wanted)]
            if hs:
                kept.append({**g, "hooks": hs})
        if kept:
            merged[event] = kept
    for event, groups in plugin_events.items():
        current = merged.setdefault(event, [])
        seen = {
            (str(g.get("matcher", "")), h.get("command"))
            for g in current
            if isinstance(g, dict)
            for h in g.get("hooks", [])
            if isinstance(h, dict)
        }
        for group in groups:
            fresh = [h for h in group.get("hooks", []) if not (isinstance(h, dict) and (str(group.get("matcher", "")), h.get("command")) in seen)]
            if fresh:
                current.append({**group, "hooks": fresh})
    return merged


def _load_json(path: Path) -> Any:
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return None


def _copy_tree(root: Path, src_dir: Path, dst_rel: str, outputs: dict[str, str]) -> None:
    for f in sorted(p for p in src_dir.rglob("*") if p.is_file()):
        if f.name.startswith(".") or "__pycache__" in f.parts:
            continue
        rel_src = f.relative_to(root).as_posix()
        rel_out = f"{dst_rel}/{f.relative_to(src_dir).as_posix()}"
        try:
            content = f.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            outputs[rel_out] = f.read_bytes()  # type: ignore[assignment]
            continue
        outputs[rel_out] = stamp(rel_out, content, rel_src)


def _role_cards(root: Path) -> list[tuple[str, dict[str, Any], str]]:
    """(source path, meta, body) for every parseable, named role card in agents/*.md."""
    cards = []
    for path in sorted(root.glob("agents/*.md")):
        if path.name.upper() == "README.MD" or path.name.startswith((".", "_")):
            continue
        try:
            meta, body = fm.load(path)
        except fm.FrontmatterError:
            continue
        if meta.get("name"):
            cards.append((path.relative_to(root).as_posix(), meta, body))
    return cards


def refusals(root: str | Path) -> list[str]:
    """"<source>: <reason>" for every role card or lane agent sync refuses to render."""
    root = Path(root).resolve()
    out = [f"{source}: {reason}" for source, meta, _ in _role_cards(root) if (reason := tools_refusal(meta))]
    out += [f"{(d / 'AGENT.md').relative_to(root).as_posix()}: {reason}"
            for d, _, meta, _ in _lane_bundles(root) if (reason := tools_refusal(meta))]
    return out


def _slug(name: Any) -> str:
    return re.sub(r"[^a-z0-9-]+", "-", str(name).lower()).strip("-")


def plan(root: str | Path) -> dict[str, Any]:
    """Compute every output as {relative path: content}. Reads only. Refused cards are skipped."""
    root = Path(root).resolve()
    out: dict[str, Any] = {}

    # roles -> agents (a card with an empty or missing tools_allow is refused, never rendered)
    for source, meta, body in _role_cards(root):
        if tools_refusal(meta) or str(meta.get("status", "")).lower() == "archived":
            continue                      # an archived role keeps its card but gets no engine agent
        name = _slug(meta["name"])
        out[f".claude/agents/{name}.md"] = render_claude_agent(meta, body, source)
        out[f".codex/agents/{name}.toml"] = render_codex_agent(meta, body, source)

    # lanes -> the lane agent and its settings
    for lane_dir, lane, meta, body in _lane_bundles(root):
        if tools_refusal(meta):
            continue
        source = (lane_dir / "AGENT.md").relative_to(root).as_posix()
        name = _slug(meta["name"])
        out[f".claude/agents/{name}.md"] = render_claude_agent(meta, body, source)
        out[f".codex/agents/{name}.toml"] = render_codex_agent(meta, body, source)
        settings: dict[str, Any] = {"agent": name, "env": dict(LANE_ENV)}
        extra_env = lane.get("env")
        if isinstance(extra_env, dict):
            settings["env"].update({str(k): str(v) for k, v in extra_env.items()})
        out[f"{LANE_SETTINGS_DIR}/{lane_dir.name}.json"] = dump_json(settings)   # strict JSON: no marker key

    # skills -> the Codex mirror (Claude Code reads ./skills through the plugin)
    skills_dir = root / "skills"
    if skills_dir.is_dir():
        for sdir in sorted(p for p in skills_dir.iterdir() if p.is_dir() and (p / "SKILL.md").is_file()):
            _copy_tree(root, sdir, f".agents/skills/{sdir.name}", out)

    # hooks
    hooks_path = root / HOOKS_JSON
    hooks_json = _load_json(hooks_path) if hooks_path.is_file() else None
    if hooks_json is not None:
        events = _hook_events(hooks_json)
        settings_path = root / ".claude" / "settings.json"
        existing = _load_json(settings_path) if settings_path.is_file() else None
        existing = existing if isinstance(existing, dict) else {}
        merged_hooks = merge_hooks(existing.get("hooks", {}), _rewrite_hooks(events, "claude"))
        settings: dict[str, Any] = {}
        if "$schema" in existing:
            settings["$schema"] = existing["$schema"]
        # No "_generated" key here: Claude Code validates settings.json strictly. Only the "hooks"
        # key is managed by sync (merged from hooks.json); every other key is hand-owned.
        for k, v in existing.items():
            if k not in ("$schema", "_generated", "hooks"):
                settings[k] = v
        settings["hooks"] = merged_hooks
        out[".claude/settings.json"] = dump_json(settings)
        out[".codex/hooks.json"] = dump_json({"_generated": note(HOOKS_JSON), "hooks": _rewrite_hooks(events, "codex")})

    # mcp: .mcp.json is the source; Codex reads config.toml
    mcp_path = root / ".mcp.json"
    mcp = _load_json(mcp_path) if mcp_path.is_file() else None
    if isinstance(mcp, dict):
        servers = mcp.get("mcpServers", mcp.get("servers", {}))
        servers = {k: v for k, v in servers.items() if not k.startswith("_")} if isinstance(servers, dict) else {}
        lines = [hash_header(".mcp.json"), "# MCP servers only. Trust and sandbox settings live in ~/.codex/config.toml.", ""]
        for name, spec in servers.items():
            lines.extend(toml_table(f"mcp_servers.{toml_key(name)}", spec if isinstance(spec, dict) else {}))
            lines.append("")
        out[".codex/config.toml"] = "\n".join(lines).rstrip("\n") + "\n"
    return out


# --------------------------------------------------------------------------- #
# checking / applying
# --------------------------------------------------------------------------- #
def _managed_generated_files(root: Path) -> list[Path]:
    found: list[Path] = []
    for pattern in MANAGED_DIR_PATTERNS:
        d = root / pattern
        if not d.is_dir():
            continue
        for f in d.rglob("*"):
            if f.is_file() and "__pycache__" not in f.parts and f.suffix.lower() in (".md", ".toml", ".json", ".py", ".sh", ".yaml", ".yml"):
                try:
                    if is_generated(f.read_text(encoding="utf-8")):
                        found.append(f)
                except (OSError, UnicodeDecodeError):
                    continue
    for pattern in UNMARKED_MANAGED:
        d = root / pattern
        if d.is_dir():
            found += [f for f in d.rglob("*") if f.is_file()]
    return sorted(set(found))


def _read(path: Path, binary: bool) -> Any:
    return path.read_bytes() if binary else path.read_text(encoding="utf-8")


def diff(root: str | Path, outputs: dict[str, Any] | None = None, registry: str | Path | None = None) -> dict[str, list[str]]:
    root = Path(root).resolve()
    outputs = plan(root) if outputs is None else outputs
    changed, missing, stale = [], [], []
    for rel, content in outputs.items():
        p = root / rel
        if not p.exists():
            missing.append(rel)
            continue
        try:
            if _read(p, isinstance(content, bytes)) != content:
                changed.append(rel)
        except (OSError, UnicodeDecodeError):
            changed.append(rel)
    for f in _managed_generated_files(root):
        rel = f.relative_to(root).as_posix()
        if rel not in outputs:
            stale.append(rel)
    return {"changed": changed, "missing": missing, "stale": stale, "refused": refusals(root),
            "plugin": plugin_drift(root, registry)}


