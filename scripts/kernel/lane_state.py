#!/usr/bin/env python3
"""lane_state.py - the small live state of a lane, extracted from its append-only hub lane file.

Why: hub/lanes/<LANE>.md files are append-only logs that grow to hundreds of KB. Every lane start rewrites the file's
`## Identity` block, and an edit needs a full read first, so a resume costs tens of thousands of tokens before any
work, mostly to find one PARKED section. The log stays (rule 12: never lose history); this script writes the part a
lane actually needs, next to it:

  hub/lanes/<LANE>-STATE.md   the newest `## Identity` block, the newest park/handoff/retire/go/open section, the newest
                              "NEEDS <owner>" section, the live end of <LANE>-ORDERS.md (last headings, newest two
                              orders in full) and the headings of the last few posts (each section capped)

Lanes never Read-then-Edit their log to change the Identity block: they APPEND a new `## Identity <date>` section
(`cat >> hub/lanes/<LANE>.md`), and this script picks the newest. The Stop hook (lane_handover.py) runs `--write`
after every turn that changed the lane's files. Deterministic, no model. Read-only on the log.

Usage:
  python3 scripts/kernel/lane_state.py FOCUSED                 # print the state
  python3 scripts/kernel/lane_state.py FOCUSED --write         # write hub/lanes/FOCUSED-STATE.md
  python3 scripts/kernel/lane_state.py --all --write           # every lane file in hub/lanes/
  python3 scripts/kernel/lane_state.py --stats                 # log bytes vs state bytes, per lane
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import agency_paths as _ap  # noqa: E402
import agency_config as agency_cfg  # noqa: E402
ROOT = _ap.CODE_ROOT
LANES = _ap.DATA_ROOT / "hub" / "lanes"
LIVE = re.compile(r"PARKED|RETIRED|Handoff|HANDOFF|\bGO\b|\bOPEN\b|UNPARKED|started", re.I)
# The heading of a section that waits on the owner: "NEEDS YOU", "NEEDS OWNER" or "NEEDS <identity.owner_label>".
NEEDS_RE = re.compile(r"\bNEEDS (?:YOU|OWNER|" + re.escape(str(agency_cfg.get("identity.owner_label", "you") or "you").upper()) + r")\b")
SECTION_CAP = 2_400
POSTS_SHOWN = 6


def sections(text: str) -> list[tuple[str, str]]:
    """(heading, body) for every `## ` section, in file order."""
    parts = re.split(r"(?m)^(## .*)$", text)
    out = []
    for i in range(1, len(parts), 2):
        out.append((parts[i].strip(), parts[i + 1].strip("\n")))
    return out


def cap(body: str, n: int = SECTION_CAP) -> str:
    return body if len(body) <= n else body[:n].rstrip() + f"\n… ({len(body) - n} more bytes in the log)"


ORDERS_HEADINGS = 12
ORDERS_BODIES = 2
ORDERS_BODY_CAP = 1_500


def orders_digest(lane: str) -> list[str]:
    """The live end of hub/lanes/<LANE>-ORDERS.md (appended over time, `# §...` sections): the last few headings
    and the full text of the newest two, so a start never reads 30-60 KB of past orders."""
    p = LANES / f"{lane}-ORDERS.md"
    if not p.is_file():
        return []
    parts = re.split(r"(?m)^(# §.*)$", p.read_text(errors="replace"))
    secs = [(parts[i].strip(), parts[i + 1].strip("\n")) for i in range(1, len(parts), 2)]
    if not secs:
        return []
    out = [f"## Orders (live end of hub/lanes/{lane}-ORDERS.md, {p.stat().st_size} bytes, {len(secs)} sections)"]
    out += [f"- {h[2:]}" for h, _ in secs[-ORDERS_HEADINGS:]]
    for h, b in secs[-ORDERS_BODIES:]:
        out += ["", f"### {h[2:]}", cap(b, ORDERS_BODY_CAP)]
    return out + [""]


def state(lane: str) -> str:
    log = LANES / f"{lane}.md"
    secs = sections(log.read_text(errors="replace"))
    ident = next((s for s in reversed(secs) if s[0].lower().startswith("## identity")), None)
    live = next((s for s in reversed(secs) if LIVE.search(s[0]) and not s[0].lower().startswith("## identity")), None)
    needs = next((s for s in reversed(secs) if NEEDS_RE.search(s[0].upper())), None)
    posts = [h for h, _ in secs if re.match(r"## (\d{4}-\d{2}-\d{2}|Post|ROUND|AGENCY)", h)][-POSTS_SHOWN:]
    out = [f"<!-- GENERATED by scripts/kernel/lane_state.py from hub/lanes/{lane}.md - do not edit; append to the log -->",
           f"# {lane} · live state",
           f"Log: hub/lanes/{lane}.md ({log.stat().st_size} bytes, {len(secs)} sections). Read the log only for history.", ""]
    for s in (ident, live, needs):
        if s and s[0] not in {o for o in out}:
            out += [s[0], cap(s[1]), ""]
    out += orders_digest(lane)
    if posts:
        out += ["## Last section headings in the log", *[f"- {h[3:]}" for h in posts], ""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("lane", nargs="?")
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--stats", action="store_true")
    ap.add_argument("--quiet", action="store_true", help="no output (the Stop hook)")
    ap.add_argument("--hub", type=Path, help="the hub folder (default: <data folder>/hub)")
    a = ap.parse_args(argv)
    global LANES
    if a.hub:
        LANES = a.hub / "lanes"
    names = sorted(p.stem for p in LANES.glob("*.md") if not p.stem.endswith(("-ORDERS", "-STATE")) and not p.stem.startswith("_"))
    if a.stats or a.all:
        todo = names
    elif a.lane:
        todo = [a.lane]
    else:
        ap.error("name a lane, or --all, or --stats")
    for n in todo:
        if not (LANES / f"{n}.md").is_file():
            print(f"{n}: no hub/lanes/{n}.md", file=sys.stderr)
            continue
        s = state(n)
        if a.stats:
            print(f"{n:22} log {(LANES / f'{n}.md').stat().st_size:>8}  state {len(s.encode()):>6}")
        elif a.write:
            (LANES / f"{n}-STATE.md").write_text(s + "\n")
            if not a.quiet:
                print(f"wrote hub/lanes/{n}-STATE.md ({len(s.encode())} bytes)")
        else:
            print(s)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
