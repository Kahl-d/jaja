from pathlib import Path

import pytest

import sync

LANE_AGENT = """---
name: lane-resume
title: Resume lane
tools_allow: [Read, Write, Edit, Grep, Glob, Bash, Agent]
model: opus
effort: high
skills: [brief]
memory: project
permission_mode: acceptEdits
max_turns: 200
initial_prompt: |
  Run ListAgents. Write your identity block. Then read the live wire.
---
# Resume lane

You own one scope: resumes/variants/**.
"""

LANE_YAML = """type: resume
roster: [researcher]
skills: [brief]
scope: ["resumes/variants/**"]
env:
  EXTRA_FLAG: "1"
"""

HOOKS = {"hooks": {
    "SessionStart": [{"hooks": [{"type": "command", "command": 'python3 "${CLAUDE_PLUGIN_ROOT}/hooks/lane_context.py"'}]}],
    "PreToolUse": [{"matcher": "Write|Edit", "hooks": [{"type": "command", "command": 'python3 "${CLAUDE_PLUGIN_ROOT}/hooks/guard_generated_files.py"'}]}],
}}


def write_plugin(root: Path, version: str = "0.1.0", market_version: str | None = None, agents: str = "./.claude/agents") -> None:
    (root / ".claude-plugin").mkdir(exist_ok=True)
    (root / "hooks").mkdir(exist_ok=True)
    (root / "hooks" / "hooks.json").write_text(json.dumps(HOOKS), encoding="utf-8")
    (root / ".mcp.json").write_text(json.dumps({"mcpServers": {}}), encoding="utf-8")
    (root / ".claude" / "agents").mkdir(parents=True, exist_ok=True)
    (root / ".claude-plugin" / "plugin.json").write_text(json.dumps({
        "name": "jaja", "version": version, "skills": "./skills", "agents": agents,
        "hooks": "./hooks/hooks.json", "mcpServers": "./.mcp.json"}), encoding="utf-8")
    (root / ".claude-plugin" / "marketplace.json").write_text(json.dumps({
        "name": "jaja", "plugins": [{"name": "jaja", "source": "./", "version": market_version or version}]}),
        encoding="utf-8")


def add_lane(root: Path) -> Path:
    lane = root / "lanes" / "resume"
    lane.mkdir(parents=True)
    (lane / "AGENT.md").write_text(LANE_AGENT, encoding="utf-8")
    (lane / "LANE.yaml").write_text(LANE_YAML, encoding="utf-8")
    return lane


def test_roles_render_claude_and_codex_agents(repo: Path):
    assert sync.main(repo) == 0
    agent = repo / ".claude" / "agents" / "researcher.md"
    text = agent.read_text(encoding="utf-8")
    assert text.startswith("---\n# GENERATED by scripts/kernel/sync.py from agents/researcher.md")
    assert "name: researcher" in text and "model: sonnet" in text
    assert "tools: Read, Grep, WebSearch" in text and "Search first. Cite every claim." in text
    raw = (repo / ".codex" / "agents" / "researcher.toml").read_text(encoding="utf-8")
    assert raw.startswith("# GENERATED by scripts/kernel/sync.py from agents/researcher.md")
    data = tomllib.loads(raw)
    assert data["name"] == "researcher" and "Search first" in data["developer_instructions"]


