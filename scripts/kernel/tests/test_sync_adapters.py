def test_empty_or_missing_tools_allow_is_refused_never_rendered_unrestricted(repo: Path, capsys):
    # Claude Code reads an empty `tools:` as "all tools", so an empty allowlist must never render.
    card = (repo / "agents" / "researcher.md").read_text(encoding="utf-8")
    (repo / "agents" / "sender.md").write_text(card.replace("name: researcher", "name: sender")
                                               .replace("tools_allow: [Read, Grep, WebSearch]", "tools_allow: []"), encoding="utf-8")
    (repo / "agents" / "ghost.md").write_text(card.replace("name: researcher", "name: ghost")
                                              .replace("tools_allow: [Read, Grep, WebSearch]\n", ""), encoding="utf-8")
    old = repo / ".claude" / "agents" / "sender.md"        # an adapter an older sync rendered with `tools: []`
    old.parent.mkdir(parents=True)
    old.write_text("---\n# GENERATED by scripts/kernel/sync.py from agents/sender.md - do not edit\nname: sender\ntools: []\n---\n", encoding="utf-8")
    outputs = sync.plan(repo)
    assert not any(k.endswith(("/sender.md", "/ghost.md", "/sender.toml", "/ghost.toml")) for k in outputs)
    assert all("tools: []" not in v for v in outputs.values() if isinstance(v, str))
    assert sorted(r.split(":")[0] for r in sync.diff(repo)["refused"]) == ["agents/ghost.md", "agents/sender.md"]
    assert sync.main(repo, check=True) == 1
    capsys.readouterr()
    assert sync.main(repo) == 1
    out = capsys.readouterr().out
    assert "refused agents/sender.md" in out and "tools_allow" in out
    assert not old.exists()                                 # fail closed: the unrestricted adapter is pruned
    assert (repo / ".claude" / "agents" / "researcher.md").exists()


