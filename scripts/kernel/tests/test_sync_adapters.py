def test_hooks_merge_into_settings_and_codex_and_mcp_into_toml(repo: Path):
    write_plugin(repo)
    (repo / ".mcp.json").write_text(json.dumps({"mcpServers": {"jobs": {
        "command": "uv", "args": ["run", "x"], "env": {"TOKEN": "${JOBS_TOKEN}"}}}}), encoding="utf-8")
    (repo / ".claude" / "settings.json").write_text(json.dumps({
        "permissions": {"allow": ["Bash(git status)"]},
        "hooks": {"SessionEnd": [{"hooks": [{"type": "command", "command": "bash old.sh"}]}]}}), encoding="utf-8")
    sync.main(repo)
    settings = json.loads((repo / ".claude" / "settings.json").read_text(encoding="utf-8"))
    assert settings["permissions"] == {"allow": ["Bash(git status)"]} and "_generated" not in settings
    assert settings["hooks"]["SessionEnd"][0]["hooks"][0]["command"] == "bash old.sh"
    assert settings["hooks"]["SessionStart"][0]["hooks"][0]["command"] == 'python3 "$CLAUDE_PROJECT_DIR/hooks/lane_context.py"'
    codex = json.loads((repo / ".codex" / "hooks.json").read_text(encoding="utf-8"))
    assert "_generated" in codex
    assert codex["hooks"]["SessionStart"][0]["hooks"][0]["command"] == 'python3 "./hooks/lane_context.py"'
    config = (repo / ".codex" / "config.toml").read_text(encoding="utf-8")
    assert config.startswith("# GENERATED by scripts/kernel/sync.py")
    parsed = tomllib.loads(config)
    assert parsed["mcp_servers"]["jobs"]["args"] == ["run", "x"] and parsed["mcp_servers"]["jobs"]["env"]["TOKEN"] == "${JOBS_TOKEN}"
    assert not (repo / "CLAUDE.md").exists() and not (repo / ".agents" / "plugins").exists()   # manifests are hand-written
    assert sync.main(repo, check=True) == 0                         # idempotent
    sync.main(repo)
    assert len(json.loads((repo / ".claude" / "settings.json").read_text(encoding="utf-8"))["hooks"]["SessionStart"]) == 1


def test_a_hook_removed_from_hooks_json_leaves_settings(repo: Path):
    write_plugin(repo)
    sync.main(repo)
    hooks = json.loads((repo / "hooks" / "hooks.json").read_text(encoding="utf-8"))
    del hooks["hooks"]["PreToolUse"]
    (repo / "hooks" / "hooks.json").write_text(json.dumps(hooks), encoding="utf-8")
    sync.main(repo)
    settings = json.loads((repo / ".claude" / "settings.json").read_text(encoding="utf-8"))
    assert "PreToolUse" not in settings["hooks"] and "SessionStart" in settings["hooks"]


