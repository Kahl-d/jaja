def test_check_detects_hand_edits_and_stale_files(repo: Path):
    sync.main(repo)
    assert sync.main(repo, check=True) == 0
    agent = repo / ".claude" / "agents" / "researcher.md"
    agent.write_text(agent.read_text(encoding="utf-8") + "\nhand edit\n", encoding="utf-8")
    assert sync.main(repo, check=True) == 1
    assert "hand edit" in agent.read_text(encoding="utf-8")        # --check never writes
    sync.main(repo)
    assert "hand edit" not in agent.read_text(encoding="utf-8")
    (repo / "agents" / "researcher.md").unlink()                   # a generated file whose source went is stale
    assert sync.main(repo, check=True) == 1
    sync.main(repo)
    assert not agent.exists() and not (repo / ".codex" / "agents" / "researcher.toml").exists()


