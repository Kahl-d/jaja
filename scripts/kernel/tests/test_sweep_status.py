def test_feed_items_reach_the_briefing_under_the_right_headings(tmp_path):
    _feed(tmp_path,
          needs=[{"title": "Confirm the start date", "why": "clock.yaml has it provisional", "link": "clock.yaml"}],
          deadlines=[{"title": "Work authorization ends", "date": "2026-10-02", "hard": True, "link": "clock.yaml"},
                     {"title": "Approval A-2026-0001 expires (send-email)", "date": "2026-09-24", "hard": False,
                      "link": "work/approvals/A-2026-0001.md"},
                     {"title": "90-day clock ends", "date": "2026-12-31", "hard": True, "link": "clock.yaml"}],
          today=[{"title": "Job clock: day 7 of 90", "link": "DASHBOARD.md"}])
    md, data = _home(tmp_path)
    needs = [e for e in data["needs_you"] if e["kind"] == "feed"]
    assert [(e["id"], e["project"], e["title"], e["path"]) for e in needs] == [("job-search", "job-search", "Confirm the start date", "clock.yaml")]
    assert "[job-search] Confirm the start date (clock.yaml has it provisional)" in _section(md, "Needs you")
    assert [(e["title"], e["date"], e["days"], e["hard"]) for e in data["deadlines"]["due_soon"]] == [("Work authorization ends", "2026-10-02", 7, True)]
    assert [(e["title"], e["days"]) for e in data["deadlines"]["overdue"]] == [("Approval A-2026-0001 expires (send-email)", -1)]
    deadlines = _section(md, "Deadlines")
    assert "- 2026-10-02 (in 7d) HARD [job-search] Work authorization ends" in deadlines
    assert "- OVERDUE 2026-09-24 (1d) [job-search] Approval A-2026-0001 expires (send-email)" in deadlines
    assert "2026-12-31" not in deadlines                                          # beyond the 7-day horizon
    assert "- [job-search] Job clock: day 7 of 90" in _section(md, "Today")
    assert data["feeds"] == [{"project": "job-search", "path": "state/home-feed.json", "generated_at": "2026-09-25T17:00:00Z", "stale": False}]
    assert "0 schema errors" in md.splitlines()[-1]


def test_a_feed_older_than_36_hours_is_flagged_stale(tmp_path):
    _feed(tmp_path, generated_at="2026-09-24T05:59:59Z")                      # 36 h 0 min 1 s before NOW
    _, data = _home(tmp_path)
    stale = [e for e in data["needs_you"] if "stale" in e["why"]]
    assert [(e["id"], e["title"], e["path"]) for e in stale] == [
        ("job-search", "job-search board is stale (last built 2026-09-24)", "state/home-feed.json")]
    assert data["feeds"][0]["stale"] is True


def test_a_feed_36_hours_old_or_newer_is_not_stale(tmp_path):
    _feed(tmp_path, generated_at="2026-09-24T06:00:00Z")
    _, data = _home(tmp_path)
    assert not any("stale" in e["why"] for e in data["needs_you"]) and data["feeds"][0]["stale"] is False


def test_unreadable_or_malformed_feeds_are_skipped_and_counted_as_schema_errors(tmp_path):
    _feed(tmp_path, raw="{not json")
    _feed(tmp_path, "second", where="projects/second/state/home-feed.json",
          raw=json.dumps({"project": "second", "generated_at": "yesterday", "needs_you": {}, "deadlines": [], "today": []}))
    _feed(tmp_path, "good", where="projects/good/state/home-feed.json", needs=[{"title": "Decide", "why": "offer", "link": "x.md"}])
    md, data = _home(tmp_path)
    assert [f["project"] for f in data["feeds"]] == ["good"] and [e["title"] for e in data["needs_you"]] == ["Decide"]
    assert len(data["feed_errors"]) == 2 and data["schema_errors"] == 2
    assert "2 schema errors" in md.splitlines()[-1]


def test_bad_items_are_skipped_and_counted_but_the_rest_of_the_feed_is_kept(tmp_path):
    _feed(tmp_path, needs=[{"title": "", "why": "x", "link": "a"}, {"title": "Keep me", "why": "y", "link": "b"}],
          deadlines=[{"title": "No date", "date": "soon", "hard": True, "link": "c"},
                     {"title": "Hard is not a bool", "date": "2026-09-26", "hard": "yes", "link": "d"},
                     {"title": "Kept", "date": "2026-09-26", "hard": False, "link": "e"}],
          today=["not a mapping", {"title": "Today kept", "link": "f"}])
    _, data = _home(tmp_path)
    assert [e["title"] for e in data["needs_you"]] == ["Keep me"]
    assert [e["title"] for e in data["deadlines"]["due_soon"]] == ["Kept"]
    assert [e["title"] for e in data["today_items"]] == ["Today kept"]
    assert len(data["feed_errors"]) == 4 and data["schema_errors"] == 4


def test_validate_feed_names_every_problem():
    assert sweep.validate_feed({"project": "p", "generated_at": "2026-09-25T00:00:00Z", "needs_you": [], "deadlines": [], "today": []}) == []
    errors = sweep.validate_feed({"project": "", "generated_at": "never", "needs_you": [], "deadlines": None})
    assert any("project" in e for e in errors) and any("generated_at" in e for e in errors)
    assert any("deadlines" in e for e in errors) and any("today" in e for e in errors)
    assert sweep.validate_feed(["not", "a", "mapping"]) == ["top level is not a JSON object"]


