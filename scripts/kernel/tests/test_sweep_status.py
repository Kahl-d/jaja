import datetime as dt
import json
from pathlib import Path

import sweep
from roots import Roots

TODAY = dt.date(2026, 9, 24)
NOW = dt.datetime(2026, 9, 25, 18, 0, tzinfo=dt.timezone.utc)


def _task(root: Path, name: str, **meta) -> None:
    lines = ["---"] + [f"{k}: {v}" for k, v in meta.items()] + ["---", f"# {meta['title']}", ""]
    (root / "work" / "tasks" / f"{name}.md").write_text("\n".join(lines), encoding="utf-8")


def make_root(tmp_path: Path) -> Path:
    root = tmp_path / "agency"
    for d in ("work/tasks", "work/inbox", "work/approvals", "agents", "routines", "skills/brief", "lanes/hunt", "logs/runs/morning-brief"):
        (root / d).mkdir(parents=True)
    common = dict(type="task", owner="owner", priority="P1", created="2026-09-01", updated="2026-09-20")
    _task(root, "T-2026-0001-overdue", id="T-2026-0001", title="Overdue thing", status="open", due="2026-09-20", **common)
    _task(root, "T-2026-0002-hard", id="T-2026-0002", title="Hard deadline soon", status="open",
          due="2026-09-26", hard_deadline="2026-09-27", **common)
    _task(root, "T-2026-0003-approval", id="T-2026-0003", title="Approve the email", type="approval",
          status="needs-human", owner="role:admin-assistant", priority="P0", created="2026-09-23", updated="2026-09-23")
    _task(root, "T-2026-0004-done", id="T-2026-0004", title="Already done", status="done", due="2026-09-01", evidence="receipt", **common)
    (root / "work" / "inbox" / "capture-1.md").write_text("hello\n", encoding="utf-8")
    (root / "work" / "inbox" / "capture-2.md").write_text("hello\n", encoding="utf-8")
    (root / "agents" / "scout.md").write_text(
        "---\nname: scout\ntitle: Scout\ndepartment: agency\npurpose: Finds roles.\ntools_allow: [Read]\n"
        "tier_max: T1\nmodel: sonnet\nstatus: active\n---\n# Scout\n", encoding="utf-8")
    (root / "agents" / "sender.md").write_text(
        "---\nname: sender\ntitle: Sender\ndepartment: agency\npurpose: Sends approved items.\ntools_allow: []\n"
        "tier_max: T3\nmodel: haiku\nstatus: probation\n---\n# Sender\n", encoding="utf-8")
    (root / "routines" / "morning-brief.yaml").write_text(
        "name: morning-brief\npurpose: Brief.\nruns_on: cloud\nengine: claude\nschedule: '0 7 * * *'\n"
        "action: skill:daily-job-plan\ntier: T1\nenabled: true\nowner: owner\n", encoding="utf-8")
    (root / "skills" / "brief" / "SKILL.md").write_text("---\nname: brief\ndescription: Use for the brief.\n---\n# Brief\n", encoding="utf-8")
    (root / "lanes" / "hunt" / "LANE.yaml").write_text("type: hunt\ntitle: Hunt lane\nroster: [scout]\n", encoding="utf-8")
    (root / "logs" / "runs" / "morning-brief" / "2026-09-23.md").write_text("ok\n", encoding="utf-8")
    return root


def _section(md: str, name: str) -> str:
    start = md.index(f"## {name}")
    nxt = md.find("\n## ", start + 1)
    return md[start: nxt if nxt != -1 else len(md)]


def _feed(root: Path, project: str = "job-search", *, generated_at: str = "2026-09-25T17:00:00Z", needs=None,
          deadlines=None, today=None, raw: str | None = None, where: str = "state/home-feed.json") -> Path:
    path = root / where
    path.parent.mkdir(parents=True, exist_ok=True)
    if raw is not None:
        path.write_text(raw, encoding="utf-8")
        return path
    path.write_text(json.dumps({"project": project, "generated_at": generated_at, "needs_you": needs or [],
                                "deadlines": deadlines or [], "today": today or []}), encoding="utf-8")
    return path


def _home(root: Path, now: dt.datetime = NOW, today: dt.date = dt.date(2026, 9, 25)):
    return sweep.build_home(sweep.load_docs(root), today, generated_at="2026-09-25T11:00:00", now=now)


def test_build_home_places_items_under_the_right_headings(tmp_path: Path):
    root = make_root(tmp_path)
    md, data = sweep.build_home(sweep.load_docs(root), TODAY)
    assert md.splitlines()[0].startswith("<!-- GENERATED by scripts/kernel/sweep.py")
    assert "Approve the email" in _section(md, "Needs you")
    assert "Overdue thing" in _section(md, "Deadlines") and "Hard deadline soon" in _section(md, "Deadlines")
    assert "HARD" in _section(md, "Deadlines")
    assert "scout" in _section(md, "Agents") and "1 skill(s)" in _section(md, "Agents") and "hunt" in _section(md, "Agents")
    assert "morning-brief" in _section(md, "Routines") and "2026-09-23" in _section(md, "Routines")
    assert "Already done" not in md and "2" in _section(md, "Inbox")
    assert "Projects" not in md and "Builds" not in md and "Company" not in md
    assert "last sweep" in md.splitlines()[-1] and len(md.splitlines()) <= 150
    assert [e["id"] for e in data["needs_you"]] == ["T-2026-0003"]
    assert [t["id"] for t in data["deadlines"]["overdue"]] == ["T-2026-0001"]
    assert [t["id"] for t in data["deadlines"]["due_soon"]] == ["T-2026-0002"] and data["deadlines"]["due_soon"][0]["hard"] is True
    assert data["inbox_count"] == 2 and data["roles_by_status"] == {"active": ["scout"], "probation": ["sender"]}
    assert data["routines"][0]["last_run"] == "2026-09-23" and data["date"] == "2026-09-24"
    assert [x["type"] for x in data["lanes"]] == ["hunt"]


