def test_two_feeds_merge_side_by_side(tmp_path):
    _feed(tmp_path, "job-search", needs=[{"title": "Confirm the start date", "why": "provisional", "link": "a"}])
    _feed(tmp_path, "second", where="projects/second/state/home-feed.json", needs=[{"title": "Approve the plan", "why": "gate", "link": "b"}],
          deadlines=[{"title": "Portal closes", "date": "2026-09-28", "hard": True, "link": "c"}])
    _, data = _home(tmp_path)
    assert sorted((e["project"], e["title"]) for e in data["needs_you"]) == [("job-search", "Confirm the start date"), ("second", "Approve the plan")]
    assert [(e["id"], e["title"]) for e in data["deadlines"]["due_soon"]] == [("second", "Portal closes")]


def test_briefing_stays_within_150_lines_with_large_feeds(tmp_path):
    rows = [{"title": f"Item {i}", "why": "w", "link": "l"} for i in range(60)]
    days = [{"title": f"Deadline {i}", "date": "2026-09-27", "hard": True, "link": "l"} for i in range(60)]
    today = [{"title": f"Today {i}", "link": "l"} for i in range(60)]
    for project in ("a", "b", "c"):
        _feed(tmp_path, project, where=f"projects/{project}/state/home-feed.json", needs=rows, deadlines=days, today=today)
    md, _ = _home(tmp_path)
    assert len(md.splitlines()) <= 150 and md.splitlines()[-1].startswith("last sweep")


