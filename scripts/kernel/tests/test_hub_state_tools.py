"""lane_state.py, hub_events.py and token_ledger.py: the small deterministic meters over the hub and the transcripts."""
import json
import subprocess
import sys
from pathlib import Path

import hub_events
import lane_state
import token_ledger

KERNEL = Path(__file__).resolve().parents[1]


def test_lane_state_keeps_newest_identity_and_live(tmp_path, monkeypatch):
    monkeypatch.setattr(lane_state, "LANES", tmp_path)
    (tmp_path / "X.md").write_text("## Identity\nold\n## 2026-10-05 PARKED\nfirst\n## Identity\nnew\n"
                                   "## 2026-10-06 post\nwork\n## 2026-10-06 PARKED (R-464)\nlast\n")
    s = lane_state.state("X")
    assert "new" in s and "old" not in s
    assert "last" in s and "first" not in s
    assert s.startswith("<!-- GENERATED by scripts/kernel/lane_state.py from hub/lanes/X.md")


def test_lane_state_cli_writes_state_next_to_the_log(tmp_path):
    lanes = tmp_path / "lanes"
    lanes.mkdir()
    (lanes / "HUNT.md").write_text("## Identity 2026-10-01\nme\n## 2026-10-02 HANDOFF\nfiles\n")
    (lanes / "HUNT-ORDERS.md").write_text("# §1 first\nbody one\n# §2 second\nbody two\n")
    done = subprocess.run([sys.executable, str(KERNEL / "lane_state.py"), "HUNT", "--write", "--quiet", "--hub", str(tmp_path)],
                          capture_output=True, text=True, env={"PATH": "/usr/bin:/bin", "PYTHONDONTWRITEBYTECODE": "1"})
    assert done.returncode == 0 and done.stdout == ""
    state = (lanes / "HUNT-STATE.md").read_text()
    assert "me" in state and "HANDOFF" in state and "§2 second" in state
    assert "ORDERS" in state and (lanes / "HUNT.md").read_text().startswith("## Identity")     # the log is never touched


def test_events_feed_scopes_and_renders_signal(tmp_path):
    hub_events.append(tmp_path, ["ALL"], "all lanes park", ts="2026-10-07T08:00+0000")
    hub_events.append(tmp_path, ["APPLY"], "apply only", ts="2026-10-07T09:00+0000")
    hub_events.append(tmp_path, ["FOCUSED"], "focused only", ts="2026-10-07T10:00+0000")
    got = [e["text"] for e in hub_events.for_lane(hub_events.load(tmp_path), "apply")]
    assert got == ["all lanes park", "apply only"]
    sig = hub_events.render(tmp_path).read_text()
    assert sig.startswith("<!-- GENERATED by scripts/kernel/hub_events.py") and "focused only" in sig


def test_events_cli_adds_and_lists_since(tmp_path):
    def run(*args):
        return subprocess.run([sys.executable, str(KERNEL / "hub_events.py"), *args, "--hub", str(tmp_path)],
                              capture_output=True, text=True, env={"PATH": "/usr/bin:/bin", "PYTHONDONTWRITEBYTECODE": "1"})

    added = run("add", "--scope", "APPLY", "--text", "Parked for the night", "--where", "hub/ORCHESTRATOR.md")
    assert added.returncode == 0 and "Parked for the night" in added.stdout
    assert (tmp_path / "SIGNAL.md").is_file() and (tmp_path / "events.jsonl").is_file()
    assert "Parked for the night" in run("since", "--lane", "APPLY", "--hours", "1").stdout
    assert "Parked for the night" not in run("since", "--lane", "HUNT", "--hours", "1").stdout


def test_ledger_dedupes_streamed_request_and_reads_subagents(tmp_path):
    u = {"input_tokens": 2, "cache_read_input_tokens": 100, "cache_creation_input_tokens": 10, "output_tokens": 5}
    line = lambda out: json.dumps({"requestId": "r1", "message": {"model": "m", "usage": {**u, "output_tokens": out}}})
    (tmp_path / "s1.jsonl").write_text(line(1) + "\n" + line(5) + "\n")
    sub = tmp_path / "s1" / "subagents"
    sub.mkdir(parents=True)
    (sub / "agent-a.jsonl").write_text(line(3).replace("r1", "r2") + "\n")
    (sub / "agent-a.meta.json").write_text(json.dumps({"agentType": "resume-tailor"}))
    rows = token_ledger.ledger(tmp_path)
    assert rows[("s1", "main", "m")]["calls"] == 1 and rows[("s1", "main", "m")]["out"] == 5
    assert rows[("s1", "resume-tailor", "m")]["cr"] == 100


