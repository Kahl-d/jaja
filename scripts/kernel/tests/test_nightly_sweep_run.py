"""nightly_sweep.py: watchdog, sweep, lint and sync --check in one command, with the routine's receipt."""
from pathlib import Path

import nightly_sweep
import sync

ROUTINE = ("name: {name}\npurpose: Test.\nruns_on: desktop\nengine: script\nschedule: \"{schedule}\"\n"
           "action: script:scripts/x.py\ntier: T1\nenabled: true\nowner: ops-watchdog\nlast_reviewed: 2026-09-20\n")
NOW = "2026-09-25T06:30:05"


def receipt(root: Path) -> str:
    return (root / "logs" / "runs" / "nightly-sweep" / "2026-09-25.md").read_text(encoding="utf-8")


def clean(repo: Path) -> Path:
    sync.main(repo)
    return repo


def test_a_clean_night_rebuilds_the_briefing_and_leaves_an_ok_receipt(repo, capsys):
    clean(repo)
    assert nightly_sweep.main(["--root", str(repo), "--now", NOW]) == 0
    assert (repo / "HOME.md").read_text(encoding="utf-8").startswith("<!-- GENERATED by scripts/kernel/sweep.py")
    text = receipt(repo)
    assert "## Run 2026-09-25T06:30:05" in text and " · ok" in text and "- sentinel: NO_ACTION" in text
    for step in ("- watchdog: state IDLE", "- sweep: HOME.md", "- lint: clean", "- sync --check: adapters up to date"):
        assert step in text, step
    assert "nightly-sweep: ok" in capsys.readouterr().out


def test_findings_and_silent_routines_make_it_warn_and_the_briefing_counts_the_alert(repo):
    clean(repo)
    (repo / "routines" / "morning-brief.yaml").write_text(ROUTINE.format(name="morning-brief", schedule="0 7 * * *"), encoding="utf-8")
    (repo / "work" / "tasks" / "T-2026-0001-bad.md").write_text(
        "---\nid: T-2026-0001\ntitle: Bad\ntype: task\nstatus: someday\nowner: owner\npriority: P1\n"
        "created: 2026-09-25\nupdated: 2026-09-25\n---\n", encoding="utf-8")
    assert nightly_sweep.main(["--root", str(repo), "--now", NOW]) == 1
    text = receipt(repo)
    assert " · warn" in text and "- sentinel: NEEDS_YOU" in text
    assert "morning-brief SILENT" in text and "- lint: 1 finding(s)" in text
    assert (repo / "work" / "inbox" / "2026-09-25-watchdog-morning-brief.md").is_file()
    assert "- 1 item(s) in `work/inbox/`" in (repo / "HOME.md").read_text(encoding="utf-8")


def test_a_step_that_raises_is_recorded_and_the_rest_still_run(repo, monkeypatch):
    clean(repo)

    def boom(root):
        raise RuntimeError("lint exploded")

    monkeypatch.setattr(nightly_sweep.lint, "run", boom)
    assert nightly_sweep.main(["--root", str(repo), "--now", NOW]) == 1
    text = receipt(repo)
    assert " · failed" in text and "- lint: failed: RuntimeError: lint exploded" in text
    assert "- sync --check: adapters up to date" in text and (repo / "HOME.md").is_file()


def test_adapter_drift_makes_it_warn(repo):
    clean(repo)
    agent = repo / ".claude" / "agents" / "researcher.md"
    agent.write_text(agent.read_text(encoding="utf-8") + "hand edit\n", encoding="utf-8")
    assert nightly_sweep.main(["--root", str(repo), "--now", NOW]) == 1
    assert "- sync --check: 1 file(s) drifted" in receipt(repo)


def test_no_receipt_flag_leaves_no_receipt(repo):
    clean(repo)
    assert nightly_sweep.main(["--root", str(repo), "--now", NOW, "--no-receipt"]) == 0
    assert not (repo / "logs" / "runs" / "nightly-sweep").exists()
