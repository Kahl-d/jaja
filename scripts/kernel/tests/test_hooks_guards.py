def test_every_hook_in_hooks_json_exists_and_every_hook_file_is_listed():
    data = json.loads((HOOKS / "hooks.json").read_text(encoding="utf-8"))
    listed = {Path(h["command"].split("/hooks/")[1].rstrip('"')).name for groups in data["hooks"].values() for g in groups for h in g["hooks"]}
    present = {p.name for p in HOOKS.glob("*.py") if p.name not in {"lane_common.py", "rulings_common.py"}}
    assert listed == present and all((HOOKS / n).is_file() for n in listed)
