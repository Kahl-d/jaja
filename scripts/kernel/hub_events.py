#!/usr/bin/env python3
"""hub_events.py - the hub's event feed: one JSON line per ruling, park, go or order change, and SIGNAL.md made from it.

Why: every lane was told to re-read hub/SIGNAL.md (a long file, a few hundred bytes current) at every phase
boundary, gate and blocking question, and at the end of every turn. Now ORCH or the Recruiter appends an event; the SessionStart hook (lane_context.py) prints only the
events for the lane since its last STATE refresh; a lane checks for new ones with one cheap command when it claims
work. SIGNAL.md stays as a view (generated from the last events) for humans and for old habits.

  <hub>/events.jsonl   {"ts": "2026-01-15T09:12-07:00", "scope": ["ALL"] | ["APPLY", ...], "text": "...",
                        "where": "path or K-id", "by": "ORCH"}   append-only

Usage:
  python3 scripts/kernel/hub_events.py add --scope ALL --text "Parked for the night" --where ORCHESTRATOR.md
  python3 scripts/kernel/hub_events.py since --lane APPLY [--after 2026-01-15T08:00] [--hours 72] [--max 8]
  python3 scripts/kernel/hub_events.py render        # rewrite SIGNAL.md from the feed
  python3 scripts/kernel/hub_events.py seed          # one-time: events from the tables of an archived SIGNAL.md
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
import agency_paths as _ap  # noqa: E402
ROOT = _ap.CODE_ROOT
DEFAULT_HUB = _ap.DATA_ROOT / "hub"                    # the hub is data: your events, rulings, lane logs
RENDER_N = 12


def now_iso() -> str:
    return dt.datetime.now().astimezone().strftime("%Y-%m-%dT%H:%M%z")


def parse_ts(s: str) -> dt.datetime:
    s = s.strip()
    for fmt in ("%Y-%m-%dT%H:%M%z", "%Y-%m-%dT%H:%M:%S%z", "%Y-%m-%dT%H:%M", "%Y-%m-%d %H:%M", "%Y-%m-%d"):
        try:
            d = dt.datetime.strptime(s, fmt)
            return d if d.tzinfo else d.astimezone()
        except ValueError:
            continue
    raise ValueError(f"unreadable time {s!r}")


def load(hub: Path) -> list[dict]:
    p = hub / "events.jsonl"
    out = []
    if p.is_file():
        for line in p.read_text(encoding="utf-8").splitlines():
            try:
                e = json.loads(line)
                e["_t"] = parse_ts(e["ts"])
                out.append(e)
            except (ValueError, KeyError):
                continue
    return out


def append(hub: Path, scope: list[str], text: str, where: str = "", by: str = "ORCH", ts: str | None = None) -> dict:
    e = {"ts": ts or now_iso(), "scope": [s.upper() for s in scope] or ["ALL"], "text": " ".join(text.split()),
         "where": where, "by": by}
    with (hub / "events.jsonl").open("a", encoding="utf-8") as fh:
        fh.write(json.dumps(e, ensure_ascii=False) + "\n")
    return e


def for_lane(events: list[dict], lane: str | None, after: dt.datetime | None = None) -> list[dict]:
    lane = (lane or "").upper()
    keep = [e for e in events if "ALL" in e["scope"] or (lane and lane in e["scope"])]
    if after:
        keep = [e for e in keep if e["_t"] > after]
    return sorted(keep, key=lambda e: e["_t"])


def line(e: dict) -> str:
    where = f" ({e['where']})" if e.get("where") else ""
    return f"- {e['ts'][:16].replace('T', ' ')} [{','.join(e['scope'])}] {e['text']}{where}"


def render(hub: Path) -> Path:
    events = sorted(load(hub), key=lambda e: e["_t"], reverse=True)[:RENDER_N]
    rows = [f"| {e['ts'][:16].replace('T', ' ')} | {', '.join(e['scope'])} | {e['text']} | {e.get('where', '')} |"
            for e in events]
    text = "\n".join([
        "<!-- GENERATED by scripts/kernel/hub_events.py from hub/events.jsonl - do not edit; add an event instead -->",
        "# SIGNAL (the last events)", "",
        "The feed is `hub/events.jsonl`. Your start hook prints the events for your lane since your last STATE refresh;",
        "check for new ones when you claim work: `python3 scripts/kernel/hub_events.py since --lane <LANE> --hours 24`.",
        "Older signal tables: `hub/archive/SIGNAL-before-feed.md`.", "",
        "| when | scope | what changed | where |", "|---|---|---|---|", *rows, ""])
    (hub / "SIGNAL.md").write_text(text, encoding="utf-8")
    return hub / "SIGNAL.md"


SECTION = re.compile(r"^## (?:LAST|PREVIOUS) UPDATE (\d{4}-\d{2}-\d{2})(?: (\d{1,2}:\d{2}))?", re.M)


def seed(hub: Path, source: Path) -> int:
    """Events from the tables of an archived SIGNAL.md (each row of each UPDATE section), oldest first."""
    text = source.read_text(encoding="utf-8")
    marks = list(SECTION.finditer(text))
    found = []
    for i, m in enumerate(marks):
        body = text[m.end(): marks[i + 1].start() if i + 1 < len(marks) else len(text)]
        ts = f"{m.group(1)}T{(m.group(2) or '00:00').zfill(5)}"
        for row in re.findall(r"^\|(.+)\|\s*$", body, re.M):
            cells = [c.strip() for c in row.split("|")]
            if len(cells) < 2 or cells[0].lower() in ("scope", "---") or set(cells[0]) <= {"-", " "}:
                continue
            scope = [s.strip().upper() for s in re.split(r"[,/+ ]+", cells[0]) if s.strip()]
            found.append((ts, scope, cells[1], cells[2] if len(cells) > 2 else ""))
    for ts, scope, what, where in sorted(found, key=lambda x: x[0]):
        append(hub, scope, what, where, by="ORCH (seeded from SIGNAL.md)", ts=parse_ts(ts).strftime("%Y-%m-%dT%H:%M%z"))
    return len(found)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("cmd", choices=["add", "since", "render", "seed"])
    ap.add_argument("--hub", type=Path, default=DEFAULT_HUB)
    ap.add_argument("--scope", nargs="*", default=["ALL"])
    ap.add_argument("--text", default="")
    ap.add_argument("--where", default="")
    ap.add_argument("--by", default="ORCH")
    ap.add_argument("--lane")
    ap.add_argument("--after")
    ap.add_argument("--hours", type=float, default=72)
    ap.add_argument("--max", type=int, default=8)
    ap.add_argument("--source", type=Path)
    a = ap.parse_args(argv)
    if a.cmd == "add":
        if not a.text:
            ap.error("add needs --text")
        print(line(append(a.hub, a.scope, a.text, a.where, a.by)))
        render(a.hub)
        return 0
    if a.cmd == "render":
        print(render(a.hub))
        return 0
    if a.cmd == "seed":
        n = seed(a.hub, a.source or a.hub / "archive" / "SIGNAL-before-feed.md")
        render(a.hub)
        print(f"seeded {n} events")
        return 0
    after = parse_ts(a.after) if a.after else dt.datetime.now().astimezone() - dt.timedelta(hours=a.hours)
    rows = for_lane(load(a.hub), a.lane, after)
    for e in rows[-a.max:]:
        print(line(e))
    if len(rows) > a.max:
        print(f"- ({len(rows) - a.max} older in hub/events.jsonl)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
