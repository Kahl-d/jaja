def hooks_block() -> str:
    hj = json.loads((ROOT / "hooks" / "hooks.json").read_text(encoding="utf-8"))
    rows = []
    for event, groups in hj["hooks"].items():
        for g in groups:
            for h in g["hooks"]:
                name = re.search(r"hooks/([\w]+\.py)", h["command"]).group(1)
                rows.append([event, g.get("matcher") or "any", f"`{name}`", HOOK_NOTE.get(name) or doc1(ROOT / "hooks" / name)])
    helpers = sorted(p.name for p in (ROOT / "hooks").glob("*.py") if p.name not in {r[2].strip("`") for r in rows})
    return details(f"Hooks ({len({r[2] for r in rows})} guards)",
                   table(["Event", "Matcher", "Hook", "Enforces"], rows) + "\n\nShared helpers: " + ", ".join(f"`{h}`" for h in helpers) +
                   ". The list is `hooks/hooks.json`; `sync.py` merges it into `.claude/settings.json` and `.codex/hooks.json`.")


def scripts_block() -> str:
    allp = {p.stem: p for p in sorted((ROOT / "scripts").glob("*.py"))}
    used: set[str] = set()
    parts = []
    for title, blurb, names in STAGES:
        rows = [[f"`{n}.py`", doc1(allp[n])] for n in names if n in allp]
        used |= {n for n in names if n in allp}
        parts.append(f"**{title}** ({blurb})\n\n" + table(["Script", "What it does"], rows))
    other = [n for n in allp if n not in used and n not in {"__init__"}]
    parts.append("**Other scripts**\n\n" + table(["Script", "What it does"], [[f"`{n}.py`", doc1(allp[n])] for n in other]))
    kern = sorted((ROOT / "scripts" / "kernel").glob("*.py"))
    parts.append("**Kernel** (`scripts/kernel/`: adapters, lint, approvals, hub tools, receipts)\n\n" +
                 table(["Script", "What it does"], [[f"`{p.name}`", doc1(p)] for p in kern]))
    n = len(allp) + len(kern)
    return details(f"Deterministic scripts by stage ({n} scripts)",
                   "Scripts count, gate, render, track and check; they never call a model. Cards and skills call them.\n\n" + "\n\n".join(parts))


def skills_block() -> str:
    rows = []
    for p in sorted((ROOT / "skills").glob("*/SKILL.md")):
        rows.append([f"`{p.parent.name}`", sentence(front(p).get("description"), 150)])
    return details(f"Skills ({len(rows)}): invoked as `/jaja:<skill>`", table(["Skill", "Use it when"], rows))


