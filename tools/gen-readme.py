def mcp_block() -> str:
    tree = ast.parse((ROOT / "mcp" / "job_search_mcp" / "server.py").read_text(encoding="utf-8"))
    read, write = [], []
    for node in tree.body:
        if isinstance(node, ast.FunctionDef):
            for dec in node.decorator_list:
                if isinstance(dec, ast.Call) and getattr(dec.func, "id", "") == "_tool" and dec.args:
                    kind = dec.args[0].value
                    first = (ast.get_docstring(node) or "").splitlines()[0].strip().rstrip(".") if ast.get_docstring(node) else ""
                    (read if kind == "read" else write).append([f"`{node.name}`", kind, first[:120]])
    return details(f"MCP server: {len(read) + len(write)} tools ({len(read)} read, {len(write)} write; none sends)",
                   "Run with `uv run --directory mcp job-search-mcp`; registered in `.mcp.json`. Text from postings and mail comes back inside "
                   "`<untrusted_*>` tags and is data, never instructions.\n\n" + table(["Tool", "Kind", "What it does"], read + write))


