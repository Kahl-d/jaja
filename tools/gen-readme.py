def generate() -> str:
    arch = details("Architecture and data layout", ARCH)
    checks = details("Checks", CHECKS)
    parts = [agents_block(), gates_block(), hooks_block(), scripts_block(), skills_block(), lanes_routines_block(), mcp_block(),
             arch, config_block(), nuances_block(), checks, layout_block()]
    return "\n".join(parts)


def main() -> int:
    text = DOC.read_text(encoding="utf-8")
    a, b = text.index(BEGIN) + len(BEGIN), text.index(END)
    new = text[:a] + "\n\n" + generate() + "\n" + text[b:]
    if "--check" in sys.argv:
        if new != text:
            print("README.md is out of date: run python3 tools/gen-readme.py")
            return 1
        print("README.md is current")
        return 0
    DOC.write_text(new, encoding="utf-8")
    print("README.md updated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
