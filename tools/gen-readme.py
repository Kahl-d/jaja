def config_block() -> str:
    merged: dict = {}
    for f in sorted((ROOT / "config" / "defaults.d").glob("*.yaml")):
        d = yaml.safe_load(f.read_text(encoding="utf-8")) or {}
        for sec, val in d.items():
            if isinstance(val, dict):
                merged.setdefault(sec, {})
                for k, v in val.items():
                    merged[sec].setdefault(k, set())
                    if isinstance(v, dict):
                        merged[sec][k] |= set(v)
    rows = []
    for sec in ("identity", "style", "policy"):
        subs = merged.get(sec, {})
        rows.append([f"`{sec}`", str(len(subs)), ", ".join(f"`{k}`" + (f" ({len(v)})" if v else "") for k, v in sorted(subs.items()))])
    return details("Configuration keys", "Every key the code reads has a neutral default in `config/defaults.d/*.yaml`; override any of them in "
                   "`<data>/config/*.yaml` (files merge in name order). Number in brackets: sub-keys.\n\n" +
                   table(["Section", "Keys", "Names"], rows))


def nuances_block() -> str:
    text = (ROOT / "docs" / "NUANCES.md").read_text(encoding="utf-8")
    body = text.split("\n", 3)[-1] if text.startswith("#") else text
    body = re.sub(r"^# .*\n", "", text, count=1).replace("\n## ", "\n#### ").replace("\n# ", "\n### ")
    return details("Design nuances and the code that enforces each", body.strip())


