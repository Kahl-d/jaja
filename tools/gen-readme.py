def front(path: Path) -> dict:
    m = re.match(r"---\n(.*?)\n---", path.read_text(encoding="utf-8"), re.S)
    try:
        return yaml.safe_load(m.group(1)) if m else {}
    except yaml.YAMLError:
        return {}


def doc1(path: Path, limit: int = 115) -> str:
    try:
        d = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or ""
    except SyntaxError:
        return ""
    lines = [x.strip() for x in d.splitlines() if x.strip()]
    s = re.sub(r"^[\w.\-]+\.py\s*[:\-–—]+\s*", "", lines[0]) if lines else ""
    s = " ".join(s.split()).rstrip(".")
    if len(s) > limit:
        s = s[:limit].rsplit(" ", 1)[0].rstrip(",;:(") + " ..."
    return s


def sentence(text: object, limit: int = 140) -> str:
    s = " ".join(str(text or "").split())
    m = re.match(r"(.+?[.;])(\s|$)", s)
    if m and len(m.group(1)) >= 25:
        s = m.group(1)
    s = s.rstrip(".;")
    if len(s) > limit:
        s = s[:limit].rsplit(" ", 1)[0].rstrip(",;:(") + " ..."
    return s


def cell(x: object) -> str:
    return str(x).replace("|", "\\|")


def table(head: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" for _ in head) + "|"]
    return "\n".join(out + ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows])


def details(title: str, body: str, open_: bool = False) -> str:
    return f"<details{' open' if open_ else ''}>\n<summary><b>{title}</b></summary>\n\n{body.strip()}\n\n</details>\n"


def agents_block() -> str:
    rows = []
    for p in sorted((ROOT / "agents").glob("*.md")):
        m = front(p)
        rows.append([f"`{p.stem}`", sentence(m.get("purpose") or m.get("description")), m.get("tier_max", ""), m.get("model", "")])
    return details(f"Agents ({len(rows)}): what each does, its tier cap and model",
                   "Each card in `agents/` states purpose, allowed tools, `tier_max` (T0 read to T4 forbidden), model, effort, budget, "
                   "KPIs, stop conditions and denied commands.\n\n" + table(["Agent", "What it does", "Max tier", "Model"], rows))


